import type { GearMods } from './gear';
import type { HeroLoadout } from './heroes';
import type { ConsumableId } from './consumables';
import type { BattleState } from './battle';
import type { ResourceKind, Resources } from './resources';
import type { Stone } from './stones';

export type Tier = 0 | 1 | 2 | 3;

export interface Cell {
  readonly x: number;
  readonly z: number;
}

/**
 * Три типа противника (§15). Идентификаторы — имена моделей набора KayKit
 * (`Skeleton_Minion`, `Skeleton_Warrior`, `Skeleton_Mage`), и это не описка:
 * называть тип тем, что игрок видит, честнее, чем придумывать породу.
 *
 * **Слова временные, см. §0.1 и §15.** Ни одно решение на них не опирается.
 */
/**
 * Кто участвует в бюджете ран яруса (§22). Трое, и все трое — скелеты (§15):
 * это отдельное имя, а не синоним `EnemyKind`, потому что цена присутствия
 * меряется ботом только у них. Привидение в ярусах не спавнится вовсе,
 * и приписывать ему измеренное число было бы враньём про замер.
 */
export type RaidEnemyKind = 'minion' | 'warrior' | 'mage';

/** Все, кого умеет вести бой: трое ярусных и обитатель кладбища (§6.1.7). */
export type EnemyKind = RaidEnemyKind | 'ghost';

/** §15 — три типа, по одному на диапазон ярусов, различимы силуэтом. */
export interface EnemyStats {
  readonly kind: EnemyKind;
  readonly name: string;
  /** §11.3 — стойкость в очках, а не в ранах. Ранами считается только герой:
   *  их видно на экране, и они обязаны быть целыми. */
  readonly hp: number;
  /** §11.3 — входит в урон по герою через пробой. Единственная ручка
   *  «насколько больно бьёт этот тип». */
  readonly attack: number;
  readonly speed: number;
  /** §17.3 — длительность замаха. Нижняя граница осознанной реакции. */
  readonly telegraph: number;
  readonly attackInterval: number;
  readonly reach: number;
  readonly chases: boolean;
  /** §15 — стреляет ли. У стрелка `reach` означает дальность выстрела,
   *  а не длину оружия, и подходить он не обязан вовсе. */
  readonly ranged: boolean;
  /** Клеток в секунду. Ноль у ближних. */
  readonly projectileSpeed: number;
}

/**
 * §11.3 — снаряд как сущность состояния, а не картинка.
 *
 * Он летит, и урон применяется в момент попадания, а не выстрела. Иначе
 * рендер завёл бы собственный снаряд, и стрела оказывалась бы в воздухе,
 * когда противник уже упал, — те самые два источника правды, которых
 * симуляция избегает везде.
 *
 * Отсюда же берётся единственная честная вариативность, доступная
 * детерминированному шагу: **промах позиционный**. Цель ушла с линии,
 * пока снаряд летел, — и это решение игрока, а не бросок кубика.
 */
export interface Projectile {
  readonly id: number;
  readonly from: 'hero' | 'enemy';
  x: number;
  z: number;
  /** Для интерполяции в рендере — как у героя и противника. */
  prevX: number;
  prevZ: number;
  /** Куда целились в момент выстрела. Не самонаведение: уйти с линии обязано
   *  быть возможно, иначе промаха не существует. */
  readonly aimX: number;
  readonly aimZ: number;
  readonly speed: number;
  /** Что применить при попадании: очки стойкости или Атака бьющего. */
  readonly power: number;
  /** По кому летит. Для снаряда врага — по герою. */
  readonly targetId: number;
  /** Кто выпустил — нужно атрибуции провала (§9). */
  readonly kind: EnemyKind | null;
}

export interface Enemy {
  readonly id: number;
  readonly kind: EnemyKind;
  x: number;
  z: number;
  prevX: number;
  prevZ: number;
  hp: number;
  awake: boolean;
  /** Секунды до конца замаха; 0 — замаха нет. */
  telegraph: number;
  cooldown: number;
}

export interface Container {
  readonly id: number;
  readonly x: number;
  readonly z: number;
  readonly amount: number;
  /** §13 — что именно лежит: вид выпадает по ярусу, а не по контейнеру. */
  readonly kind: ResourceKind;
  opened: boolean;
}

export interface GameLocation {
  readonly seed: number;
  readonly tier: Tier;
  readonly size: number;
  readonly blocked: Uint8Array;
  readonly evac: Cell;
  readonly containers: Container[];
  /**
   * Валуны на проходимых клетках (§13.4). Клетку не занимают: по камню
   * по колено ходят, и путь назад от него не меняется — иначе разбитый
   * валун пересчитывал бы карту, как просека (§13.3), а он не проход
   * открывает, а даёт камень.
   */
  readonly stones: Stone[];
  readonly enemies: Enemy[];
  /** §11.1 «путь назад»: длина кратчайшего пути до выхода, в шагах. */
  readonly backSteps: Int32Array;
}

/**
 * Боец отряда (§11.7).
 *
 * Всё, что делает его собой, лежит здесь, а не на вылазке: класс, снаряжение,
 * колчан и **личный запас хода** (§11.9а). Общий котёл на троих — это тот же
 * одиночный герой с шестью руками: состав отряда на глубину не влияет,
 * и решение «кого вести» исчезает.
 *
 * Пока боец один, разница не видна — и это правильная проверка: замена
 * представления обязана оставить золотой мастер неподвижным.
 */
export interface Fighter {
  readonly id: number;
  /** Кем идёт: класс, Атака, Защита, Знание, умение (§11.7). */
  readonly loadout: HeroLoadout;
  /** С чем идёт: снаряжение, свёрнутое в числа на входе (§14). */
  readonly mods: GearMods;
  x: number;
  z: number;
  prevX: number;
  prevZ: number;
  facing: number;
  /**
   * §11.3 — здоровье. Обычная шкала, а не целые раны.
   *
   * Ранами оно было три версии раздела подряд, и держалось это на доводе
   * «целое читается мгновенно на маленьком экране». Довод верный, но цена
   * оказалась выше: при трёх ранах любой удар — это треть жизни, Защита
   * не может смягчить его иначе как порогом, а порог либо не переходится
   * вовсе, либо переходится сразу вдвое.
   *
   * На шкале урон делится плавно, и формула раздела наконец работает так,
   * как написана: урон = Атака минус половина Защиты.
   */
  hp: number;
  readonly hpMax: number;
  cooldown: number;
  /** §14.3 — свой колчан. У ближника вместимость нулевая. */
  arrows: number;
  readonly arrowsMax: number;
  /** §11.9а — свой запас хода. Кухня задаёт не сам запас, а насколько
   *  он больше базового. */
  food: number;
  readonly foodMax: number;
}

/**
 * Тот, кем ведут отряд по локации. Оставлен отдельным именем, а не заменён
 * на `party[active]`, потому что вне боя вопросов «чей обзор» и «чей путь
 * назад» быть не должно: их задаёт ведущий, и §11.4 с §11.1 остаются
 * на одном сравнении.
 *
 * Это тот же объект, что в `party`, а не его копия: правка через любое
 * из двух имён меняет одно и то же.
 */
export type Hero = Fighter;


export type RaidStatus = 'running' | 'evacuated' | 'failed';

export interface RaidState {
  readonly loc: GameLocation;
  /**
   * §11.7 — отряд. Вне боя идёт одной фишкой за ведущим; в бою распадается
   * по гексам (§11.3). В бой втягиваются только те, кто рядом, — остальные
   * подходят и вступают позже.
   */
  readonly party: Fighter[];
  /** Кем ведут отряд. Индекс в `party`. */
  active: number;
  /**
   * §11.7 — след ведущего, свежий первым. Остальные идут по нему, а не рядом
   * с ним: так они обходят те же камни и не застревают в стене, которую
   * ведущий обогнул.
   */
  readonly trail: { x: number; z: number }[];
  /**
   * Ведущий: тот же объект, что `party[active]`, а не копия. Отдельное имя
   * оставлено затем, что вне боя вопросов «чей обзор» и «чей путь назад»
   * быть не должно — их задаёт ведущий (§11.4, §11.1).
   */
  hero: Hero;
  /** Кем идём (§11.7). Вылазка знает о герое ровно это и ничего про лечение. */
  readonly loadout: HeroLoadout;
  /** §14 — снаряжение, свёрнутое в числа на входе. Внутри вылазки не меняется:
   *  перековаться посреди тракта нельзя, и это не упущение, а правило. */
  readonly mods: GearMods;
  /** §11.7 — умение применяется один раз за вылазку, отката нет. */
  skillUsed: boolean;
  /** Сколько секунд умение ещё действует. 0 — не действует. */
  skillLeft: number;
  /**
   * Провиант отряда — сумма личных запасов (§11.9а). Читается полосой HUD
   * и списывается шагом у каждого бойца, а не из общего котла: иначе состав
   * отряда на дальность не влияет, и «кого вести» перестаёт быть решением.
   */
  food: number;
  /** Потолок — тоже сумма: полоса показывает отряд, а не ведущего. */
  readonly foodMax: number;
  /** Рюкзак по видам: на экране возврата ресурсы зачисляются как есть. */
  bag: Resources;
  bagTotal: number;
  /** Вместимость Склада на момент выхода (§2). */
  readonly capacity: number;
  path: Cell[];
  status: RaidStatus;
  steps: number;
  /** Дальше всего от выхода, куда игрок заходил (§9: глубина возвращения). */
  maxBack: number;
  /** Секунды в локации — для §17.4 и для телеметрии. */
  elapsed: number;
  /** Секунды без провианта — голод отнимает раны не сразу. */
  starve: number;
  /** Цена вскрытия контейнера. Обычно `FOOD_COST.container`, в прологе ноль. */
  readonly containerFood: number;
  /** Грызёт ли голод раны на нуле провианта. В прологе — нет. */
  readonly hunger: boolean;
  /**
   * Рубится ли здесь лес (§13.3). Свойство локации, а не рендера: занятая
   * клетка поляны — дерево, занятая клетка вылазки — камень, и топор
   * ко второму не относится.
   */
  readonly logging: boolean;
  /** Называет ли событие подбора ставку. В прологе — нет: терять там нечего,
   *  а ставку вводит кадр `bait` первой вылазки. */
  readonly risk: boolean;
  /**
   * Событие локации (§11.6), объявленное до входа. Три поля, а не ссылка
   * на событие: вылазке незачем знать, как оно называется, — ей нужны числа,
   * ровно как со снаряжением (`mods`).
   */
  /** Слагаемое к доле под угрозой: §11.2 складывает, а не множит. */
  readonly riskAdd: number;
  /** Прибавка к радиусу обзора. */
  readonly visionAdd: number;
  /** Множитель цены шага. Возврат — самая длинная дорога, по нему и бьёт. */
  readonly stepMul: number;
  /** Копится, пока идёт бой: провиант списывается один раз за стычку (§11.1). */
  inFight: boolean;
  /** Взятые в вылазку расходники, ещё не сработавшие (§21).
   *  Имя не loadout: так называется снаряжение героя из §14. */
  consumables: ConsumableId[];
  /** Что сработало — для телеметрии и для гашения слота в HUD. */
  fired: ConsumableId[];
  /** До этой секунды после дыма противники не просыпаются: без передышки
   *  контакт восстановился бы на следующем же тике. */
  smokeUntil: number;
  /** Кто нанёс последний удар — нужен телеметрии и замеру: без атрибуции
   *  «провалы в бою» ничего не говорят о том, что чинить. */
  lastHitBy: EnemyKind | null;
  /**
   * §9 — от чего пришла последняя рана. Прежде причину провала выводил
   * замерный скрипт по правилу «раны кончились раньше провианта», и оно
   * врёт ровно там, где интереснее всего: голодный герой, добитый скелетом,
   * попадал в бой, а раненный в бою и доевший провиант — в голод. Причина
   * записывается в момент раны, потому что только там она известна точно.
   */
  lastWoundFrom: "enemy" | "hunger" | null;
  /** §9 — счётчики боя за вылазку. Пишутся итогом, а не событием на удар:
   *  буфер телеметрии кольцевой, и событие на стычку вымыло бы начало сессии. */
  damageTaken: number;
  /** Стычек за вылазку: считается вход в контакт, а не удар. */
  fights: number;
  /** §11.7 — сколько бойцов суммарно втянулось в бои за вылазку. */
  joined: number;
  /** Противников, упавших за вылазку. */
  kills: number;
  /**
   * Открыт ли выход. Обычно да с первой секунды — «выход всегда доступен
   * одним касанием» (`onboarding.html`, кадр 7). Закрывается он ровно в одном
   * месте: в первой вылазке, пока игрок не взял добычу. Герой стартует на
   * точке выхода, и без этого первый же тап рядом со стартом заканчивал
   * вылазку с пустым рюкзаком — игрок уходил домой, не увидев игры.
   */
  evacOpen: boolean;
  /**
   * §14.3 — стрел в колчане. Тратятся боем, который автоматичен (§11.3):
   * кнопки выстрела нет, приберечь физически невозможно, и решение,
   * которое стрелы создают, лежит перед боем — «ввязываться ли».
   */
  arrows: number;
  /** Вместимость: сколько было на выходе и сколько влезает при подборе. */
  readonly arrowsMax: number;
  /** §9 — потрачено за вылазку. Нужно замеру: колчан обязан пустеть
   *  не всегда и не никогда. */
  arrowsSpent: number;
  /** Стычек, проведённых с пустым колчаном, — цена сухого боя. */
  dryFights: number;
  /**
   * §11.3 — идущий бой. Пока он не null, мир стоит: шаги не делаются,
   * провиант за шаг не тратится, снаряды не летят. Время останавливается
   * целиком, а не «замедляется» — иначе получилось бы два хода часов.
   */
  battle: BattleState | null;
  /** Раунд, за который провиант уже списан: раунд стоит еды, но один раз. */
  paidRound: number;
  /** §11.3 — снаряды в полёте. Пустой массив у локации без стрелков. */
  projectiles: Projectile[];
  nextProjectileId: number;
  /** Реплики для HUD — то, что игрок должен заметить в этот тик. */
  events: string[];
}
