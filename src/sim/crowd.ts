/**
 * Тела не проходят сквозь тела. Базовая механика любого NPC: где бы человек
 * ни считался — обходом гарнизона, кругом жильца, погоней противника, —
 * он занимает место, и второй в это место не встаёт.
 *
 * **Почему отдельным модулем, а не в каждом на месте.** Способов считать
 * движение в игре три и они разные: обход — функция времени, круг жильца —
 * функция времени со стоянками, погоня — шаг за кадр. Общего у них ровно
 * одно: на выходе получается кадр с людьми в клетках. Разведение и работает
 * с кадром, поэтому оно одно на все три, а не переписано трижды.
 *
 * **Кадр остаётся функцией времени.** Расчёт идёт от положений на этот кадр
 * и ничего не хранит: `patrolAt(g, t)` и `dwellersAt(g, t)` при одном `t`
 * дают то же самое, сколько бы раз их ни позвали, и отладочная перемотка
 * по-прежнему собирает кадр из ничего. Разведение с памятью — накопленный
 * толчок, инерция — эту опору выбило бы, поэтому его здесь нет.
 */

/**
 * Ширина фигуры в клетках: ближе этого двое не сходятся. Снято с модели
 * набора — корпус 0,79 единицы при росте 2,54, — приведено к росту человека
 * в игре (1,38) и округлено вверх до 0,45.
 *
 * Число одно на всех, и это решение: скелет, рыцарь и жилец занимают
 * одинаковое место, потому что и рисуются они одного роста (§6.1.6).
 */
export const BODY = 0.45;

/** Тот, кого разводят: всё, у чего есть место в клетках. */
export interface Body {
  x: number;
  z: number;
}

/** Чем настроить разведение. Всё необязательное: по умолчанию двигают всех. */
export interface Apart {
  /** Можно ли стоять в точке. Без неё сдвиг применяется всегда. */
  readonly free?: (x: number, z: number) => boolean;
  /** Кого не двигают — по номеру в списке. Такой один на локацию: торговец. */
  readonly fixed?: (i: number) => boolean;
  readonly rounds?: number;
}

/**
 * Развести сошедшихся ближе `BODY`.
 *
 * **Потолка на сдвиг нет, и это решение.** Сначала он был: казалось разумным
 * не двигать человека больше чем на столько-то за кадр. Вышло наоборот —
 * там, где потолка не хватало развести, разведение не доводило дело до конца,
 * на следующем кадре бралось за него снова с другой стороны, и человек
 * дрожал. Без потолка сдвиг заканчивается за один-два прохода и сам собой
 * ограничен половиной ширины тела (0,22 клетки; 0,45, если второй неподвижен),
 * то есть меньше половины клетки — в стену такой сдвиг не выносит.
 *
 * Между кадрами никто не прыгает: сдвиг растёт от нуля вместе с перекрытием,
 * а перекрытие набегает постепенно — люди сходятся шагом, а не рывком.
 *
 * `free` — можно ли стоять в точке. Нужно там, где рядом стена: не прошедший
 * проверку сдвиг просто не применяется, и двое остаются в перекрытии — это
 * честнее, чем человек внутри камня.
 *
 * Два прохода: одного мало, когда трое сошлись в кучу, а больше двух ничего
 * заметно не меняют.
 */
export function keepApart(men: readonly Body[], opts: Apart = {}): void {
  const { free, fixed, rounds = 2 } = opts;
  for (let pass = 0; pass < rounds; pass++) {
    const push = men.map(() => ({ x: 0, z: 0 }));
    for (let i = 0; i < men.length; i++) {
      for (let j = i + 1; j < men.length; j++) {
        const a = men[i]!;
        const b = men[j]!;
        const dx = b.x - a.x;
        const dz = b.z - a.z;
        const d = Math.hypot(dx, dz);
        if (d >= BODY) continue;
        const need = (BODY - d) / 2;
        let sx: number;
        let sz: number;
        if (d < 1e-6) {
          // Совпали точка в точку. Разводить всё равно надо, а направление
          // берётся от номера: любое, лишь бы одно и то же при каждом вызове,
          // иначе кадр перестанет быть функцией времени.
          sx = Math.cos(i * 2.399963);
          sz = Math.sin(i * 2.399963);
        } else {
          sx = dx / d;
          sz = dz / d;
        }
        const ux = sx * need;
        const uz = sz * need;
        const aFixed = fixed?.(i) === true;
        const bFixed = fixed?.(j) === true;
        // Неподвижный не делится сдвигом: его половину забирает подвижный.
        if (!aFixed) {
          push[i]!.x -= bFixed ? ux * 2 : ux;
          push[i]!.z -= bFixed ? uz * 2 : uz;
        }
        if (!bFixed) {
          push[j]!.x += aFixed ? ux * 2 : ux;
          push[j]!.z += aFixed ? uz * 2 : uz;
        }
      }
    }
    for (let i = 0; i < men.length; i++) {
      const p = push[i]!;
      if (Math.hypot(p.x, p.z) < 1e-9) continue;
      const nx = men[i]!.x + p.x;
      const nz = men[i]!.z + p.z;
      if (free !== undefined && !free(nx, nz)) continue;
      men[i]!.x = nx;
      men[i]!.z = nz;
    }
  }
}
