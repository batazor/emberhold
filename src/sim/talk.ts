/**
 * Реплики жильцов: лагерь, в котором иногда говорят.
 *
 * Это речь людей, а не голос игры (§23.1): канал «диалог», как у поселенца
 * в знакомстве, — единственный, где допустимы «ты», точка в конце
 * и вообще характер. Механики в репликах нет ни грамма: реплика ничего
 * не подсказывает, не отказывает и не сообщает — она произносится при
 * игроке, а не адресуется ему. Единственное исключение по содержанию —
 * безкрышный: его строки говорят о палатке, потому что нехватка крыши
 * и без того читается заданием (§16.1), и человек у костра имеет право
 * называть её сам.
 *
 * **Кто говорит и когда — функция времени.** Очередь идёт по кругу:
 * в каждое окно `TALK_GAP` право голоса у одного жильца, и говорит он
 * с начала окна не дольше `TALK_SECONDS` — значит, двое не говорят никогда,
 * сколько бы их ни было, и пузыри не дерутся за кадр. Прозвучит ли реплика
 * вообще, решает сид окна: лагерь, бормочущий без пауз, читался бы
 * заведённой шарманкой, а не людьми.
 */
import { mulberry32, pick } from '../core/rng';
import type { Rng } from '../core/rng';

/**
 * Сколько секунд видна реплика. Ровно срок строки полосы (`BANNER_SECONDS`):
 * читалка у игрока одна, и два разных срока чтения ей ни к чему.
 * Число продублировано, а не импортировано: сим не тянет ui.
 */
export const TALK_SECONDS = 4;

/**
 * Окно одной очереди. Больше двух сроков реплики: пауза обязана быть
 * длиннее речи, иначе тишина перестаёт быть фоном, а речь — событием.
 */
export const TALK_GAP = 9;

/** Доля окон, в которые очередник вправду говорит. */
const TALK_CHANCE = 0.55;

/**
 * О чём человек говорит: его занятие или его положение. «Без крыши»
 * перекрывает занятие — ночующему у костра не до присказок о топоре.
 */
export type TalkMood = 'строим' | 'ходим' | 'кормим' | 'отдых' | 'без крыши';

/**
 * Слова жильцов. Таблица переписана в `voice.rules.ts` каналом «диалог» —
 * заводить строки мимо переписи нельзя (§23), даже человеческие.
 * Ключ — настроение и номер; группы собирает `poolOf` по префиксу.
 */
export const TALK_TEXT: Record<string, string> = {
  'build-1': 'Дерево само себя не принесёт.',
  'build-2': 'Кромка добрая — руби, не кончится.',
  'build-3': 'Ещё охапка — и на палатку хватит.',
  'build-4': 'Топор нынче не тупится.',
  'mine-1': 'Камень внизу, а спина здесь.',
  'mine-2': 'Дорога вниз длинная, зато своя.',
  'mine-3': 'Порода нынче добрая.',
  // §13.8 — добытчик пищи. Говорит о кусте и корзине: это всё, что у него
  // есть, и придумывать ему промысел, которого в игре нет, нельзя (§0.1).
  'pick-1': 'Ягода пошла, только успевай.',
  'pick-2': 'Этот куст обобрали, пусть стоит.',
  'pick-3': 'Полкорзины есть, к вечеру будет полная.',
  'rest-1': 'Хорошо у огня.',
  'rest-2': 'Посидеть — тоже дело.',
  'rest-3': 'Дым глаза ест, а уходить не хочется.',
  'idle-1': 'Славный нынче день.',
  'idle-2': 'Лагерь растёт — глядеть приятно.',
  'idle-3': 'Вечером бы похлёбки.',
  'home-1': 'Палатку бы — под небом спится так себе.',
  'home-2': 'Крыша — не роскошь, а сон.',
  /**
   * Отклики: то, чем разговор отличается от двух присказок рядом. Отклик
   * не о деле, а о собеседнике — он ничего не сообщает и не обязан: его
   * работа в том, чтобы сказанное было услышано. Поэтому он короткий
   * и почти пустой по смыслу, и поэтому же он на «ты»: канал диалога —
   * единственный, где это разрешено (§23.1).
   */
  'reply-1': 'И не говори.',
  'reply-2': 'Твоя правда.',
  'reply-3': 'Это точно.',
  'reply-4': 'Кому ты рассказываешь.',
  'reply-5': 'Вот и я о том же.',
};

const group = (prefix: string): string[] =>
  Object.keys(TALK_TEXT)
    .filter((k) => k.startsWith(prefix))
    .map((k) => TALK_TEXT[k]!);

/**
 * Пул настроения. Общие присказки подмешаны к занятиям и отдыху — люди
 * говорят не только о работе; безкрышному общих не положено: его строки —
 * то самое задание, и разбавлять его погодой значило бы прятать.
 */
const POOLS: Record<TalkMood, readonly string[]> = {
  строим: [...group('build-'), ...group('idle-')],
  ходим: [...group('mine-'), ...group('idle-')],
  // §13.8 — у добытчика свои три присказки: он говорит о том, что делает,
  // как дровосек и камнетёс. Про ягоды и корзину, а не про охоту: охоты
  // в игре нет, и выдумывать её ради строки нельзя (§0.1).
  кормим: [...group('pick-'), ...group('idle-')],
  отдых: [...group('rest-'), ...group('idle-')],
  'без крыши': group('home-'),
};

/** Отклики — общий пул на всех: они не о деле говорящего. */
const REPLIES: readonly string[] = group('reply-');

/** Говорящий: сид лица и о чём ему говорить. */
export interface Talker {
  readonly seed: number;
  readonly mood: TalkMood;
}

/**
 * Реплика жильца `i` на момент `t`; null — молчит. Чистая функция:
 * перемотка времени отдаёт те же слова тем же людям.
 *
 * Это присказка в одиночку — то, что человек говорит при других, а не им.
 * Разговор двоих (`chatAt`) её перебивает: он назначен маршрутами и потому
 * знает своё время, а очередь присказок про него не знает вовсе.
 */
export function phraseAt(folk: readonly Talker[], i: number, t: number): string | null {
  const n = folk.length;
  const who = folk[i];
  if (who === undefined || n === 0) return null;
  const window = Math.floor(t / TALK_GAP);
  if (((window % n) + n) % n !== i) return null;
  if (t - window * TALK_GAP >= TALK_SECONDS) return null;
  // Сид — лицо и номер окна: тот же человек в то же окно говорит то же,
  // а в следующее — своё, не по кругу списка.
  const rng = mulberry32((who.seed ^ Math.imul(window + 1, 0x9e3779b1)) | 0);
  if (rng() > TALK_CHANCE) return null;
  const pool = POOLS[who.mood];
  return pool.length === 0 ? null : pick(rng, pool);
}

/* ---------- разговор двоих ---------- */

/**
 * Реплик в одном разговоре. Четыре, и порядок их не случаен: **мысль —
 * отклик — мысль — отклик**. Каждый говорит своё и слышит чужое, и это
 * единственное, чем обмен отличается от двух присказок, произнесённых
 * рядом. Трёх было бы мало — кто-то остался бы неуслышанным; пять уже
 * держат обоих у костра дольше, чем длится дорога.
 */
export const CHAT_LINES = 4;

/** Сколько длится разговор целиком. Столько же пара стоит у костра. */
export const CHAT_SECONDS = CHAT_LINES * TALK_SECONDS;

/** Реплика разговора: кто из двоих её сказал и что. */
export interface ChatLine {
  /** 0 — первый из пары, 1 — второй. Чей это номер, знает зовущий. */
  readonly who: 0 | 1;
  readonly text: string;
}

/**
 * Весь обмен целиком. Считается разом, а не по реплике: иначе двое сказали
 * бы одно и то же слово в одном разговоре — пулы у них пересекаются
 * общими присказками, и «славный нынче день» дважды подряд читается
 * не разговором, а эхом.
 */
function exchange(a: Talker, b: Talker, round: number): ChatLine[] {
  const rng = mulberry32(
    (a.seed ^ Math.imul(b.seed, 0x85ebca6b) ^ Math.imul(round + 1, 0xc2b2ae35)) | 0,
  );
  // Заговаривает то один, то другой: всегда начинающий первым — это не
  // разговор, а доклад по расписанию.
  const flip = (((round % 2) + 2) % 2) === 1;
  const lead: 0 | 1 = flip ? 1 : 0;
  const echo: 0 | 1 = flip ? 0 : 1;
  const said = new Set<string>();
  const say = (who: 0 | 1, pool: readonly string[], gen: Rng): ChatLine => {
    for (let k = 0; k < 8 && pool.length > said.size; k++) {
      const text = pick(gen, pool);
      if (!said.has(text)) {
        said.add(text);
        return { who, text };
      }
    }
    return { who, text: pool[0] ?? '' };
  };
  const moodOf = (who: 0 | 1): TalkMood => (who === 0 ? a.mood : b.mood);
  return [
    say(lead, POOLS[moodOf(lead)], rng),
    say(echo, REPLIES, rng),
    say(echo, POOLS[moodOf(echo)], rng),
    say(lead, REPLIES, rng),
  ];
}

/**
 * Что звучит на `since`-й секунде разговора; null — пауза или разговор
 * кончился. Пара стоит у костра дольше, чем говорит: последние секунды
 * молчания — это не пропуск, а то, ради чего пауза вообще существует.
 *
 * `round` — номер встречи (круг маршрута): без него каждая встреча повторяла
 * бы предыдущую слово в слово, а видятся эти двое каждую минуту.
 */
export function chatAt(a: Talker, b: Talker, since: number, round: number): ChatLine | null {
  const slot = Math.floor(since / TALK_SECONDS);
  if (slot < 0 || slot >= CHAT_LINES) return null;
  return exchange(a, b, round)[slot] ?? null;
}
