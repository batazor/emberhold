/**
 * Ограда — вторая стройка на готовом наборе (§6.1.7, Kenney Graveyard Kit).
 * Устроена она не так, как стена замка, и разницу дал обмер, а не вкус.
 *
 * **Стена занимает клетку, ограда — линию между клетками.** У замка деталь
 * заполняет клетку целиком: по ней ходят поверху, у неё есть зубцы и проход,
 * и потому её выбирают по тому, какие рёбра клетки она оставляет открытыми.
 * У кладбища деталь — панель шириной ровно в клетку и толщиной 0,11–0,30:
 * она стоит **на** линии, а не в клетке. Меряет это `npm run models`:
 * у всех прямых ограды в каталоге `rim` равен `1100` — линия пересекает
 * два противоположных ребра и ни одного больше.
 *
 * Из этого следует всё остальное, и следует само:
 *
 * - **Углы не нужны.** Панель ставится на отрезок между центрами соседних
 *   клеток цепи; в угловой клетке два отрезка сходятся под прямым углом
 *   и смыкаются сами. Угловые дуги набора поэтому не взяты вовсе — не потому,
 *   что плохи, а потому, что решают задачу, которой у нас нет.
 * - **Поворот не выбирается.** Он и есть направление отрезка, а сторона,
 *   к которой панель прижата, выбирается наружу от того, что ограда обносит.
 * - **Ворота — та же панель со створкой**, и у двух материалов из четырёх
 *   её в наборе нет. Там проезд — это проём: клетка остаётся пустой
 *   и проходимой. Это ответ набора, а не заглушка, ровно как перекрёсток
 *   у замка (§6.1.6).
 *
 * Файл живёт в `sim/`: ограда — это числа, а не картинка. Ни three, ни DOM,
 * гоняется в Node, проверяется `fence.rules.ts`, а каждое имя детали
 * сверяется там же с `catalog.json` набора.
 */
import { mulberry32, randInt, type Rng } from '../core/rng';
import { CASTLE_CELL, DIRS, type Spot } from './castle';

/**
 * Клетка ограды в клетках локации — та же двойка, что у замка, и по той же
 * причине измерена, а не назначена.
 *
 * Герой — 1,38 в клетках локации. Ограда набора: дерево 0,62, кирпич и камень
 * 0,73, ковка 0,88 в единицах набора. При масштабе один самая высокая из них
 * 0,88 — герою по колено, то есть бордюр. При двойке они 1,24–1,76 против
 * роста 1,38: **дерево и камень по грудь, ковка на ладонь выше макушки**.
 *
 * Это и есть требование, которое держит правило (`models.rules.ts`): ограда
 * обязана быть ниже стены замка (2,62) и примерно вровень с человеком.
 * Через ограду видно — этим она и отличается от стены, и потому общая сетка
 * с замком у неё не совпадение: одна и та же клетка лагеря обязана уметь
 * принять и то и другое.
 */
export const FENCE_CELL = CASTLE_CELL;

/** Четыре материала набора — четыре словаря деталей. */
export type FenceMaterial = 'дерево' | 'ковка' | 'кирпич' | 'камень';

export const FENCE_MATERIALS: readonly FenceMaterial[] = ['дерево', 'ковка', 'кирпич', 'камень'];

/**
 * Словарь материала. Объявлен по обмеру: каждое имя есть в наборе, каждая
 * прямая пересекает ровно два противоположных ребра клетки, и это сверяет
 * правило с `catalog.json`.
 *
 * По две-три прямых на материал — не украшение: без чередования ограда
 * читается гребёнкой из одинаковых зубцов, а не постройкой. Столб ставится
 * на изломе и есть только у дерева: у остальных трёх материалов излом
 * закрывает торец самой панели.
 */
export interface FenceKind {
  readonly title: string;
  /** Прямые пролёты: чередуются по сиду. */
  readonly spans: readonly string[];
  /** Створка проезда; `null` — у материала её в наборе нет, и проезд пуст. */
  readonly gate: string | null;
  /** Столб на изломе; `null` — излом закрывается торцами панелей. */
  readonly post: string | null;
}

export const FENCE: Readonly<Record<FenceMaterial, FenceKind>> = {
  'дерево': {
    title: 'Дощатая',
    spans: ['fence', 'fence-damaged'],
    gate: 'fence-gate',
    post: 'border-pillar',
  },
  'ковка': {
    title: 'Кованая',
    spans: ['iron-fence-border', 'iron-fence-border-column'],
    gate: 'iron-fence-border-gate',
    post: null,
  },
  'кирпич': {
    title: 'Кирпичная',
    spans: ['brick-wall', 'brick-wall-end'],
    gate: null,
    post: null,
  },
  'камень': {
    title: 'Каменная',
    spans: ['stone-wall', 'stone-wall-damaged', 'stone-wall-column'],
    gate: null,
    post: null,
  },
};

/** Зачем деталь стоит. */
export type FenceRole = 'пролёт' | 'проезд' | 'столб';

/**
 * Поставленная деталь. Координаты — в клетках набора и **могут быть
 * половинными**: пролёт стоит на середине отрезка между центрами двух
 * соседних клеток, а не в клетке. Столб стоит в клетке и потому целый.
 */
export interface FencePiece {
  readonly model: string;
  readonly x: number;
  readonly z: number;
  /** Четверти поворота вокруг вертикали, 0..3. */
  readonly turn: number;
  readonly role: FenceRole;
}

const keyOf = (s: Spot): string => `${s.x}:${s.z}`;

/**
 * Куда смотрит панель толщиной. Сторона выбирается наружу от `inside`:
 * панель прижата к своему −z, поэтому поворот берётся тот, при котором
 * этот −z смотрит от середины обносимого участка. У дощатой ограды панель
 * симметрична и сторона ничего не меняет — правило от этого не портится,
 * а два других материала без него зигзагом гуляли бы то внутрь, то наружу.
 */
function spanTurn(dx: number, outX: number, outZ: number): number {
  // Пролёт вдоль x: повороты 0 и 2, панель прижата к −z и +z соответственно.
  if (dx !== 0) return outZ >= 0 ? 2 : 0;
  // Пролёт вдоль z: повороты 1 и 3.
  return outX >= 0 ? 1 : 3;
}

/**
 * Ограда по клеткам. Клетки берутся любые — хоть кольцо генератора, хоть
 * то, что наметил игрок пальцем, — и **порядок в списке ничего не значит**:
 * пролёт возникает там, где две клетки оказались соседями. Отсюда и то,
 * ради чего конструктор стоило писать именно так: у кольца последняя клетка
 * соседствует с первой сама, а у мазка ничего лишнего не замыкается,
 * и особого случая ни там ни там нет.
 *
 * `gates` — клетки, через которые проходят. У материала со створкой там
 * встаёт створка, у материала без неё пролёта не встаёт вовсе: проезд —
 * это проём, и это ответ набора, а не заглушка.
 */
export function buildFence(
  cells: readonly Spot[],
  material: FenceMaterial,
  options: {
    /** Клетки проезда, ключ `keyOf`. */
    readonly gates?: ReadonlySet<string>;
    readonly rng?: Rng;
  } = {},
): FencePiece[] {
  const kind = FENCE[material];
  const rng = options.rng ?? mulberry32(1);
  const gates = options.gates ?? new Set<string>();
  if (cells.length < 2) return [];

  const set = new Set(cells.map(keyOf));
  // Середина участка — от неё и считается «наружу». Для кольца это его центр,
  // для мазка игрока — середина мазка, и в обоих случаях сторона выходит
  // одна и та же у всех пролётов.
  const mid = cells.reduce(
    (a, s) => ({ x: a.x + s.x / cells.length, z: a.z + s.z / cells.length }),
    { x: 0, z: 0 },
  );

  const out: FencePiece[] = [];
  // Только +x и +z: пара клеток обязана дать один пролёт, а не два.
  const FORWARD: readonly (readonly [number, number])[] = [[1, 0], [0, 1]];
  for (const cell of cells) {
    for (const [dx, dz] of FORWARD) {
      if (!set.has(`${cell.x + dx}:${cell.z + dz}`)) continue;
      const x = cell.x + dx / 2;
      const z = cell.z + dz / 2;
      const gate = gates.has(keyOf(cell)) || gates.has(`${cell.x + dx}:${cell.z + dz}`);
      if (gate && kind.gate === null) continue;
      out.push({
        model: gate ? kind.gate! : kind.spans[randInt(rng, kind.spans.length)]!,
        x,
        z,
        turn: spanTurn(dx, x - mid.x, z - mid.z),
        role: gate ? 'проезд' : 'пролёт',
      });
    }
  }

  // Столб — на изломе и на конце: там торцы двух панелей сходятся под прямым
  // углом или не сходятся вовсе, и у дощатой ограды между ними видна щель.
  // Есть столб только у дерева; у трёх других материалов торец панели
  // закрывает стык сам, и это видно по обмеру — панель у них толще втрое.
  if (kind.post !== null) {
    for (const cell of cells) {
      const dirs = fenceNeighbors(set, cell);
      if (dirs.length === 2) {
        const a = DIRS[dirs[0]!]!;
        const b = DIRS[dirs[1]!]!;
        if (a[0] === -b[0] && a[1] === -b[1]) continue; // прямая — столб не нужен
      }
      if (dirs.length === 0) continue; // одинокая клетка: ставить нечего
      out.push({ model: kind.post, x: cell.x, z: cell.z, turn: 0, role: 'столб' });
    }
  }
  return out;
}

/** Соседи клетки по цепи — та же четвёрка направлений, что у замка. */
export const fenceNeighbors = (set: ReadonlySet<string>, s: Spot): number[] =>
  DIRS.map((d, i) => (set.has(`${s.x + d[0]}:${s.z + d[1]}`) ? i : -1)).filter((i) => i >= 0);
