/**
 * Подарок за вход (§29): семь дней круга и семь дней первой недели.
 *
 * **Механика целиком стоит на одном числе.** Всё остальное — доли и
 * округление. Число это — не размер подарка, а **гарантия**: неделя подарков
 * не больше семи десятых того, что за ту же неделю приносит самый редкий
 * играющий игрок, одна вылазка в день. Из неё выводится доля вылазки
 * (`GIFT_SHARE`), из доли и весов дней — сами кучки, а из замеренной добычи
 * яруса (`TIER_HAUL`, §22.2) — их величина в штуках.
 *
 * Так подарок не может обогнать игру ни при каком росте лагеря: он всегда
 * доля вылазки того яруса, на который лагерь уже ходит.
 *
 * **Кристалла в подарке нет и не будет.** §13 держит на кристалле всю
 * конструкцию глубины: он берётся только риском. Подарок, из которого капает
 * кристалл, отменяет причину спускаться — и отменяет её молча, потому что
 * замер добычи этого не увидит.
 *
 * **Круг считается подарками, а не календарём.** Пропущенный день ничего
 * не сжигает и ничего не отматывает: седьмой день достанется тому, кто
 * пришёл семь раз, за сколько бы недель он это ни сделал. Полоса, которая
 * гаснет от одного пропуска, — наказание за отсутствие, а наказывать за
 * то, чего игрок не делал, эта игра не умеет нигде: ни истощение локаций
 * (§4), ни ставка (§11.2) так не устроены.
 *
 * **Замок суточный и живёт в сейве.** День берётся серверными часами (§27),
 * то есть перевод телефона вперёд подарка больше не даёт. Правка сейва
 * в консоли — даёт, и это честно названо в §27.4 вместе с остальным:
 * авторитет переезжает на сервер отдельной работой, тем же путём, каким
 * ушло колесо (`edge/wheel.ts`).
 */
import { TIER_HAUL, roundNice, tierForLevel } from './balance';
import type { ResourceKind, Resources } from './resources';
import type { Tier } from './types';

/** Дней в круге. Семь — потому что неделя, и потому что так просили. */
export const WEEK = 7;

/**
 * Гарантия, из которой выведено всё остальное: подарки за неделю не больше
 * семи десятых недельной добычи игрока, ходящего одну вылазку в день.
 *
 * Порог назначен, и это единственное назначенное число механики. Довод:
 * играть обязано быть выгоднее, чем приходить, — причём выгоднее у того,
 * кто играет меньше всех. У того, кто ходит три вылазки в день, запас
 * втрое больше сам собой.
 */
export const WEEK_BUDGET_SHARE = 0.7;

/**
 * Вес дня в круге. Неделя растёт к седьмому дню — ради этого круг и нужен:
 * пришедший в понедельник знает, что в воскресенье дадут больше.
 *
 * Сумма весов равна числу дней намеренно: тогда доля вылазки читается
 * средним днём, а гарантия выше проверяется сложением без поправок.
 */
export const DAY_WEIGHT: readonly number[] = [0.6, 0.7, 0.9, 1.0, 1.1, 1.3, 1.4];

/**
 * Доля вылазки, которую стоит средний день недели. **Выведена прибором**
 * (`npm run gift`), а не выбрана: перебор печатает наибольшую долю, при
 * которой обе гарантии держатся на округлённых кучках и на всех четырёх
 * ярусах, — и это она.
 *
 * Бюджету недели (0,7) она не равна, и не должна: бюджет — про сумму, а доля
 * платит ещё и за округление вверх, и за самый жадный день. Упирается она
 * на дне: там день «полный воз» перерастает вылазку раньше, чем неделя
 * перерастает бюджет.
 */
export const GIFT_SHARE = 0.6;

/** Что даёт день. Ресурсы повторяются, вещи и люди — нет (см. §29.2). */
export type GiftId = 'ресурсы' | 'сундук' | 'стрелы' | 'встреча';

export interface DailyGift {
  readonly id: GiftId;
  /** Что написано на карточке дня. */
  readonly title: string;
  /** Виды ресурсов, между которыми делится кучка. Пусто у вещей и встречи. */
  readonly kinds: readonly ResourceKind[];
}

/**
 * Первая неделя. Отличается от круга **не размером, а составом**: три дня
 * из семи дают не ресурсы, а то, что игрок иначе покупает сам, — хранилище,
 * стрелы и человека. Каждый такой день бесплатно показывает механику,
 * за которую со следующего раза платят.
 *
 * Человек седьмым днём — это местный ответ на «дают героя»: героев в игре
 * не выдают порогами (§11.8, они приходят знакомством), и подарок обязан
 * играть по тем же правилам. Приходит не карточка в отряде, а человек
 * к костру, и знакомство с ним такое же, как первое.
 */
export const ROOKIE_WEEK: readonly DailyGift[] = [
  { id: 'ресурсы', title: 'Дерево', kinds: ['wood'] },
  { id: 'ресурсы', title: 'Камень', kinds: ['stone'] },
  { id: 'сундук', title: 'Сундук', kinds: [] },
  { id: 'ресурсы', title: 'Железо', kinds: ['iron'] },
  { id: 'стрелы', title: 'Пачка стрел', kinds: [] },
  { id: 'ресурсы', title: 'Камень и дерево', kinds: ['stone', 'wood'] },
  { id: 'встреча', title: 'Гость у костра', kinds: [] },
];

/**
 * Круг, который повторяется дальше без конца. Здесь только расходуемое:
 * вещь, выдаваемая каждую неделю, — это уже не подарок, а вторая экономика
 * рядом с добычей, и растёт она сама по себе.
 */
export const CYCLE_WEEK: readonly DailyGift[] = [
  { id: 'ресурсы', title: 'Камень', kinds: ['stone'] },
  { id: 'ресурсы', title: 'Дерево', kinds: ['wood'] },
  { id: 'ресурсы', title: 'Камень и дерево', kinds: ['stone', 'wood'] },
  { id: 'ресурсы', title: 'Железо', kinds: ['iron'] },
  { id: 'ресурсы', title: 'Дерево и железо', kinds: ['wood', 'iron'] },
  { id: 'ресурсы', title: 'Камень и железо', kinds: ['stone', 'iron'] },
  { id: 'ресурсы', title: 'Полный воз', kinds: ['stone', 'wood', 'iron'] },
];

/**
 * Отметка о подарках в сейве. Два числа: день последнего и сколько взято
 * всего. Второе — и есть весь прогресс: круг считается подарками.
 */
export interface DailyState {
  /** День (`dayAt`) последнего взятого подарка. */
  readonly day: number;
  /** Сколько подарков взято за всё время. */
  readonly taken: number;
}

export const emptyDaily = (): DailyState => ({ day: -1, taken: 0 });

/** Идёт ли ещё первая неделя. */
export const rookie = (taken: number): boolean => taken < WEEK;

/** Номер дня внутри своей недели, 0…6. */
export const dayOf = (taken: number): number => taken % WEEK;

/** Какая неделя идёт, считая с первой. Нужна только показу. */
export const weekOf = (taken: number): number => Math.floor(taken / WEEK) + 1;

/** Что даст следующий подарок. */
export const giftAt = (taken: number): DailyGift =>
  (rookie(taken) ? ROOKIE_WEEK : CYCLE_WEEK)[dayOf(taken)]!;

/** Неделя, которая сейчас показывается карточками. */
export const weekAt = (taken: number): readonly DailyGift[] =>
  rookie(taken) ? ROOKIE_WEEK : CYCLE_WEEK;

/**
 * Кучка ресурсов дня. Величина — доля вылазки того яруса, на который лагерь
 * ходит; округляется слоем §20.3.3 **целиком**, и уже округлённое делится
 * между видами дня.
 *
 * Порядок здесь и есть всё правило. Округлять каждый вид отдельно казалось
 * тем же самым и не было им: три вида по 1,5 давали три двойки, то есть
 * шесть штук вместо пяти, — и день «полный воз» на нулевом ярусе перерастал
 * вылазку, ради которой всё считалось. Гарантия §29.1 умирала не в модели,
 * а в косметике — ровно тем способом, о котором предупреждает §20.3.3.
 *
 * Ноль здесь невозможен: округление вниз до нуля превратило бы подарок
 * в пустое окно, а окно, которое ничего не даёт, — худшее, что может
 * случиться с механикой, ради которой открывают игру. Поэтому у каждого
 * вида есть единица, и на неё же уменьшается общая кучка.
 */
export function giftLoot(gift: DailyGift, tier: Tier, taken: number): Partial<Resources> {
  if (gift.kinds.length === 0) return {};
  const model = GIFT_SHARE * DAY_WEIGHT[dayOf(taken)]! * TIER_HAUL[tier];
  const total = Math.max(gift.kinds.length, roundNice(model));
  // Делится поровну, остаток достаётся первым видам дня: они и названы
  // в заголовке первыми.
  const each = Math.floor(total / gift.kinds.length);
  let rest = total - each * gift.kinds.length;
  const loot: Partial<Resources> = {};
  for (const kind of gift.kinds) {
    loot[kind] = each + (rest > 0 ? 1 : 0);
    if (rest > 0) rest -= 1;
  }
  return loot;
}

/**
 * Ярус, долей которого считается подарок: тот, на который лагерь ходит
 * **сейчас**. Гейт ярусов стоит на Кухне (§22.8), и читается он от уровня
 * следующего — отсюда `+1`: с Кухней ур. 2 открыт ярус 1, а `tierForLevel(2)`
 * отвечает про того, кто на второй только копит.
 *
 * Ошибиться здесь на единицу значит платить подарком за ярус, куда игрока
 * ещё не пускают, — и §22.8 на этой самой единице уже терял ярус однажды.
 */
export const giftTier = (kitchenLevel: number): Tier => tierForLevel(kitchenLevel + 1);

/** Сколько стрел в пачке подарка. Та же пачка, что покупается за железо. */
export const GIFT_ARROWS = 4;

export type ClaimBlock = 'ok' | 'today';

/**
 * Можно ли взять подарок сегодня. Причина, а не булево, — тем же правилом,
 * что у стройки и палатки: отказ обязан называть себя.
 */
export const claimBlock = (state: DailyState, day: number): ClaimBlock =>
  state.day === day ? 'today' : 'ok';

export const CLAIM_REASON: Record<Exclude<ClaimBlock, 'ok'>, string> = {
  today: 'Подарок сегодня уже взят — следующий завтра',
};

/** Отметить взятый подарок. Считает вызывающий: здесь только счёт. */
export const claimed = (state: DailyState, day: number): DailyState => ({
  day,
  taken: state.taken + 1,
});
