import type { BuildingId, CampState } from './camp';
import { MAX_LEVEL } from './camp';
import { findPath } from './pathfinding';
import type { Cell, GameLocation, RaidState } from './types';

/**
 * Первые три минуты — раскадровка `onboarding.html`, десять кадров.
 * §16 ставит их в начало кривой: «0–3 мин · вылазка, лагерь, Кухня».
 *
 * Правило, из которого выведено всё остальное: ни одного экрана меню до того,
 * как игрок сыграет. Приложение открывается сразу в вылазке, лагерь появляется
 * как награда за неё, а не как стартовая комната. Поэтому онбординг — не набор
 * подсказок поверх готовой игры, а порядок, в котором игра включает саму себя:
 * каждая полоса HUD появляется в тот момент, когда ей есть что показать.
 *
 * Модуль намеренно headless: он решает «какой сейчас кадр и что открыто»,
 * ничего не зная ни про DOM, ни про сцену. Отсюда `onboarding.rules.ts` —
 * порядок кадров проверяется без браузера.
 */
export type OnbStep =
  /**
   * Пролог: поляна, герой, полоса провианта и пара брусков дерева на земле.
   * Ни боя, ни выхода — кадр кончается собранным деревом или кончившимся
   * провиантом, и лагерь предлагается разбить прямо там, где герой встал
   * (`prologue.ts`).
   */
  | 'glade'
  /**
   * Первый брусок в сумке. Полоса рюкзака зажигается здесь, а не в вылазке:
   * ей есть что показать — в сумке лежит то, из чего сейчас встанет палатка.
   */
  | 'gather'
  /**
   * Лагерь разбит, и палатка просит второй уровень: за деревом идут снова.
   * Кадр нужен затем, что первый акт учит «здание стоит принесённого» один
   * раз, а один раз читается как обряд постановки лагеря, а не как правило.
   */
  | 'upgrade'
  /**
   * Пролог отдал лагерь. Жильё ур. 2 открыло Мастерскую, Мастерская просит
   * камня, а камня на поляне не было и быть не могло — за ним и идут.
   *
   * Кадр стоит в лагере, а не в локации: выхода с поляны нет и не заводилось,
   * уводит игрока нижняя строка лагеря — та самая, где кнопки стояли всегда.
   */
  | 'world'
  /** 0:00 — герой в локации, одна подсвеченная точка на полу. */
  | 'move'
  /** 0:20 — первый скелет, бой идёт сам собой. */
  | 'approach'
  /** 0:40 — скриптовая рана: урон показан до того, как стал опасным. */
  | 'wound'
  /** 1:00 — первая добыча вылазки. Полоса рюкзака к этому кадру уже горит
   *  с пролога; здесь впервые появляется добыча, которую в неё кладут. */
  | 'loot'
  /** 1:15 — выход подсвечен, появляется цена возврата. */
  | 'back'
  /** 1:30 — приманка: второй сундук в стороне от выхода, ставка вводится нулём. */
  | 'bait'
  /** 1:50 — возвращение, красная кнопка. */
  | 'evac'
  /** 2:05 — экран возврата, единственный путь — в лагерь. */
  | 'return'
  /**
   * 2:30 — лагерь, и Мастерская просит принесённый камень.
   *
   * Просит именно она, а не Кухня: костёр игрок поставил своими руками ещё
   * в прологе, и звать его строить то же самое второй раз значило бы
   * не заметить, что он уже это сделал.
   *
   * И платит он здесь по-настоящему. Первое здание дарится в прологе
   * (`grantLevelOffBooks`), а это — первое, за которое спрашивают цену:
   * ровно то, ради чего игрок сходил в вылазку.
   */
  | 'build'
  /**
   * 2:50 — Мастерская встала, а ковать нечем: первый предмет стоит железа,
   * и его роняют только ярусы 1–3 (§13), которые Кухня ещё не отперла.
   *
   * Кадр поэтому не показывает витрину, а называет нехватку и место, где её
   * закрыть, — торговца в замке (§13.5). Это и есть та единственная запись,
   * которую `quests.html` называет «направлением»: «продолжение онбординга
   * за пределы первых трёх минут».
   *
   * Кончается кадр первой ковкой, а не второй вылазкой. Прежде он висел
   * до входа в следующую вылазку — то есть до того, как игрок сделает то,
   * ради чего Мастерская и строилась.
   */
  | 'craft'
  /** Онбординг пройден: игра работает как обычно. */
  | 'done';

export const ONB_ORDER: readonly OnbStep[] = [
  'glade', 'gather', 'upgrade', 'world',
  'move', 'approach', 'wound', 'loot', 'back', 'bait', 'evac',
  'return', 'build', 'craft', 'done',
];

/**
 * Кадры, которые идут в лагере. Лагерь лежит в сохранении целиком, поэтому
 * они перезапуск переживают — в отличие от всего остального.
 */
const CAMP_STEPS: readonly OnbStep[] = ['world', 'return', 'build', 'craft', 'done'];

/**
 * Кадры, переименованные по ходу дела. Сейв хранит имя кадра строкой, и
 * незнакомое имя читается как «онбординг пройден» — игрок, закрывший вкладку
 * на предпоследнем кадре, терял бы его молча.
 */
export const RENAMED_STEPS: Readonly<Record<string, OnbStep>> = {
  // Кадр звал на следующий ярус, открытый Кухней; теперь он показывает ковку,
  // открытую Мастерской.
  tier: 'craft',
};

export const stepIndex = (step: OnbStep): number => ONB_ORDER.indexOf(step);

/**
 * Кадр идёт в локации — значит, при перезапуске его придётся начинать заново:
 * ни поляна, ни вылазка перезапуск не переживают (см. `save.ts`).
 *
 * Считается от списка лагерных кадров, а не по порядковому номеру: `world`
 * стоит между прологом и первой вылазкой, но идёт в лагере, и номер про это
 * ничего не говорит.
 */
export const isRaidStep = (step: OnbStep): boolean => !CAMP_STEPS.includes(step);

/**
 * С какого кадра продолжить после перезапуска. Ни поляна, ни первая вылазка
 * его не переживают, но начинаются они с разного: пролог — с себя самого,
 * вылазка — со своего первого кадра. Без этой развилки сохранённый пролог
 * открывался вылазкой, и кнопка «Играть» вела мимо него.
 */
export const restartStep = (step: OnbStep): OnbStep =>
  step === 'glade' || step === 'gather' || step === 'upgrade'
    ? 'glade'
    : isRaidStep(step)
      ? 'move'
      : step;

/**
 * Что открыто на этом кадре. «Одна механика на кадр»: полосы включаются по
 * одной и больше не гаснут — исчезнувшая полоса читалась бы как поломка.
 */
export interface Reveal {
  readonly food: boolean;
  readonly wounds: boolean;
  readonly bag: boolean;
  readonly back: boolean;
  /** Строка «под угрозой». На нулевом ярусе она показывает ноль — и в этом
   *  весь смысл кадра 6: риск существует, но пока ничего не стоит. */
  readonly risk: boolean;
  readonly evac: boolean;
  /** Поворот, зум, ночь, умение. В первой вылазке жест ровно один — тап. */
  readonly controls: boolean;
}

export function reveal(step: OnbStep): Reveal {
  const i = stepIndex(step);
  const done = step === 'done';
  return {
    food: true,
    wounds: done || i >= stepIndex('wound'),
    // Рюкзак зажигается в прологе, на первом бруске, и больше не гаснет:
    // кадр `loot` вводит уже не полосу, а добычу, которую в неё кладут.
    bag: done || i >= stepIndex('gather'),
    back: done || i >= stepIndex('back'),
    risk: done || i >= stepIndex('bait'),
    evac: done || i >= stepIndex('evac'),
    controls: done,
  };
}

/**
 * Единственная строка подсказки. Всплывающих окон с «Понятно» нет ни одного:
 * обучение идёт жестом и подсвеченной точкой, текст только называет жест.
 */
export const ONB_HINT: Partial<Record<OnbStep, string>> = {
  glade: 'Коснитесь земли, чтобы идти',
  gather: 'Соберите бруски',
  upgrade: 'Отнесите к палатке три бруска',
  world: 'Мастерской нужен камень — его нет на поляне',
  move: 'Коснитесь земли, чтобы идти',
  approach: 'Подойдите ближе',
  bait: 'Дальше — ещё один сундук',
  build: 'Поставьте Мастерскую',
  craft: 'Железо — у торговца в замке',
};

/**
 * Пауза между двумя соседними открытиями. Кадры 4–6 идут подряд по одному
 * событию — добыче, — и без паузы три полосы появились бы разом, нарушив
 * правило «одна механика на кадр».
 */
export const REVEAL_PAUSE = 4;

/** Сколько ждём приманку, прежде чем показать выход. Игрок мог решить
 *  не жадничать — кадр 7 обязан наступить в любом случае. */
export const BAIT_TIMEOUT = 25;

export interface RaidSignals {
  /** Игрок сделал хотя бы шаг — значит, тап понят. */
  readonly moved: boolean;
  readonly wounded: boolean;
  /** Сколько контейнеров вскрыто. */
  readonly looted: number;
  readonly sinceStep: number;
}

/**
 * Следующий кадр вылазки или null, если ещё рано. Кадры двигаются событиями,
 * а не секундомером: полоса рюкзака вводится в момент, когда ей есть что
 * показать, а не на первой минуте по часам.
 */
export function nextRaidStep(step: OnbStep, s: RaidSignals): OnbStep | null {
  switch (step) {
    case 'move':
      return s.moved ? 'approach' : null;
    case 'approach':
      if (s.wounded) return 'wound';
      // Игрок обошёл противника и пошёл за добычей: кадр с раной пропускается,
      // но цепочка обязана идти дальше — иначе рюкзак не появится никогда.
      return s.looted >= 1 ? 'loot' : null;
    case 'wound':
      return s.looted >= 1 ? 'loot' : null;
    case 'loot':
      return s.sinceStep >= REVEAL_PAUSE ? 'back' : null;
    case 'back':
      return s.sinceStep >= REVEAL_PAUSE ? 'bait' : null;
    case 'bait':
      return s.looted >= 2 || s.sinceStep >= BAIT_TIMEOUT ? 'evac' : null;
    default:
      return null;
  }
}

/**
 * Куда показать точку тапа в кадре 1. Не случайная клетка: два шага по пути
 * к ближайшему контейнеру — тап учит идти туда, где что-то есть.
 */
export function firstTapCell(loc: GameLocation, from: Cell): Cell | null {
  let best: Cell[] = [];
  for (const c of loc.containers) {
    const path = findPath(loc.size, loc.blocked, from, { x: c.x, z: c.z });
    if (path.length === 0) continue;
    if (best.length === 0 || path.length < best.length) best = path;
  }
  if (best.length === 0) return null;
  return best[Math.min(2, best.length - 1)] ?? null;
}

/**
 * Скриптовая рана кадра 3. Первый противник обязан задеть героя: раны нужно
 * показать до того, как они станут опасными, иначе игрок узнает о них
 * в тот момент, когда терять уже есть что.
 *
 * Ровно одна и только в первой вылазке — дальше бой считается сам.
 */
export function scriptWound(state: RaidState): boolean {
  if (state.status !== 'running') return false;
  if (!state.inFight) return false;
  if (state.hero.wounds <= 1) return false;
  state.hero.wounds -= 1;
  state.events.push('Скелет задел');
  return true;
}

/**
 * Открыть выход, когда он заслужен. Герой стартует на точке выхода,
 * поэтому в первой вылазке выход молчит до первой добычи: иначе тап рядом
 * со стартом уводит игрока домой с пустым рюкзаком — и вся раскадровка,
 * от боя до ставки, не случается вовсе.
 *
 * Условие — именно добыча, а не номер кадра: как только нести есть что,
 * решение «уйти сейчас или пойти за приманкой» обязано быть настоящим.
 * Ровно эту долю и меряет вторая метрика раскадровки.
 */
export function openEvacWhenEarned(state: RaidState, step: OnbStep): boolean {
  if (state.evacOpen) return false;
  if (state.bagTotal <= 0 && stepIndex(step) < stepIndex('evac')) return false;
  state.evacOpen = true;
  return true;
}

/**
 * Уровень в обход ценника лагеря. Бесплатным это не делает ничего: жильё
 * ур. 2 в прологе платит три бруска — просто не по `BUILD_COST`, а из рюкзака,
 * на глазах, той самой полосой, куда их клали (§16.1).
 *
 * Раньше функция звалась «первая постройка бесплатно» и это было правдой:
 * лагерь открывался после первого возвращения и дарил Кухню. Дарить давно нечего —
 * жильё, Кухня и Склад стоят с ур. 1 из `createCamp`, а Мастерская, четвёртое
 * здание, стоит камня (§16.2). Осталась одна работа: провести улучшение мимо
 * таблицы, потому что цена пролога измеряется в дереве, а `BUILD_COST[2]` —
 * в камне, которого у игрока ещё нет и взять негде.
 *
 * Мгновенность — да, и по-прежнему по §20.2: ждать таймер игрок на этом шаге
 * ещё не научился.
 *
 * Отдельная функция, а не флаг внутри `startUpgrade`, именно затем, чтобы
 * обычная экономика не знала об этом исключении: калибровка §20.3 и золотой
 * мастер петли считают стройку по полной цене и не могут сюда попасть.
 */
export function grantLevelOffBooks(camp: CampState, id: BuildingId): boolean {
  if (camp.construction !== null) return false;
  if (camp.levels[id] >= MAX_LEVEL) return false;
  camp.levels[id] += 1;
  return true;
}
