/**
 * §13.8 — местные мест мира у своих кустов: формула, которую видно.
 *
 * Полнота узла места считается формулой от сида и часов (`berries.ts`),
 * и один из её ответов звучал так: **этот куст обирают местные**. Ответ был
 * честный, но немой — игрок приходил к пустой ветке и не имел ни одного
 * способа узнать, почему она пуста. Место жило в бухгалтерии и не жило
 * в кадре.
 *
 * Этот модуль не заводит второй правды. Он **ничего не решает**: список
 * обираемых узлов ему выдаёт `takenBushes`, и собиратель ставится ровно
 * к тем кустам, которые формула уже объявила своими. Обратной связи нет —
 * человек в кадре не может отменить формулу и не может добавить к ней узла.
 * Поэтому «кадр разошёлся с числом» здесь невозможно не по недосмотру,
 * а по устройству: считает одна сторона, показывает другая.
 *
 * **Рутина берётся у лагеря целиком** (`chores.ts`). Второй ходьбы в игре
 * заводить нельзя — это уже было сказано про жильцов двора (`garrison.ts`),
 * и здесь то же самое, только с другого конца: круг «вышел из ворот,
 * поработал у куста, вернулся с ношей» — тот же круг добытчика поляны,
 * до последней стоянки. Разница между лагерем и местом умещается в два поля
 * площадки: у места нет неба (свет ему назначает сцена, и ночи в маршруте
 * поэтому нет) и нет разговора у костра (карточек, имён и настроений
 * у местных не заведено).
 *
 * **Дом маршрута — те же ворота, от которых формула мерит близость.** Это
 * не совпадение, а то, ради чего ворота в формуле и стоят: доля обобранного
 * падает с расстоянием потому, что за дальним кустом дальше идти, — и теперь
 * это видно ногами. Одна точка, один смысл.
 *
 * **Ничего не платит** (§6.1.15). Как и рутина лагеря, собиратель не кладёт
 * в кладовую ни ягоды: пища мест приходит игроку только из его собственных
 * десяти замахов, а местные едят своё за кадром. Ресурс, появившийся отсюда,
 * был бы вторым каналом за ту же работу.
 */
import { takenBushes } from './berries';
import type { Bush, Locals } from './berries';
import { choresOf } from './chores';
import type { Chore, ChoreFolk, ChoreSite } from './chores';
import { SHIFT_SEC } from './world';
import type { Cell } from './types';

/**
 * Сколько собирателей выходит разом. Три — не про толпу, а про то, сколько
 * их вообще может быть: у замка три-пять кустов, спелой в окне бывает
 * четверть, и обираемых местными больше трёх не выпало ни на одном
 * из измеренных сидов (`npm run locals`). Потолок стоит здесь не затем,
 * чтобы резать картину, а затем, чтобы новый набор кустов не превратил
 * поле в очередь: если он начнёт срабатывать, это будет видно замером,
 * а не в кадре.
 */
export const GATHERERS_MAX = 3;

/** Площадка, по которой ходят местные. Всё, кроме кустов, — как у рутины. */
export interface GatherSite {
  readonly seed: number;
  readonly size: number;
  readonly blocked: Uint8Array;
  /** Все кусты места: кого из них обирают, решает формула, а не этот модуль. */
  readonly bushes: readonly Bush[];
  /** Люди места; `null` — местных нет, и тогда некому ходить. */
  readonly locals: Locals | null;
}

/** Один местный: его круг и куст, ради которого круг проложен. */
export interface Gatherer {
  readonly chore: Chore;
  readonly bush: Bush;
}

/**
 * Куст, у которого работает этот маршрут. Выводится из самого маршрута,
 * а не запоминается рядом с ним: рабочая стоянка стоит вплотную к кусту,
 * и другого способа ошибиться тут нет.
 */
function bushOf(chore: Chore, bushes: readonly Bush[]): Bush | null {
  const stop = chore.stops.find((s) => s.working);
  if (stop === undefined) return null;
  const at = chore.path[stop.at];
  if (at === undefined) return null;
  return bushes.find((b) => Math.abs(b.x - at.x) + Math.abs(b.z - at.z) <= 1) ?? null;
}

/**
 * Местные у своих кустов на момент `now`. Пусто — обирать некому или нечего:
 * и то и другое сказала формула, а не этот модуль.
 *
 * `now` берётся один раз, на входе в место: полнота узлов меняется раз
 * в созревание (два часа), а прогулка по замку идёт минуты — окно не успевает
 * повернуться под ногами. Правило сторожит именно это соответствие, а не
 * обещание: маршрут, оставшийся от прошлого окна, оно поймает.
 */
export function gatherersOf(site: GatherSite, now: number): Gatherer[] {
  const { locals } = site;
  if (locals === null) return [];
  const taken = takenBushes(site.seed, site.bushes, locals, now).slice(0, GATHERERS_MAX);
  if (taken.length === 0) return [];

  /**
   * Люди без лиц: рутине довольно сида тропы и занятия. Сид — от места
   * и номера узла, чтобы один и тот же замок водил своих одной и той же
   * дорогой, а не подменял их при каждом заходе.
   */
  const folk: ChoreFolk[] = taken.map((b) => ({
    seed: (site.seed * 2654435761) ^ (b.id * 40503) ^ 0x9a7e,
    answer: 'кормим',
    rest: false,
  }));

  const home: Cell = { x: Math.round(locals.hub.x), z: Math.round(locals.hub.z) };
  const choreSite: ChoreSite = {
    size: site.size,
    blocked: site.blocked,
    // Дом — ворота: та же точка, от которой формула мерит близость куста.
    fire: home,
    seed: site.seed ^ 0x9e13,
    // Палаток у места нет, и не потому, что их забыли: спать в маршруте
    // негде — смена отдана кругам целиком (см. `awake`).
    tents: [],
    bushes: taken.map((b) => ({ x: b.x, z: b.z })),
    awake: SHIFT_SEC,
    chats: false,
  };

  // Крыша есть у всех: она тут стена замка, а не палатка на поляне, и решает
  // она не «работает ли человек» (§6.1.15), а только то, где он ночует, —
  // ночи же у места нет.
  const chores = choresOf(choreSite, folk, () => true);
  const out: Gatherer[] = [];
  const busy = new Set<number>();
  for (const chore of chores) {
    if (chore === null) continue;
    const bush = bushOf(chore, taken);
    // Круг без куста — круг не сюда: до узла не нашлось дороги, и рутина
    // отдала маршрут к кромке леса. Такого местного в кадре быть не должно:
    // он ходил бы неизвестно за чем.
    if (bush === null) continue;
    /**
     * Двое у одного куста бывают: рутина разводит рабочие точки порогом
     * «врозь», а порог отпускается, когда точек мало (`chores.ts`). Здесь
     * это отменяется, и не ради тесноты — **узел обирают один раз**, и двое
     * над ним читались бы как две горсти с одной ветки. Второй просто
     * не выходит: соседний куст остаётся обобранным без свидетеля, что
     * формуле не противоречит — местный там уже побывал.
     */
    if (busy.has(bush.id)) continue;
    busy.add(bush.id);
    out.push({ chore, bush });
  }
  return out;
}
