/**
 * Как причина склеивается с тем, к чему относится (§23.3).
 *
 * Правило одно: **строка причины не меняется от места**. Панель показывает
 * её как есть, полоса ставит перед ней имя — и обе видят одни и те же слова
 * до буквы. Раньше на разницу регистра заводилась вторая таблица, и слова
 * в ней разъезжались молча.
 *
 * Отсюда разделитель « · », а не двоеточие. Двоеточие требует строчной буквы
 * после себя, строчная буква требует опустить первую, а опустить её нельзя:
 * «Жильё не пускает выше» и «Мастерская не тянет выше» начинаются с имени
 * здания. Точка-разделитель уже работает в полосе («+3 · Камень») и ничего
 * от строки не требует.
 */

/** «Мастерская · Не хватает железа». */
export const refusal = (subject: string, reason: string): string => `${subject} · ${reason}`;
