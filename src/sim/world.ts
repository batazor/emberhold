/**
 * Свет лагеря в долях смены. **Смена и есть сутки**, и второго числа тут
 * нет намеренно: `SHIFTS_PER_DAY` уже говорит, что смен в сутках тридцать
 * шесть, а небо, поворачивающееся раз в смену, впервые делает мировые часы
 * видимыми — игрок смотрит на свет и знает, где мир.
 *
 * Свои сутки длиной в двадцать минут были бы вторыми часами рядом с этими,
 * и разошлись бы они молча — той же болезнью, какой §22.8 болел на ярусах.
 * Сутки региона (`dayAt`, 24 часа) на эту роль не годятся с другой стороны:
 * §20.2 говорит прямо, что срок длиннее суток превращает лагерь в календарь.
 *
 * Доли фаз выбраны не на глаз, а замером `npm run shift`: он печатает, в чём
 * игрок застаёт лагерь и как часто застаёт перелом. Сумерки широкие потому,
 * что перелом — единственная фаза, которую **смотрят**, а не застают:
 * узкий закат за двухминутный заход не поймал бы никто.
 */
const PHASE = { день: 0.42, закат: 0.13, ночь: 0.32 } as const;

/**
 * Границы фаз **в секундах**, а не в долях, и посчитаны один раз.
 *
 * Доли выглядели честнее, но 0,32 в двоичной дроби не точна, и `0.87 × 2400`
 * оказывалось то чуть больше 2088, то чуть меньше. На эпсилон расходились
 * ровно две вещи, которым расходиться нельзя: свет говорил «ещё ночь»,
 * а расписание уже будило жильца. Одни и те же секунды у обоих снимают
 * вопрос вместо того, чтобы прятать его за округлением.
 */
const DUSK_AT = Math.round(PHASE.день * SHIFT_SEC);
const DARK_AT = Math.round((PHASE.день + PHASE.закат) * SHIFT_SEC);
const DAWN_AT = Math.round((PHASE.день + PHASE.закат + PHASE.ночь) * SHIFT_SEC);

/**
 * Свет полудня. То же число, каким светилась поляна пролога: сутки
 * не переосвещают день, они добавляют к нему всё остальное.
 */
export const CAMP_DAY = 0.12;

/**
 * Свет глухой ночи. Темнее сумерек кладбища (0,45) и светлее подземелья (1):
 * под небом никогда не бывает так же черно, как под землёй, а лагерь обязан
 * читаться силуэтами и без факела — прятать от игрока его собственный лагерь
 * незачем, там нечего прятать.
 */
export const CAMP_NIGHT = 0.8;

/**
 * Ночь в секундах смены — и её начало. Отсюда же берёт расписание рутина
 * (`sim/chores.ts`): жильцы спят ровно ту фазу, которую небо показывает
 * тёмной, и второго числа на это нет. Разойдись они — жилец ложился бы
 * при свете или работал в темноте, и починить это можно было бы только
 * подгонкой одного под другое.
 */
export const SLEEP_FROM = DARK_AT;
export const SLEEP_SEC = DAWN_AT - DARK_AT;
/** Начало рассвета: с него у рутины отсчёт, потому что с него встают. */
export const WAKE_AT = DAWN_AT;
/** Сколько смены жилец на ногах. Столько же длятся все его круги вместе. */
export const AWAKE_SEC = SHIFT_SEC - SLEEP_SEC;

/** Сглаженная ступень: перелом без излома на краях, иначе закат читается
 *  щелчком выключателя, а не заходом солнца. */
const smooth = (u: number): number => u * u * (3 - 2 * u);

/**
 * Насколько темно в лагере на момент `t` — 0 не бывает: день тоже свет,
 * а не его отсутствие. Чистая функция часов, как и всё в этом модуле:
 * ничего не тикает, в сохранение не едет ни поля, а закрытая вкладка
 * отрабатывает сама, потому что часы настенные.
 */
export function nightAt(t: number): number {
  const s = ((t % SHIFT_SEC) + SHIFT_SEC) % SHIFT_SEC;
  const lerp = (k: number): number => CAMP_DAY + (CAMP_NIGHT - CAMP_DAY) * smooth(k);
  if (s < DUSK_AT) return CAMP_DAY;
  if (s < DARK_AT) return lerp((s - DUSK_AT) / (DARK_AT - DUSK_AT));
  if (s < DAWN_AT) return CAMP_NIGHT;
  return lerp(1 - (s - DAWN_AT) / (SHIFT_SEC - DAWN_AT));
}

/** Время суток словом — отладочным сценам и прибору, а не игроку: в кадре
 *  время суток называет свет, а не подпись. */
export function phaseAt(t: number): 'день' | 'закат' | 'ночь' | 'рассвет' {
  const s = ((t % SHIFT_SEC) + SHIFT_SEC) % SHIFT_SEC;
  if (s < DUSK_AT) return 'день';
  if (s < DARK_AT) return 'закат';
  if (s < DAWN_AT) return 'ночь';
  return 'рассвет';
}

/**
 * Место клетки сетки в долях экрана. Раздача точек, прогулок и лагерей
 * соседей считает его одинаково, и вынесено оно затем, что три копии одной
 * арифметики расходятся молча — а расходиться им нельзя: минимальный зазор
 * между точками сторожит `world.rules.ts` числом.
 *
 * Разброс приходит снаружи двумя долями, а не берётся здесь из своего
 * генератора: у раздачи дня он свой, у лагерей — вечный, и порядок бросков
 * в раздаче трогать нельзя.
 */
const cellSpot = (cell: number, jx: number, jy: number): { x: number; y: number } => {
  const col = cell % GRID_X;
  const row = (cell / GRID_X) | 0;
  return {
    // Нижняя полоса оставлена лагерю игрока: точка поверх лагеря сделала бы
    // нечитаемыми обе.
    x: (col + 0.5) / GRID_X + (jx - 0.5) / GRID_X / 2.2,
    y: 0.08 + ((row + 0.5) / GRID_Y) * 0.76 + (jy - 0.5) / GRID_Y / 2.6,
  };
};

/**
 * Клетки, отданные лагерям соседей (§30). Отданы **до раздачи дня и навсегда**:
 * регион пересобирается каждые сутки, а лагерь — нет. Сосед, переезжающий
 * вместе с точками, был бы не соседом, а ещё одной точкой дня; та же причина,
 * по которой лагерь игрока в раздаче не участвует.
 *
 * Отсюда же и способ: клетки вынимаются из общей колоды, поэтому вылазка
 * не сядет на чужой лагерь ни в один день — не проверкой, а по построению.
 * Колода при этом остаётся вместительной: 35 клеток минус четыре — 31,
 * ровно самый людный день (22 вылазки и до девяти прогулок).
 */
const CAMP_CELLS: readonly number[] = (() => {
  const cells: number[] = [];
  for (let i = 0; i < GRID_X * GRID_Y; i++) cells.push(i);
  const rng = mulberry32(hash(SEED, 11));
  for (let i = cells.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const swap = cells[i]!;
    cells[i] = cells[j]!;
    cells[j] = swap;
  }
  return cells.slice(0, CLANS.length);
})();

/** Лагерь фракции на карте: кто и где. Место вечное, состояние — считается. */
export interface ClanCamp {
  readonly id: number;
  readonly x: number;
  readonly y: number;
}

/**
 * Лагеря фракций (§30). Мир был до игрока (§4), и его соседи стоят на карте
 * всегда — в тот же день, когда игрок впервые её открыл, и в любой другой.
 */
export const CLAN_CAMPS: readonly ClanCamp[] = CAMP_CELLS.map((cell, id) => {
  const rng = mulberry32(hash(SEED, id, 12));
  return { id, ...cellSpot(cell, rng(), rng()) };
});

/** Лагерь: место постоянное, оно не переезжает вместе с картой. */
const CAMP_SPOT = { x: 0.5, y: 0.9 };

/**
 * Полоса живых соседей (§30.7) — нижняя кромка карты, та же, на которой
 * стоит свой лагерь.
 *
 * Клетки сетки им не достались, и это не экономия: колода вмещает самый
 * людный день впритык (31 точка из 31), а живых лагерей может быть сколько
 * угодно. Кромка вмещает их, ничего не отнимая у региона, и говорит правду:
 * фракции стоят внутри, потому что они тут давно, а пришедшие — с краю,
 * рядом с вашим лагерем, который стоит там же и по той же причине.
 */
const LIVE_BAND = { top: 0.875, bottom: 0.965 };

/**
 * Сколько чужих лагерей помещается на кромку. Шесть — не вкус: узел рисуется
 * радиусом `w * 0.026`, то есть кромка длиной в экран вмещает их около
 * восемнадцати вплотную; шесть оставляют между ними три радиуса — расстояние,
 * на котором тап попадает в тот лагерь, в который целились (порог выбора —
 * 9% ширины).
 *
 * Подрезанных таблица называет вслух (`standings`): молча обрезанный список
 * читается как «это все», а это не все.
 */
export const LIVE_SHOWN = 6;

/**
 * Тот же FNV, что у `hash`, но по строке: идентификатор аккаунта — не число.
 * Нужен ровно затем, чтобы место чужого лагеря не прыгало между чтениями:
 * позиция по номеру в списке переезжала бы каждый раз, когда сосед обгонит
 * соседа, — а лагерь стоит там, где разбит.
 */
export function hashText(text: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i) & 255;
    h = Math.imul(h, 16777619) >>> 0;
  }
  return h >>> 0;
}

/**
 * Места на кромке: три слева от своего лагеря, три справа. Список, а не
 * формула, и это исправление замера: место, посчитанное из одного лишь
 * идентификатора, дважды сажало соседей вплотную — худший зазор из двухсот
 * имён выходил 0,004 ширины при пороге выбора в 0,09. Два лагеря в одной
 * точке — это один нечитаемый лагерь и тап, попадающий не туда.
 *
 * Шаг 0,12 — вчетверо больше радиуса узла (`w × 0,026`), и середина
 * оставлена своему лагерю: он стоит на 0,5 и был там раньше всех.
 */
const LIVE_SLOTS: readonly number[] = [0.08, 0.2, 0.32, 0.68, 0.8, 0.92];

/**
 * Разложить чужие лагеря по кромке. Порядок — по хешу имени, а не по силе:
 * от силы место переезжало бы каждый раз, когда сосед обгонит соседа,
 * а лагерь стоит там, где разбит.
 *
 * Больше `LIVE_SHOWN` мест на кромке нет; кого не поместили, называет
 * вслух карточка — молча обрезанный список читается как «это все».
 */
export function liveCampSpots(
  ids: readonly string[],
): { id: string; x: number; y: number }[] {
  return [...ids]
    .sort((a, b) => hashText(a) - hashText(b))
    .slice(0, LIVE_SHOWN)
    .map((id, i) => ({
      id,
      x: LIVE_SLOTS[i] ?? 0.5,
      // Высота своя у каждого: ровный ряд читается легендой, а не местами.
      y: LIVE_BAND.top + mulberry32(hashText(id))() * (LIVE_BAND.bottom - LIVE_BAND.top),
    }));
}

/** Регион последнего спрошенного дня. Раздача стоит одинаково, а карта
 *  перерисовывается кадрами — считать её каждый кадр незачем. */
let cached: Region | null = null;

/**
 * Регион на день. Точки, их число и ярусы выпадают заново — постоянного
 * соотношения ярусов нет намеренно: день, в котором рядом только третий
 * ярус, обязан быть возможен, иначе карта снова станет расписанием.
 */
export function regionAt(day: number): Region {
  if (cached !== null && cached.day === day) return cached;
  const rng = mulberry32(hash(SEED, day, 1));
  const count = NODES_MIN + Math.floor(rng() * (NODES_MAX - NODES_MIN + 1));

  // Клетки сетки перемешиваются и разбираются по одной: две точки не
  // садятся в одно место, а раздача при этом остаётся случайной.
  const cells: number[] = [];
  // Клетки чужих лагерей в колоду не попадают вовсе: соседи стоят на месте,
  // а точки дня раздаются вокруг них (`CAMP_CELLS`).
  for (let i = 0; i < GRID_X * GRID_Y; i++) if (!CAMP_CELLS.includes(i)) cells.push(i);
  for (let i = cells.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const swap = cells[i]!;
    cells[i] = cells[j]!;
    cells[j] = swap;
  }

  const names = [...NAMES];
  const nodes: WorldNode[] = [];
  for (let i = 0; i < Math.min(count, cells.length); i++) {
    const cell = cells[i]!;
    const { x, y } = cellSpot(cell, rng(), rng());
    const name = names.splice(Math.floor(rng() * names.length), 1)[0] ?? `Место ${i}`;
    nodes.push({ id: i, name, x, y, tier: Math.floor(rng() * 4) as Tier, kind: 'вылазка' });
  }

  /**
   * Прогулочные точки дня — замок (§6.1.6) и кладбище (§6.1.7). Их несколько,
   * и сколько именно, решает раздача, а не таблица расписания: день, в котором
   * рядом три замка и одно кладбище, обязан быть возможен ровно так же, как
   * день, где рядом только третий ярус.
   *
   * Правило, ради которого эти точки писались, остаётся дословно: **они
   * добавляются сверх раздачи вылазок, а не вместо одной из них**. Ярусы,
   * богатство и весь счёт §4 обязаны остаться такими же, какими были до них.
   * Клетка берётся следующей из той же перетасованной колоды — значит, ни
   * поверх вылазки, ни друг поверх друга они не сядут никогда.
   *
   * Имя — та же рабочая подпись местности (§0.1), в кавычках: склонять её
   * было бы враньём про язык мира, которого нет.
   */
  for (const spec of STROLL) {
    const count = spec.min + Math.floor(rng() * (spec.max - spec.min + 1));
    for (let i = 0; i < count; i++) {
      const cell = cells[nodes.length];
      if (cell === undefined) break;
      const where = names.splice(Math.floor(rng() * names.length), 1)[0] ?? 'Пустошь';
      nodes.push({
        id: nodes.length,
        name: `${spec.label} «${where}»`,
        ...cellSpot(cell, rng(), rng()),
        tier: 0,
        kind: spec.kind,
      });
    }
  }

  cached = { day, nodes, camp: CAMP_SPOT };
  return cached;
}

/**
 * Сид локации. Место держит форму сутки: в течение дня одна и та же точка
 * собирается одной и той же пещерой — иначе «сходить сюда ещё раз»
 * перестаёт быть решением. Завтра этого региона уже нет, и сида тоже.
 */
export const nodeSeed = (day: number, node: number): number => hash(SEED, day, node, 3);

/**
 * Что происходит на точке сейчас (§11.6). Считается так же, как клан и
 * богатство, — из сида и номера окна, без единого поля в сохранении.
 *
 * Окно, а не смена: событие обязано пережить сессию, иначе решение «схожу
 * туда» превращается в гонку с таймером, чего `world.html` прямо не хочет
 * («окно события — часы, а не минуты»). И обязано смениться внутри суток,
 * иначе карта снова расписание.
 *
 * Замок событий не носит: §6.1.6 обещает там прогулку без добычи
 * и противников, а модифицировать нечего.
 */
export function eventAt(day: number, node: number, t: number): EventId | null {
  const window = Math.floor(shiftAt(t) / EVENT_WINDOW_SHIFTS);
  return eventFor(hash(SEED, day, node, window, 4));
}

/** Дельта игрока: единственное, что попадает в сохранение. */
export interface Visit {
  readonly node: number;
  /** Номер смены, а не секунда: богатство считается сменами. */
  readonly shift: number;
}

export interface ClanState {
  readonly level: number;
  readonly nodes: readonly number[];
}

/**
 * Стоянка: клан держит точку три смены подряд — два часа. Число не выбрано,
 * а совпадает с `RICH_MAX` намеренно: за стоянку клан вырабатывает жилу
 * ровно до дна, и крест на карте после его отъезда — это дописанная фраза
 * «клан здесь работал», а не случайность. Прежде клан переезжал каждую
 * смену, и `npm run clans` называл это телепортом: средний прыжок —
 * полэкрана, 42% прыжков — дальше половины карты, оседлость 1,04 смены.
 */
export const CLAN_STAY = 3;

/**
 * Ярусный характер клана: где он работает, решает сид, а не день. Без него
 * все четыре флага вели себя одинаково — `npm run clans` показывал одну
 * и ту же гистограмму ярусов у всех кланов, и фракции, которые §4 велит
 * отличать, отличались только цветом. Соль своя, а не общий сид клана:
 * характер темпа (`pace`) живёт в `clanState`, и сцеплять два розыгрыша
 * порядком бросков — значит сломать один, поменяв другой.
 */
export const clanTier = (id: number): Tier =>
  Math.floor(mulberry32(hash(SEED, id, 5))() * 4) as Tier;

/** Расселение стоянки последнего спрошенного блока: `worldAt` спрашивает
 *  кланы девять смен подряд, и считать колоду заново на каждую незачем. */
let cachedSpots: { day: number; block: number; spots: readonly number[] } | null = null;

/**
 * Расселение всех кланов одной стоянки — одним расчётом, а не по клану.
 * Это и есть ответ на две дыры, которые мерил `npm run clans`: врозь кланы
 * садились вдвоём на одну точку (6,6% смен — второй флаг молча не рисовался)
 * и в 17,7% смен занимали прогулочную, где флага нет вовсе. Общая колода
 * вылазок раздаётся по одной, и обе дыры закрыты по построению.
 *
 * Очередь идёт по кругу от номера стоянки: ничья за ярус не достаётся
 * всегда одному и тому же клану.
 */
function clanSpots(day: number, block: number): readonly number[] {
  if (cachedSpots !== null && cachedSpots.day === day && cachedSpots.block === block) {
    return cachedSpots.spots;
  }
  const deck = regionAt(day).nodes.filter((n) => KIND[n.kind].raidable);
  const rng = mulberry32(hash(SEED, day, block, 7));
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const swap = deck[i]!;
    deck[i] = deck[j]!;
    deck[j] = swap;
  }
  const spots = new Array<number>(CLANS.length).fill(-1);
  for (let o = 0; o < CLANS.length; o++) {
    const k = (o + block) % CLANS.length;
    const want = clanTier(k);
    let best = -1;
    let bestGap = Infinity;
    for (let i = 0; i < deck.length; i++) {
      const gap = Math.abs(deck[i]!.tier - want);
      if (gap < bestGap) {
        bestGap = gap;
        best = i;
      }
    }
    if (best < 0) continue;
    spots[k] = deck[best]!.id;
    deck.splice(best, 1);
  }
  cachedSpots = { day, block, spots };
  return spots;
}

/**
 * Рост фракции без округления: единица плюс `log2` от возраста, темп — свой
 * у каждой (`pace`). Уровень (`clanState`) — это она же, срезанная до целого.
 *
 * Наружу выставлена ради силы (§30): на третий день мира все четыре фракции
 * стоят на шестом уровне, и таблица по силе, считанная от целого, показала
 * бы четыре одинаковые строки. Округлять дважды нельзя — округляет один
 * последний слой (§20.3.3), а сравнение идёт по неокруглённому.
 */
export function clanGrowth(id: number, t: number): number {
  const rng = mulberry32(hash(SEED, id));
  const pace = 0.7 + rng() * 0.6; // характер: медленный / жадный
  const age = Math.max(0, t - WORLD_EPOCH);
  return 1 + Math.log2(1 + (age / (90 * 60)) * pace);
}

/**
 * Состояние клана в момент наблюдения. Ни таймера, ни записи: характер
 * клана — из сида, уровень — из прошедших часов, занятая точка — из номера
 * стоянки.
 */
export function clanState(id: number, t: number): ClanState {
  const level = Math.floor(clanGrowth(id, t));
  const day = dayAt(t);
  if (regionAt(day).nodes.length === 0) return { level, nodes: [] };
  // Артбук предлагал «одну-две локации», и замер это отменил: вторая
  // локация у каждого клана занимает почти половину региона, и условие
  // «три богатых локации всегда доступны» рушится от одной сессии
  // (`world.rules.ts`). Клан держит одну.
  const block = Math.floor((shiftAt(t) - dayStartShift(day)) / CLAN_STAY);
  const node = clanSpots(day, block)[id] ?? -1;
  return { level, nodes: node < 0 ? [] : [node] };
}

export interface NodeState {
  /** 0…3 — сколько заходов в локации ещё осталось. */
  readonly rich: number;
  /** Клан, который работает здесь прямо сейчас; null — никого. */
  readonly clan: number | null;
  /**
   * Сколько чужих заходов съело здесь богатство за окно (§30.6) — живых
   * соседей, не фракций: фракция видна флагом, а живой сосед не виден
   * ничем и без этого числа выглядел бы порчей жилы из ниоткуда.
   *
   * Число, а не «кто»: имена и почты чужих игроков карте не нужны ни для
   * одного решения, а решение здесь ровно одно — идти или не идти.
   */
  readonly others: number;
  /** Смен до следующего восстановления; 0 — восстанавливать нечего. */
  readonly restShifts: number;
  /** Что здесь сегодня (§11.6); null — обычный день, и таких большинство. */
  readonly event: EventId | null;
}

/**
 * Весь регион в момент t. Богатство тратит любое посещение — чужое или
 * своё, — и восстанавливается покоем: конкуренция без единого удара по
 * чужому лагерю.
 *
 * Чужое посещение приходит третьим списком (§30.6) и остаётся **входом
 * функции, а не её памятью**: метки живых соседей лежат на сервере, читает
 * их `main`, а модуль как был чистой функцией сида и часов, так и остался —
 * иначе сервер (§6) не смог бы повторить тот же счёт и сверить результат.
 *
 * Окно упирается в начало суток: за границей дня стоял другой регион,
 * и его заходы к сегодняшним точкам отношения не имеют.
 */
export function worldAt(
  t: number,
  visits: readonly Visit[] = [],
  others: readonly Visit[] = [],
): NodeState[] {
  const day = dayAt(t);
  const region = regionAt(day);
  const now = shiftAt(t);
  const window = Math.max(1, Math.min(RICH_WINDOW, now - dayStartShift(day) + 1));

  const used: boolean[][] = region.nodes.map(() => new Array<boolean>(window).fill(false));
  const clan = new Array<number | null>(region.nodes.length).fill(null);
  for (let k = 0; k < CLANS.length; k++) {
    for (let s = 0; s < window; s++) {
      for (const node of clanState(k, (now - s) * SHIFT_SEC).nodes) {
        if (used[node] === undefined) continue;
        used[node]![s] = true;
        if (s === 0 && clan[node] === null) clan[node] = k;
      }
    }
  }
  for (const visit of visits) {
    const s = now - visit.shift;
    if (s >= 0 && s < window && used[visit.node] !== undefined) used[visit.node]![s] = true;
  }
  // Чужие заходы — тем же списком и тем же весом: §4 говорит «тратит его
  // любое посещение, чужое или своё», и разного веса у них быть не может,
  // иначе жила у соседа кончалась бы медленнее, чем у меня.
  //
  // Считаются они при этом отдельно (`seen`): смена, в которую сходили
  // и я, и сосед, стоит локации один заход, а не два, — но сказать про неё
  // «здесь были соседи» карточка обязана.
  const seen = new Array<number>(region.nodes.length).fill(0);
  for (const visit of others) {
    const s = now - visit.shift;
    if (s < 0 || s >= window || used[visit.node] === undefined) continue;
    used[visit.node]![s] = true;
    seen[visit.node]! += 1;
  }

  return region.nodes.map((_, i) => {
    // От старой смены к новой: −1 за заход, +1/3 за смену покоя.
    let v = RICH_MAX;
    for (let s = window - 1; s >= 0; s--) {
      v += used[i]![s] ? -1 : RICH_REST;
      v = Math.max(0, Math.min(RICH_MAX, v));
    }
    const rich = Math.round(v);
    // Сколько смен покоя до следующего целого — цифра, которую игрок
    // читает как «через сколько сюда снова стоит идти».
    const restShifts = rich >= RICH_MAX ? 0 : Math.max(1, Math.ceil((rich + 1 - v) / RICH_REST));
    const node = region.nodes[i]!;
    const event = KIND[node.kind].events ? eventAt(day, node.id, t) : null;
    return { rich, clan: clan[i]!, others: seen[i]!, restShifts, event };
  });
}

/**
 * Куда пускают первую вылазку (§16.2). Ровно одна точка: игрок на кадре `move`
 * не видел ни боя, ни ран, и «выбирай из двадцати» здесь не выбор, а рулетка.
 *
 * **Ранжирование, а не фильтр**, и это найдено замером: на 60 днях нашёлся
 * день, где идеального входа — нулевой ярус, полное богатство, никакого
 * клана — не существует вовсе. Фильтр в такой день вернул бы ничего и запер
 * игрока в лагере с единственной кнопкой, которая ничего не открывает.
 * Поэтому места сортируются, и первое место занимает лучшее из имеющихся.
 *
 * Порядок ключей — это порядок того, чем на первой вылазке можно пожертвовать:
 * ярусом нельзя (он и есть ставка, §11.2), богатством можно, компанией клана
 * тоже, а мягкое событие — приятный довесок, а не условие.
 */
export function firstRaidNode(day: number, t: number): number | null {
  const region = regionAt(day);
  const world = worldAt(t, []);
  const raids = region.nodes.filter((n) => KIND[n.kind].raidable);
  if (raids.length === 0) return null;
  const rank = (n: WorldNode): number => {
    const state = world[region.nodes.indexOf(n)];
    return (
      n.tier * 1000 -
      (state?.rich ?? 0) * 10 +
      (state?.clan === null ? 0 : 5) -
      (isGentle(state?.event ?? null) ? 1 : 0)
    );
  };
  return [...raids].sort((a, b) => rank(a) - rank(b))[0]!.id;
}

/**
 * Заходы прошлых суток не относятся ни к одной сегодняшней точке — регион
 * пересобран. Чистка при записи держит сохранение ограниченным по размеру,
 * сколько бы игрок ни играл.
 */
export const liveVisits = (visits: readonly Visit[], t: number): Visit[] =>
  visits.filter((v) => v.shift >= dayStartShift(dayAt(t)) && shiftAt(t) - v.shift < RICH_WINDOW);
