/**
 * Работа по клетке: замах, досягаемость и остаток секунд.
 *
 * Появился этот файл вторым источником, который платится временем. Первым
 * была вырубка (§13.3), и всё, кроме двух вещей, у неё оказалось не про лес:
 * герой подходит, встаёт, машет с постоянным шагом и на каждом замахе даёт
 * рендеру повод дрогнуть. Про лес там ровно два места — что стоит на клетке
 * и что ложится в рюкзак; их и оставили в `logging.ts`, а всё остальное
 * переехало сюда, чтобы валун (§13.4) не заводил вторую копию тех же
 * восьми секунд.
 *
 * Работник — не герой вылазки, а тот, у кого есть место и взгляд. Так
 * написано затем, что в лагере герой другой (`campWalk.ts`): у него ярусы
 * и настил вместо клеток вылазки, а замах обязан быть тем же самым.
 */
import type { Cell } from './types';

/**
 * Секунды на замах. Замах — это клип «удар» (§17.1), у которого удар
 * приходится на 0,583 с (`STRIKE` в `raidView.ts`), поэтому цифра задаёт
 * растяжение клипа, а не подбирается на глаз: 0,8 с — тот же клип
 * в 0,73 скорости, и инструмент от этого читается тяжелее клинка. Звук
 * стучит ровно на замахе, то есть в момент удара, — правило §17.3, общее
 * для боя, топора и кайла.
 */
export const SWING_SECONDS = 0.8;

/**
 * Досягаемость инструмента. Соседняя клетка вместе с диагональю (√2 ≈ 1,41):
 * герой встаёт туда, куда его привёл `nearestWalkable`, и требовать
 * от него ортогонального соседства значило бы отказывать по причине,
 * которой игрок не видит.
 */
export const WORK_REACH = 1.6;

/**
 * Почему работа не идёт. Причина, а не `false`: молчащий отказ читается
 * как поломка — то же правило, что у места под здание (`prologue.ts`).
 *
 * Список общий у топора и кайла, и слова в нём нарочно не лесные:
 * «здесь этим не занимаются», «того, по чему бить, больше нет», «далеко»,
 * «некуда класть». Что именно исчезло и куда его некуда класть, знает
 * тот, кто зовёт, — он же и объясняет это игроку словами.
 */
export type WorkBlock = 'ok' | 'off' | 'gone' | 'far' | 'bag';

/** Кто работает. Симуляции хватает места и взгляда — остальное её не касается. */
export interface Worker {
  x: number;
  z: number;
  /** Куда смотрит, в радианах. Работающий смотрит на то, по чему бьёт. */
  facing: number;
}

/** Начатая работа: клетка, остаток секунд и сделанные замахи. */
export interface Work {
  readonly cell: Cell;
  /** Секунд всего — по ним считается доля сделанного. */
  readonly total: number;
  /** Секунд до конца. */
  left: number;
  /** Сделано замахов — по ним рендер бьёт клипом, а звук стучит. */
  swings: number;
}

export const startWork = (cell: Cell, swings: number): Work => ({
  cell: { x: cell.x, z: cell.z },
  total: swings * SWING_SECONDS,
  left: swings * SWING_SECONDS,
  swings: 0,
});

/** Дотягивается ли работник до клетки. */
export const inReach = (worker: Worker, cell: Cell): boolean =>
  Math.hypot(worker.x - cell.x, worker.z - cell.z) <= WORK_REACH;

/** Доля сделанной работы, 0..1 — её и показывает кольцо на клетке. */
export const workProgress = (work: Work): number =>
  Math.max(0, Math.min(1, 1 - work.left / work.total));

export interface WorkStep {
  /** На этом тике случился замах. */
  readonly swing: boolean;
  /** Работа кончена: то, по чему били, поддалось. */
  readonly done: boolean;
  /** Работа прервана и почему; null — идёт или ещё идут к цели. */
  readonly stopped: WorkBlock | null;
}

const IDLE: WorkStep = { swing: false, done: false, stopped: null };

/**
 * Тик работы. Пока работник идёт к цели, время не тратится: работает тот,
 * кто дошёл, — иначе дерево падало бы от одного намерения.
 *
 * Причина отказа приходит готовой, а не считается здесь: что мешает рубке
 * и что мешает добыче — разные вопросы, и отвечают на них разные модули.
 * Здесь важно одно: «далеко» у идущего не отказ, а дорога.
 */
export function stepWork(
  worker: Worker,
  walking: boolean,
  work: Work,
  dt: number,
  block: WorkBlock,
): WorkStep {
  if (block === 'far') {
    // Работник ещё в дороге — ждём. Дошёл и всё равно не дотянулся (цель
    // в глухом углу) — работы не будет, и это надо сказать, а не молчать.
    return walking ? IDLE : { ...IDLE, stopped: 'far' };
  }
  if (block !== 'ok') return { ...IDLE, stopped: block };

  // Работник смотрит на то, по чему бьёт. Направление держит симуляция
  // по той же причине, что и в бою: рендер его сглаживает, но не выдумывает.
  worker.facing = Math.atan2(work.cell.x - worker.x, work.cell.z - worker.z);

  work.left -= dt;
  // Замах считается по удару, а не по началу движения: звук и дрожь цели
  // приходятся на момент, когда инструмент вошёл в неё (§17.3). Поэтому
  // первый стук слышен через `SWING_SECONDS` после начала работы,
  // а последний совпадает с концом.
  const swings = Math.min(
    Math.round(work.total / SWING_SECONDS),
    Math.floor((work.total - work.left) / SWING_SECONDS),
  );
  const swing = swings > work.swings;
  work.swings = Math.max(work.swings, swings);
  return { swing, done: work.left <= 0, stopped: null };
}
