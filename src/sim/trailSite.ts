/**
 * Лесная тропа — третья прогулка мировой карты (§4, §6.1.17). Как замок
 * и кладбище, это **место, по которому ходят**: ни добычи, ни противников
 * здесь нет, и это объявленное состояние, а не забытый шаг. Дальше на тропе
 * поселятся засады и охота — и поселятся отдельными записанными решениями,
 * а не молчаливым дополнением к этой прогулке.
 *
 * От двух первых прогулок тропа отличается формой, и форма здесь — решение.
 * Замок и кладбище — участки: их видно целиком с одного места, и весь смысл
 * захода — рассмотреть. Тропа **длинная**: ход в разы длиннее своей ширины,
 * дальний конец из начала не виден, и смысл захода — пройти. Это первая
 * локация, где «сколько ещё осталось» игрок чувствует ногами.
 *
 * Сетка локации при этом остаётся квадратной (`GameLocation.size` — одно
 * число, и весь код игры считает из него): прямоугольник **вырезан внутри
 * квадрата** — просека во всю длину, а всё вокруг неё глухой лес. Вводить
 * в `GameLocation` вторую сторону ради одной локации значило бы править
 * `grid.ts`, генератор копей и обе волны — цена не за форму, а за
 * представление формы, которого игрок не видит.
 *
 * Всё выводится из сида: длина хода, куда виляет спина, где грунт. Одна
 * и та же точка карты собирается одной и той же тропой весь день (§4).
 */
import { mulberry32, randInt, type Rng } from '../core/rng';
import { distanceField, idx } from './grid';
import type { Cell, GameLocation } from './types';

/** Толщина леса по краю локации: та же рамка, что у кладбища. */
export const WOOD = 3;

/**
 * Полуширина просеки: спина ±2 — открытых клеток пять. Уже — и два героя
 * не разойдутся с деревом, шире — и тропа станет поляной, вытянутой в нитку:
 * длина читается только рядом с теснотой.
 */
export const CLEAR_HALF = 2;

/** Полуширина грунта: спина ±1. По краю просеки остаётся травяная обочина —
 *  без неё грунт упирается прямо в стволы и читается дном оврага. */
export const DIRT_HALF = 1;

/**
 * Насколько спина уходит от осевой. Ограничен не ради красоты, а ради формы:
 * правило `trailSite.rules.ts` меряет, что ход длиннее своей ширины минимум
 * вдвое, и разброс спины входит в ширину. Прямая как линейка тропа при этом
 * тоже не выпадает: виляние — то, чем тропа отличается от коридора.
 */
export const MEANDER = 3;

/**
 * Длина хода в клетках. Нижняя граница — от обещания «длинная»: втрое длиннее
 * самого крупного участка кладбища и заведомо длиннее диагонали экрана —
 * дальний конец из начала не виден ни при каком зуме прогулок.
 */
export const LEN_MIN = 24;
export const LEN_MAX = 31;

export interface TrailSite {
  readonly loc: GameLocation;
  /**
   * Клетки утоптанного грунта. Рендеру они голая земля: трава на ходу
   * не растёт, и тропа читается цветом и вытоптанностью, а не подписью.
   */
  readonly path: readonly Cell[];
  /** Длина хода в клетках — от входа до дальнего конца. */
  readonly length: number;
}

/**
 * Тропа по сиду. Размер локации — от длины хода: ход и есть то, ради чего
 * локация существует, ровно как участок у кладбища.
 */
export function generateTrailSite(seed: number): TrailSite {
  const rng: Rng = mulberry32(seed);
  const length = LEN_MIN + randInt(rng, LEN_MAX - LEN_MIN + 1);
  const size = length + 2 * WOOD;
  const center = Math.floor(size / 2);

  /**
   * Спина хода — ломаная вдоль x. Шаг между соседними столбцами не больше
   * клетки: просеки соседних столбцов перекрываются на четыре клетки,
   * и связность хода верна по построению, а не по проверке.
   */
  const spine: number[] = [];
  let z = center + randInt(rng, MEANDER * 2 + 1) - MEANDER;
  for (let i = 0; i < length; i++) {
    spine.push(z);
    if (rng() < 0.4) {
      z += rng() < 0.5 ? -1 : 1;
      z = Math.max(center - MEANDER, Math.min(center + MEANDER, z));
    }
  }

  // Всё, что не просека, — глухой лес. Он же рамка локации: край карты
  // обязан оставаться стеной, и здесь эта стена деревья во всю глубину,
  // а не полоса по краю — сквозь лес тропы не срезают.
  const blocked = new Uint8Array(size * size).fill(1);
  const path: Cell[] = [];
  for (let i = 0; i < length; i++) {
    const x = WOOD + i;
    const s = spine[i]!;
    for (let dz = -CLEAR_HALF; dz <= CLEAR_HALF; dz++) {
      blocked[idx(size, x, s + dz)] = 0;
    }
    for (let dz = -DIRT_HALF; dz <= DIRT_HALF; dz++) path.push({ x, z: s + dz });
  }

  // Вход — ближний конец хода, на самом грунте. Дальний конец глухой:
  // тропа пока никуда не ведёт, и честнее упереть её в лес, чем нарисовать
  // выход, за которым ничего нет.
  const evac: Cell = { x: WOOD, z: spine[0]! };

  const loc: GameLocation = {
    seed,
    tier: 0,
    size,
    blocked,
    evac,
    // Прогулка (§4): ни добычи, ни валунов, ни противников — пока. Засады
    // и охота придут сюда своими решениями, а не пустыми массивами.
    containers: [],
    stones: [],
    enemies: [],
    backSteps: distanceField(size, blocked, evac),
  };
  return { loc, path, length };
}
