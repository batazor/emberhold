/**
 * §13.7 — содержание лагеря: что он тратит **сам**, без участия игрока.
 *
 * До этого модуля вся экономика была односторонней: ресурс приходил из
 * вылазки и уходил в постройку, то есть каждый расход был решением игрока.
 * Содержание — первый сток, который идёт по часам: жильцы едят, костры жгут
 * дерево, и происходит это, пока игрока нет.
 *
 * **Три забора, которые этот модуль не имеет права снести.**
 *
 * 1. §13.1 — нехватка ресурса **никогда не блокирует вход в вылазку**.
 *    Голод бьёт по работе жильцов, а не по герою: пустая кладовая означает,
 *    что лагерь ничего не наработал, а не что играть нельзя. Проверяется
 *    правилом, а не обещанием (`upkeep.rules.ts`).
 * 2. §24.1 — **ночь ничего не стоит**. Костёр жжёт дерево ровно одинаково
 *    днём и ночью; иначе это была бы та самая «цена костру», которую раздел
 *    отверг поимённо, и ночь стала бы гейтом по календарю.
 * 3. §6.1.15 — рутина видима, но не платит. Содержание считается тем же
 *    временем отлучки, что и работа (`WORK_SECONDS`), и тем же потолком
 *    (`WORK_CAP`): у прихода и расхода один клапан, иначе неделя без игры
 *    либо кормила бы даром, либо выедала лагерь до нуля.
 *
 * **Почему пища — отдельный ресурс, а не провиант.** Провиант (§11.9) —
 * это шкала одной вылазки: он восполняется бесплатно между заходами и по
 * §13.1 обязан восполняться. Пища — запас лагеря, и у неё ровно
 * противоположное свойство: она **убывает сама**. Свести их в одно число
 * значило бы либо сделать провиант платным (запрет §13.1), либо сделать
 * пищу бесплатной (тогда её незачем вводить).
 *
 * **Почему пища не выпадает в находках.** Ресурс, который сыплется из
 * вылазки, привязывает лагерь к вылазке ещё раз — а её и так связывают
 * четыре первых. Пищу приносит только жилец с приказом «Добывать пищу»
 * (`RESIDENT_WORK`), и отсюда единственный настоящий выбор между людьми:
 * добытчик не носит ни дерева, ни камня, но без него не работает никто.
 */
import { WORK_CAP, WORK_SECONDS, roofs } from './residents';
import type { CampState } from './camp';

/**
 * Сколько пищи съедает один рот за один рабочий такт (`WORK_SECONDS`).
 *
 * Треть, а не единица, и это главное число раздела: **один добытчик кормит
 * троих**. Единица означала бы, что каждый кормит только себя и лагерь
 * не растёт никогда; половина давала бы двоих и делала бы приглашение
 * жильца почти бессмысленным. При трети приглашённый окупается — но каждый
 * четвёртый рот требует нового добытчика, и это и есть цена роста.
 *
 * Число черновое до замера (`npm run upkeep`), как и всё в §20.3.
 */
export const FOOD_PER_MOUTH = 1 / 3;

/**
 * Сколько дерева сжигает один костёр за тот же такт.
 *
 * Столько же, сколько ест человек, и это выбрано намеренно: **костёр ест
 * как рот**. Так у декоративного до сих пор огня (§6.1.6.2) появляется
 * цена, которую можно назвать одним предложением, — и она не зависит
 * от времени суток (§24.1).
 */
export const FIRE_WOOD = 1 / 3;

/**
 * Кого считать ртом. **Только жильцов.**
 *
 * Героя здесь нет, и это не забывчивость: его еда — провиант вылазки (§11.9),
 * который по §13.1 обязан восполняться бесплатно. Посчитать его вторым ртом
 * значило бы взять с игрока за одно и то же дважды, а лагерь без единого
 * жильца объявить голодающим — то есть завести состояние, из которого
 * не выйти и в котором нечего решать.
 *
 * Бездомные едят наравне с прочими: крыша решает, работает ли человек
 * (§6.1.15), а не кормится ли он.
 */
export const mouths = (camp: CampState): number => camp.residents.length;

/** Сколько костров горит. Костры приходят с гостями замка (§6.1.6.2). */
export const firesOf = (camp: CampState): number => camp.fires?.length ?? 0;

/** Тактов содержания за отлучку. Тот же клапан, что у работы: недоеденное
 *  не копится ровно так же, как недоработанное. */
export const upkeepTicks = (awaySec: number): number =>
  Math.min(WORK_CAP, Math.floor(Math.max(0, awaySec) / WORK_SECONDS));

export interface UpkeepDue {
  readonly ticks: number;
  /** Сколько пищи полагается съесть за отлучку. */
  readonly food: number;
  /** Сколько дерева полагается сжечь. */
  readonly wood: number;
}

export function upkeepDue(camp: CampState, awaySec: number): UpkeepDue {
  const ticks = upkeepTicks(awaySec);
  return {
    ticks,
    food: ticks * mouths(camp) * FOOD_PER_MOUTH,
    wood: ticks * firesOf(camp) * FIRE_WOOD,
  };
}

export interface UpkeepReport {
  /** Сколько пищи вправду съедено. */
  readonly eaten: number;
  /** Сколько дерева вправду сожжено. */
  readonly burned: number;
  /**
   * Сколько ртов осталось голодными. Считается по недостаче, а не по людям:
   * половина пайка на весь лагерь — это половина лагеря голодна, и кто
   * именно, решает порядок списка, а не жребий.
   */
  readonly hungry: number;
  /** Погас ли хоть один костёр: дерева не хватило. */
  readonly dark: boolean;
}

/**
 * Списать содержание. Возвращает то, что вправду списано, — кладовая пуста
 * не по-разному, и «съедено 2 из 3» обязано читаться как недостача, а не
 * как долг: долгов лагерь не помнит (тот же довод, что у `workDone`).
 *
 * Порядок списания — сперва еда, потом костры. Он не безразличен: дерево
 * и пища разные ресурсы, но при пустой кладовой первым обязан спасаться
 * человек, а не огонь.
 */
export function payUpkeep(camp: CampState, awaySec: number): UpkeepReport {
  const due = upkeepDue(camp, awaySec);
  if (due.ticks === 0) return { eaten: 0, burned: 0, hungry: 0, dark: false };

  const eaten = Math.min(camp.resources.food, due.food);
  camp.resources.food = Math.max(0, camp.resources.food - eaten);

  const burned = Math.min(camp.resources.wood, due.wood);
  camp.resources.wood = Math.max(0, camp.resources.wood - burned);

  const short = Math.max(0, due.food - eaten);
  // Недостача переводится в рты: сколько пайков не выдано, столько человек
  // и голодны. Округление вверх — голодным считается и тот, кому не хватило
  // половины: половина пайка не работа.
  const hungry = Math.min(mouths(camp), Math.ceil(short / FOOD_PER_MOUTH));
  return { eaten, burned, hungry, dark: burned + 1e-9 < due.wood };
}

/**
 * Сколько жильцов вышло на работу после раздачи еды.
 *
 * Голодные не работают — это единственное последствие голода, и его хватает:
 * лагерь, забывший про пищу, перестаёт приносить дерево и камень, но играть
 * не мешает (§13.1). Голод считается с конца списка: первым ест тот, кто
 * пришёл раньше, — правило произвольное, но записанное, и оно детерминировано.
 */
export function workingAfter(camp: CampState, hungry: number): number {
  const roofed = Math.min(camp.residents.length, Math.max(0, roofs(camp) - 1));
  // Герой ест первым и работником не считается: он ходит в вылазки.
  return Math.max(0, roofed - hungry);
}
