/**
 * Кривая Кухни выведена моделью (§22), а не назначена: ярус k открывается
 * Кухней k+1, и запас на этом уровне обязан совпасть с модельным для яруса.
 * Отсюда 22 / 49 / 76 / 103 / 130 — прямая с шагом 27.
 *
 * **Слой округления (§20.3.3) сюда не кладётся, и это измерено.** Провиант —
 * первое число, которое игрок читает всю вылазку, и округлить его хотелось
 * сильнее прочих. Не вышло дважды: шаг 25 давал 50 на ярусе 0 при полном
 * обходе ровно в 50 — правило §12.2 завалило сборку, локацию стало можно
 * зачистить. Шаг 5 вниз давал 45 и стоил ярусу **четверти добычи** (4,7 → 3,5
 * по `npm run measure`): окно между «дойти до дна» и «обойти всё» на этом
 * ярусе уже пяти единиц, потому что щедрость там намеренно предельная.
 *
 * Вывод общий: округляется то, у чего есть запас. У Кухни его нет.
 */
export const kitchenFood = (level: number): number => modelKitchenFood(level);

/**
 * Вместимость Склада. Модель — прямая `11 + 4·ур`, поверх неё слой
 * округления (§20.3.3): 10 / 15 / 20 / 25 / 30 / 35 / 40.
 *
 * Здесь округление и понадобилось первым: 23 и 27 округляются оба в 25,
 * и без проверки «больше предыдущего» Склад ур. 3 и ур. 4 стали бы
 * неотличимы. Рюкзак — второе число, которое игрок читает всю вылазку,
 * и запаса у него, в отличие от провианта, хватает: гарантии §22.4
 * вместимость не сторожат, её сторожит связь λ.
 */
const STORAGE_CAPACITY = roundSeries(
  Array.from({ length: MAX_LEVEL + 1 }, (_, level) => 11 + 4 * level),
  5,
);

export const storageCapacity = (level: number): number =>
  STORAGE_CAPACITY[Math.max(0, Math.min(MAX_LEVEL, level))] ?? 11 + 4 * level;

/* ---------- кладовая (§13.6) ---------- */

/**
 * База кладовой. Шестой уровень зданий стоит ~160 разом: базы не хватает
 * намеренно — глубокая стройка требует сундуков. Черновое до перемера (§22.6).
 */
export const STORE_BASE = 60;

/** Прибавка к вместимости кладовой за каждый сундук (`chests.ts`). */
export const CHEST_BONUS = 30;

/** Вместимость кладовой: база плюс сундуки. Общий счёт, как у рюкзака. */
export const storeCapacity = (camp: CampState): number =>
  STORE_BASE + camp.chests.length * CHEST_BONUS;

/**
 * Занято в кладовой. **Пища (§13.7) не считается**, и это решение, а не
 * недосмотр: кладовая меряет добытое — то, что герой принёс на спине,
 * — а пища лежит в закромах и уходит сама. Посчитать её здесь значило бы
 * молча срезать четверть стартового места (запас 16 при потолке 60)
 * и наказать игрока за механику, которой он не управляет.
 */
export const storeUsed = (camp: CampState): number =>
  camp.resources.stone + camp.resources.wood + camp.resources.iron + camp.resources.crystal +
  (camp.resources.meat ?? 0) + (camp.resources.pelt ?? 0);

/** Свободно. Ноль и у переполненного старого сейва: перебор не отнимается. */
export const storeFree = (camp: CampState): number =>
  Math.max(0, storeCapacity(camp) - storeUsed(camp));

/**
 * Зачислить в кладовую сколько влезет. Единственный вход для притока извне:
 * добычи, работы жильцов, подарков и обмена. Возвращает, сколько
 * не поместилось, — ноль значит «влезло всё», и событие о потере не нужно.
 *
 * Возвраты своих денег — снос стены, отмена расходника — идут мимо потолка
 * намеренно: это не приток, а возврат того, что уже вмещалось.
 *
 * Порядок кинов — от дорогого к дешёвому: если место кончается на середине
 * зачисления, пропадать должен камень, а не кристалл, — иначе потолок
 * наказывает сильнее всего за самое трудное.
 */
export function stash(camp: CampState, from: Partial<Resources>): number {
  let free = storeFree(camp);
  let lost = 0;
  // Пища идёт мимо потолка: место в кладовой она не занимает (`storeUsed`),
  // и терять её на пороге было бы вдвойне странно — она и так убывает сама.
  camp.resources.food += from.food ?? 0;
  for (const kind of ['pelt', 'meat', 'crystal', 'iron', 'wood', 'stone'] as (keyof Resources)[]) {
    const amount = from[kind] ?? 0;
    if (amount <= 0) continue;
    const taken = Math.min(amount, free);
    camp.resources[kind] = (camp.resources[kind] ?? 0) + taken;
    free -= taken;
    lost += amount - taken;
  }
  return lost;
}

/**
 * Сколько из этого не влезет в кладовую. Тот же счёт, что делает `stash`,
 * но **до** зачисления: панели обязаны называть потерю заранее, а не сообщать
 * о ней после нажатия (§29.4).
 *
 * Считается суммой, а не по видам, ровно потому, что счёт кладовой один
 * (§13.6): что именно пропадёт при нехватке места, решает порядок `stash` —
 * от дорогого к дешёвому, — а сколько пропадёт, от порядка не зависит.
 *
 * Держит эти две функции вместе правило `chests.rules.ts`: предупреждение
 * обязано совпасть с потерей на любом наборе. Разойдись они — игра соврала бы
 * не в мелочи, а ровно в том, ради чего предупреждение и заведено.
 */
export function overflowOf(camp: CampState, from: Partial<Resources>): number {
  const asked = (Object.values(from) as number[]).reduce((sum, n) => sum + Math.max(0, n), 0);
  return Math.max(0, asked - storeFree(camp));
}

/** §20.4 — площадь растёт с Жильём: 6×6 на ур. 1 … 10×10 на ур. 5. */
