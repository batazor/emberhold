/** Минуты строкой для ценников зданий: «6 мин», «1 ч 30 мин». */
const minutes = (sec: number): string => {
  const m = Math.round(sec / 60);
  return m < 60 ? `${m} мин` : m % 60 === 0 ? `${m / 60} ч` : `${(m / 60) | 0} ч ${m % 60} мин`;
};

