/**
 * Знакомство у прогалины: поселенец, его имя и то, что он с собой принёс.
 *
 * **Зачем этот кадр вообще есть.** Редактор героя — это форма, а форма
 * до игры ломает два правила разом: ни одного экрана меню до того, как игрок
 * сыграл, и ни одного слова до того, как он сыграл (§16.1). Знакомство ни
 * одного из них не ломает: кто-то называет себя, и ответить своим именем
 * естественно. К этой минуте у игрока уже есть чем быть — он спустился,
 * вернулся и поставил лагерь, — и имя вешать есть на что.
 *
 * **Имена здесь — рабочие подписи, как и все прочие (§0.1).** Пул нарочно
 * невыразительный: за этими словами не стоит ни одного решения, лора у них
 * нет, и менять их можно строкой. Из того же пула берётся имя, подставленное
 * игроку, — игра предлагает ему имя из той же шапки, из которой достала имя
 * поселенца, и это единственная причина, по которой пул один.
 *
 * **Имя игрока — не решение, а идентификация**, и потому оно бесплатно
 * и ни на что не влияет. Всё, что игрок сообщает о себе сверх имени, обязано
 * что-то менять, иначе это тот самый выбор происхождения, который отвергнут
 * ровно за то, что не отвечал на вопрос «что это меняет в решении игрока».
 * Поэтому вопрос ровно один, и ответ на него решает две вещи: что поселенец
 * достанет из котомки сейчас и чем он будет занят в лагере потом
 * (`residents.ts`).
 */
import { mulberry32, pick, randInt } from '../core/rng';
import type { DwellerLook } from './garrison';
import { DWELLER_LOOKS } from './garrison';
import { RESOURCE_NAME, emptyResources } from './resources';
import type { ResourceKind, Resources } from './resources';

/**
 * Пул имён — рабочие подписи (§0.1). Ни одно из них ничего не значит
 * и ничего не объясняет; список существует затем, чтобы у человека в кадре
 * было имя, а у игрока — подставленное в поле. Переименование — правка
 * этой строки и ничего больше: имя лежит в `name` и не читается ни балансом,
 * ни генератором, ни сохранением.
 */
export const NAMES: readonly string[] = [
  'Астра',
  'Борш',
  'Вейн',
  'Гита',
  'Дарн',
  'Елка',
  'Живр',
  'Кайса',
  'Ларт',
  'Мила',
  'Нест',
  'Орса',
  'Пран',
  'Рика',
  'Сван',
  'Тула',
];

/** Что игрок отвечает на единственный вопрос о себе. */
export type SelfAnswer = 'строим' | 'ходим';

export const SELF_ANSWERS: readonly SelfAnswer[] = ['строим', 'ходим'];

/** Как ответ выглядит строкой. Подписи, а не решения (§0.1). */
export const SELF_LABEL: Record<SelfAnswer, string> = {
  строим: 'Строим лагерь',
  ходим: 'Ходим вниз',
};

/**
 * Что поселенец достаёт из котомки. Крохи, и это условие, а не скромность:
 * дар, который заметно двигает экономику, превратил бы знакомство в награду
 * за прохождение кадра, а кадр — в то, что проходят ради награды. Он должен
 * читаться как «человек отдал, что было», а не как выдача.
 *
 * Числа держатся ниже цены самого дешёвого здания (§20.3): дар не обязан
 * ничего закрывать, он обязан быть виден в полосе.
 */
export interface Gift {
  readonly resources: Resources;
  /** Вещи — подписи предметов, которые видно строкой. Механики за ними нет. */
  readonly things: readonly string[];
}

/**
 * Ответ выбирает **состав** дара, а не его размер: ресурсов в обоих ровно
 * три единицы, и это условие, а не совпадение — оно проверяется правилом.
 * Иначе один ответ стал бы правильным, и вопрос «кто ты» превратился бы
 * в вопрос «что выгоднее», то есть перестал бы быть вопросом о себе.
 *
 * **Вес ответа лежит не здесь.** Дерево против камня на трёх единицах
 * не решает ничего, и вещи механики не имеют вовсе — это подписи. Настоящее
 * последствие приходит вместе с жильцом: ответ выбирает, чем он занят
 * в лагере (`RESIDENT_WORK`). Дар остаётся тем, чем и был, — тем, что
 * человек отдал сразу.
 */
export const GIFT: Record<SelfAnswer, Gift> = {
  строим: { resources: { ...emptyResources(), wood: 2, stone: 1 }, things: ['Моток бечёвки'] },
  ходим: { resources: { ...emptyResources(), wood: 1, stone: 2 }, things: ['Сухарь', 'Нож'] },
};

/** Сколько единиц ресурса в даре: мерка, которой сравниваются ответы. */
export const giftWeight = (gift: Gift): number =>
  gift.resources.wood + gift.resources.stone + gift.resources.iron + gift.resources.crystal;

export interface Settler {
  readonly name: string;
  readonly look: DwellerLook;
  /**
   * Сид, из которого он выведен. Хранится вместе с ним, потому что лицо
   * (`ui/avatar.ts`) выводится из того же сида: без него человек, вошедший
   * в лагерь, получил бы там другое лицо, чем то, с которым сидел
   * на прогалине.
   */
  readonly seed: number;
  /** Имя, подставленное игроку в поле: принять тапом или поправить. */
  readonly offeredName: string;
}

/**
 * Поселенец выводится из сида, а не хранится: тот же сид даёт того же
 * человека, сколько раз ни зайди. То же свойство, на котором стоят жильцы
 * замка (§6.1.6.1) и вся генерация локаций (§12).
 *
 * Имя игроку подставляется из того же пула и обязано отличаться от имени
 * поселенца: два одинаковых имени в кадре из двух человек читались бы
 * ошибкой, а не совпадением.
 */
export function generateSettler(seed: number): Settler {
  const rng = mulberry32(seed);
  const name = pick(rng, NAMES);
  const look = pick(rng, DWELLER_LOOKS);
  const rest = NAMES.filter((n) => n !== name);
  return { name, look, seed, offeredName: rest[randInt(rng, rest.length)]! };
}

/** Шаги знакомства. Кадров три, и четвёртого не бывает. */
export type MeetStep =
  /** Он называет себя. */
  | 'он'
  /** Он спрашивает, кто ты: поле с подставленным именем. */
  | 'ты'
  /** Единственный вопрос о себе. */
  | 'вопрос'
  /** Он достаёт, что было, и ждёт, позовут ли. */
  | 'дар'
  | 'кончено';

export const MEET_ORDER: readonly MeetStep[] = ['он', 'ты', 'вопрос', 'дар', 'кончено'];

export interface MeetState {
  step: MeetStep;
  /** Имя героя. Пустым не бывает: поле открывается уже заполненным. */
  heroName: string;
  answer: SelfAnswer | null;
  /** Позвал ли игрок его с собой. */
  invited: boolean;
}

export const startMeet = (settler: Settler): MeetState => ({
  step: 'он',
  heroName: settler.offeredName,
  answer: null,
  invited: false,
});

/**
 * Шаг вперёд. Разговор двигается только вперёд и только по одному кадру:
 * возврат назад означал бы, что имя можно переписать, а значит поле надо
 * держать открытым — то есть завести форму, которой мы весь кадр
 * и избегаем.
 */
export function advance(state: MeetState): MeetStep {
  const at = MEET_ORDER.indexOf(state.step);
  state.step = MEET_ORDER[Math.min(at + 1, MEET_ORDER.length - 1)]!;
  return state.step;
}

/**
 * Имя героя. Пустое и пробельное отбрасывается — не запретом, а тем, что
 * поле возвращается к подставленному: тупика в кадре знакомства быть
 * не может, а «безымянный» это не решение игрока, а промах пальцем.
 *
 * Длина режется, потому что имя стоит строкой над головой и в листе отряда:
 * то, что не влезает, читается как сломанная вёрстка, а не как длинное имя.
 */
export const MAX_NAME = 14;

export function setHeroName(state: MeetState, raw: string, fallback: string): string {
  const clean = raw.trim().slice(0, MAX_NAME);
  state.heroName = clean === '' ? fallback : clean;
  return state.heroName;
}

export function answerSelf(state: MeetState, answer: SelfAnswer): Gift {
  state.answer = answer;
  return GIFT[answer];
}

/** Что вправду досталось: до ответа — ничего. */
export const giftOf = (state: MeetState): Gift | null =>
  state.answer === null ? null : GIFT[state.answer];

/**
 * Строка дара — именительный и число, как в лавке (`offerLine`, §13.5):
 * «Дерево 1 · Камень 2 · Сухарь». Порядок именно такой, а не «1 дерево»,
 * и это не стиль, а отказ от таблицы склонений: «1 дерево, 2 дерева,
 * 5 деревьев» пришлось бы держать на каждый ресурс и на каждую вещь,
 * и первая же новая вещь про эту таблицу забыла бы. Игра и так называет
 * ресурсы именительным везде, где их считает.
 */
export function giftLine(gift: Gift): string {
  const parts: string[] = [];
  const order: readonly ResourceKind[] = ['wood', 'stone', 'iron', 'crystal'];
  for (const kind of order) {
    const n = gift.resources[kind];
    if (n > 0) parts.push(`${RESOURCE_NAME[kind]} ${n}`);
  }
  parts.push(...gift.things);
  return parts.join(' · ');
}
