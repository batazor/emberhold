/**
 * §11.3 — **дно охраняется**: самое глубокое тело локации встаёт на её
 * последнюю клетку и получает эту прибавку к уровню.
 *
 * Число выведено перебором форм рычага (`npm run depth`), а не назначено.
 * Правило §11.3 требует, чтобы павшие были не мельче дошедших, а разрыв
 * держался на −19 п.п.: гибель распределялась по всей глубокой части ровно,
 * тогда как глубина дошедшего обрывается на его пределе. Прибор перебрал
 * линейный подъём уровня с глубиной, ступень, сужение полосы врагов
 * и стража; выправил разрыв только последний, и только поставленный
 * **на дно**, а не у самого глубокого из имеющихся тел: усиливать надо
 * встречу там, куда доходят не все.
 *
 * После перехода к сети комнат ранний воин оказался слишком жёстким в
 * обязательном проходе. Поэтому на ярусе 1 страж получает +1, а на нижних
 * ярусах остаётся +2: там больше маршрутов и достаточно места для манёвра.
 *
 * **На нулевом ярусе стража нет, и это решение, а не пропуск.** С прибавкой
 * он проваливался в 32% забегов против 18% у первого — лестница ярусов
 * ломалась, а её `npm run measure` защищает отдельным вердиктом. Ярус 0
 * обещан §15 как тот, что «учит, что бой дёшев»; страж на дне учил бы
 * обратному. Правило §11.3 там остаётся невыполненным осознанно: решения
 * «глубже или назад» на обучающем ярусе нет и не задумано.
 */
export const BOTTOM_GUARD_LEVELS: Record<Tier, number> = { 0: 0, 1: 1, 2: 2, 3: 2 };

/**
 * §15 — потолок числа противников на локацию.
 *
 * Живёт здесь, а не в генераторе, потому что состав набирает модель, и
 * потолок, стоящий после неё, был бы обрезанием готового ответа, а не
 * ограничением при наборе.
 *
 * **Смысл потолка пришлось уточнить, и это следствие замера.** Прежде он
 * значил «за пятым противником провал в бою становится нормой независимо
 * от характеристик». На шкале hp этот порог оказался разным у разных ярусов:
 * половину вылазок теряют на трёх противниках ярус 1, на пяти — ярус 2
 * и на семи — Дно. Плоское число такого смысла не несёт, и нести не может.
 *
 * Держать сложность стало кому и без него: цена присутствия теперь своя
 * у каждого яруса, и бюджет ран ограничивает состав там, где раньше
 * ошибался. Потолок остаётся тем, чем и был по-настоящему, — **пределом
 * читаемости**: локация, набранная телами до упора, перестаёт быть местом
 * с решением «обойти или пробиться» и становится коридором.
 */
export const MAX_ENEMIES = 8;

/**
 * Сколько врагов приходится на одну достижимую находку.
 *
 * Величина про плотность, а не про сложность: она отвечает, сколько тел
 * помещается на карте, не превращая её в толпу. Прежние 0,8 держали ярус 3
 * на трёх противниках при карте 20×20 — и держали жёстче бюджета: замер
 * поднимал ω с 0,33 до 4,6, а число врагов не менялось ни на одном ярусе.
 * Сложность настраивается бюджетом (ω), и плотность обязана быть выше него,
 * иначе рычаг модели не подключён. Верхнюю границу держит `MAX_ENEMIES`.
 */
export const ROOM_PER_FIND = 1.6;

/**
 * §11.3 — какая доля локации, считая от дна, отдана противникам.
 *
 * Ручка правила «провал приходит глубже середины локации». Находки
 * раскладывались по глубине с самого начала, а противники брались из всей
 * локации подряд — то есть с равной вероятностью вставали и у входа,
 * и провал приходил туда же. Чем меньше доля, тем дальше от входа первая
 * встреча и тем позже приходит провал.
 *
 * Про **где**, а не про **сколько**: плотность держит `ROOM_PER_FIND`,
 * сложность — бюджет ω, и эта доля не подменяет ни того, ни другого.
 *
 * Число подобрано `npm run measure` по его вердикту, а не назначено,
 * и меняется вместе с ним. Ноль невозможен по построению: `generate`
 * берёт не меньше одной клетки, иначе локация осталась бы без противников.
 */
export const ENEMY_DEPTH_SHARE: Record<Tier, number> = { 0: 0.1, 1: 0.35, 2: 0.27, 3: 0.28 };

/**
 * Доля заходов яруса 3 с золотым сундуком (§13.6). Меньше половины —
 * сундук обязан оставаться событием, а не строкой росписи; больше трети —
 * иначе за десять заходов его можно не встретить ни разу и не узнать,
 * что он бывает. Черновое до перемера (§22.6): у события пока нет
 * замерного вердикта, и первый же `npm run measure` с ним его получит.
 */
export const GOLD_CHEST_CHANCE = 0.4;

/* ---------- вход ---------- */

export interface TierSpec {
  /**
   * Какой это ярус. Поле не описывает сложность и потому стоит особняком:
   * оно нужно, чтобы модель взяла цену присутствия своей строкой таблицы,
   * а не чужой. Совпадение с ключом `TIER_SPEC` держит правило, а не память.
   */
  readonly tier: Tier;
  /** Сторона локации. Единственный источник геометрии. */
  readonly size: number;
  /** Сколько находок разложить. */
  readonly containers: number;
  /** Щедрость провианта, 0..1: 0 — едва хватает дойти до дна и вернуться,
   *  1 — почти хватает обойти всё. Главный регулятор напряжения. */
  readonly generosity: number;
  /** Связь рюкзака с добычей. 1 — оба ограничения связывают поровну,
   *  <1 — чаще упирается рюкзак, >1 — чаще провиант. */
  readonly capacityRatio: number;
  /** Доля ран героя, которую забирает средний забег. Задаёт состав врагов. */
  readonly woundBudget: number;
  /** Во сколько раз находка у дна ценнее находки у входа. */
  readonly depthValue: number;
  /** Доля добычи, теряемая при провале. */
  readonly risk: number;
  /** Базовая величина находки у входа. */
  readonly base: number;
}

export interface TierNumbers {
  readonly food: number;
  readonly capacity: number;
  readonly containers: number;
  readonly roster: readonly RaidEnemyKind[];
  readonly geometry: { depth: number; hop: number; deepAndBack: number; fullTour: number };
  readonly expected: { haul: number; reachable: number; woundsTaken: number };
  readonly checks: { deepReachable: boolean; fullTourImpossible: boolean; survivable: boolean };
}

/* ---------- вывод ---------- */

export function deriveTier(spec: TierSpec): TierNumbers {
  const depth = DEPTH_PER_N * spec.size;
  const hop = HOP_PER_N * spec.size;

  // Дойти до дна и вернуться: путь туда-обратно с крюком плюс вскрытие.
  const deepAndBack = 2 * depth * DETOUR + FOOD_COST.container;
  // Обойти всё: выход к дну, перегоны между находками, возврат.
  const fullTour = 2 * depth + (spec.containers - 1) * hop + spec.containers * FOOD_COST.container;

  // §12.2 — запас обязан лежать между этими границами. Нижняя со зазором 0.85,
  // иначе дно недостижимо; верхняя строгая, иначе локацию можно зачистить.
  const floor = deepAndBack / 0.85;
  const ceil = fullTour;
  const food = Math.round(floor + Math.max(0, Math.min(1, spec.generosity)) * Math.max(0, ceil - floor));

  // Сколько находок реально успеть: после дороги до дна остаток делится
  // на перегон плюс вскрытие.
  const reachable = Math.max(1, Math.min(spec.containers, Math.floor((food - 2 * depth * DETOUR) / (hop + FOOD_COST.container)) + 1));
  // Средняя ценность находки: кривая глубины линейна, среднее — в середине.
  const meanValue = spec.base * (1 + (spec.depthValue - 1) / 2);
  const haul = reachable * meanValue;

  // Рюкзак связывает ровно тогда, когда его вместимость сравнима с тем,
  // что позволяет унести провиант. Это и есть «оба ограничения живые».
  const capacity = Math.max(4, Math.round(haul * spec.capacityRatio));

  // Состав врагов. Раны и провиант набираются раздельно: воины и маги
  // до бюджета ран, простые скелеты — сколько нужно давления на провиант.
  // Бюджет считается ценой присутствия, а не дуэли: иначе непреследующий
  // маг съедает вдвое больше бюджета, чем стоит на деле.
  const woundPoints = spec.woundBudget * HERO_HP;
  const roster: RaidEnemyKind[] = [];
  let spent = 0;
  const price = ENCOUNTER_WOUND[spec.tier];
  const afford = (kind: RaidEnemyKind): boolean => spent + price[kind] <= woundPoints;
  const put = (kind: RaidEnemyKind): void => {
    roster.push(kind);
    spent += price[kind];
  };

  /**
   * §15 — у каждого яруса свой ведущий тип, и он **один**.
   *
   * Здесь стоял второй цикл, добиравший воинов до трёх, и он-то и сломал
   * лестницу: на ярусе 2 стояли три воина и ни одного скелета, все 168
   * провалов яруса были от воина, и ярус выходил тяжелее третьего —
   * 44% успеха против 69%. §15 ничего подобного не просит: воин там
   * «делает проход через комнату платным», то есть он один, а стаю водят
   * скелеты.
   *
   * Правило пережило смену шкалы и осталось верным по другой причине.
   * Оно выросло из того, что скелет и воин стоили поровну, и «дороже»
   * не значило «реже»; на шкале hp цены разошлись вдвое, и бюджет один
   * справился бы. Но роль ведущего задаёт раздел, а не арифметика:
   * бюджет ограничивает число, а не назначает смысл.
   */
  const lead: RaidEnemyKind | null =
    spec.size >= 18 ? 'mage' : spec.size >= 12 ? 'warrior' : null;
  if (lead !== null && afford(lead)) put(lead);

  /**
   * Скелеты набираются из бюджета, но ограничены и потолком.
   *
   * Абзац написан, когда скелет не стоил ран вовсе и ограничивал его один
   * потолок. На шкале hp он снова стоит — 2,98 очка, — и набирается опять
   * из бюджета. Уцелело от прежней редакции главное: **потолок нужен
   * независимо от цены**, потому что бюджет считает очки, а коридор
   * из дешёвых тел получается по числу.
   *
   * Потолков два, и оба названы разделами. `room` держит число сравнимым
   * с числом находок — иначе локация становится коридором из скелетов.
   * `MAX_ENEMIES` — §15, замером выведенный предел, за которым провал
   * в бою становится нормой независимо от характеристик.
   */
  const density = spec.tier === 3 ? 2.3 : ROOM_PER_FIND;
  const room = Math.min(MAX_ENEMIES, Math.max(1, Math.round(reachable * density)));
  while (roster.length < room && afford('minion')) put('minion');

  const woundsTaken = spent;

  return {
    food,
    capacity,
    containers: spec.containers,
    roster,
    geometry: {
      depth: +depth.toFixed(1),
      hop: +hop.toFixed(1),
      deepAndBack: Math.round(deepAndBack),
      fullTour: Math.round(fullTour),
    },
    expected: { haul: +haul.toFixed(1), reachable, woundsTaken: +woundsTaken.toFixed(2) },
    checks: {
      deepReachable: deepAndBack <= food * 0.85,
      fullTourImpossible: fullTour > food,
      // Забег обязан переживаться: если ожидаемые раны дотягивают до потолка,
      // провал становится не риском, а расписанием.
      survivable: woundsTaken < HERO_HP - 0.5,
    },
  };
}

/* ---------- теория игр: когда идти дальше ---------- */

/**
 * Правило остановки. Игрок продолжает, пока ожидаемая ценность продолжения
 * выше синицы в руке:
 *
 *   EV(идти) = (B + g)·(1 − p·ρ)      EV(уйти) = B
 *   идти, если  g > B·p·ρ / (1 − p·ρ)
 *
 * где B — уже собранное, g — ценность следующей находки, p — вероятность
 * не дойти, ρ — доля добычи, теряемая при провале.
 *
 * Отсюда условие живого решения: **точка безразличия обязана попадать внутрь
 * забега.** Если g всегда больше порога — игрок всегда идёт дальше, и решения
 * нет; если всегда меньше — он уходит сразу, и глубины нет. Ставка ρ и кривая
 * ценности μ связаны через это неравенство и не настраиваются порознь.
 */
export function shouldContinue(bag: number, gain: number, failChance: number, risk: number): boolean {
  const pr = failChance * risk;
  if (pr >= 1) return false;
  return gain > (bag * pr) / (1 - pr);
}

/** Сколько добычи в рюкзаке делает следующий шаг невыгодным. */
export function indifferenceBag(gain: number, failChance: number, risk: number): number {
  const pr = failChance * risk;
  if (pr <= 0) return Infinity;
  return (gain * (1 - pr)) / pr;
}

