/**
 * Базовая прогрессия лагеря: **во скольких успешных вылазках стоит уровень.**
 * Это единственное назначенное число в стоимости — та самая константа, которую
 * статья велит выбирать так, чтобы её нельзя было сломать расчётом. Лестница
 * взята из таблицы §20.3 («конец первой сессии», «второй день», «потолок»),
 * а не выведена: она описывает темп игры, а не следует из него.
 *
 * Лестница сдвинута на ступень против той, что таблица §20.3 называла
 * (1/2/3/5/7), и сдвиг не выбран, а измерен: **нижнюю границу первой ступени
 * задают три правила, которые уже были в коде** — сундук стоит 2 дерева,
 * палатка 5, кольцо стены 8 камня, и все трое обязаны быть дешевле второго
 * уровня здания. Одна вылазка не покрывает ни одного из них.
 *
 * Концы лестницы при этом сошлись со старой таблицей почти точно: уровень 2
 * стоил 11 и стоит 10, уровень 6 стоил 158 и стоит 160. Провисала середина —
 * старая цена уровня 3 составляла полторы вылазки против двух с третью
 * у соседнего снизу, то есть лестница шла назад.
 */
export const RAIDS_PER_LEVEL: Record<number, number> = { 2: 2, 3: 3, 4: 4, 5: 6, 6: 8 };

/**
 * Добыча успешной вылазки по ярусам. **Измерено**, а не выведено:
 * `npm run measure`, 300 вылазок на ярус, бот-осторожный. Это свойство
 * генератора и боя — меняются они, число перемеряют.
 *
 * Модельная `expected.haul` сюда не годится: она считает все достижимые
 * находки взятыми и расходится с прогоном до полутора раз. Цена уровня
 * измеряется в том, что игрок приносит, а не в том, что мог бы.
 */
export const TIER_HAUL: Record<Tier, number> = { 0: 7.4, 1: 11.9, 2: 17.0, 3: 20.5 };

/**
 * Ярус, на который игрок ходит, **пока копит** на уровень: гейт читается
 * от нынешнего уровня, а не от будущего. Списывать пару «уровень — ярус»
 * руками нельзя — на этом §22.8 уже потерял ярус.
 */
export function tierForLevel(level: number): Tier {
  let best: Tier = 0;
  for (const t of [0, 1, 2, 3] as Tier[]) {
    if (TIER_KITCHEN_GATE[t] <= level - 1) best = t;
  }
  return best;
}

/**
 * Стоимость уровня: сколько вылазок × что вылазка приносит, разложенное
 * по составу добычи того же яруса (`LOOT_SHARE`) и округлённое.
 *
 * Состав берётся из таблицы, по которой генератор раскладывает находки:
 * требовать дерево там, где его не выпадает, значило бы назначить цену,
 * которую нечем платить.
 */
export function deriveBuildCost(level: number): Partial<Resources> {
  const raids = RAIDS_PER_LEVEL[level];
  if (raids === undefined) return {};
  const tier = tierForLevel(level);
  const total = raids * TIER_HAUL[tier];
  const cost: Partial<Resources> = {};
  for (const [kind, share] of Object.entries(LOOT_SHARE[tier]) as [ResourceKind, number][]) {
    const amount = roundNice(total * share);
    if (amount > 0) cost[kind] = amount;
  }
  return cost;
}

