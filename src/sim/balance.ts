/* ---------- слой округления: числа, которые читает игрок (§20.3.3) ---------- */

/**
 * §22 выводит числа, а выведенные числа круглыми не бывают: 49 провианта,
 * 19 рюкзака, 23 камня. Округление — **последний слой между моделью и
 * экраном**, а не правка модели: модельное значение остаётся тем, что
 * проверяют гарантии §22.4, а игрок читает круглое.
 *
 * Приём и его страховка взяты вместе: округлять до кратного можно только
 * с проверкой, что округлённое по-прежнему больше предыдущего, — иначе
 * два соседних уровня сливаются в одно число и лестница исчезает.
 */
export const roundTo = (x: number, step: number): number =>
  Math.max(step, Math.round(x / step) * step);

/** Шаг округления растёт вместе с величиной: до десяти игрок считает
 *  поштучно, до полусотни — пятёрками, дальше — десятками. */
export const niceStep = (x: number): number => (x < 10 ? 1 : x < 50 ? 5 : 10);

export const roundNice = (x: number): number => roundTo(x, niceStep(x));

/**
 * Округление лестницы целиком. Если округлённое не переросло предыдущее,
 * оно поднимается на шаг: рюкзак 23 и 27 округляются оба в 25, и без этой
 * проверки Склад ур. 3 и ур. 4 стали бы неотличимы.
 */
export function roundSeries(
  values: readonly number[],
  step: number,
  /**
   * Куда округлять. `down` нужен там, где округление вверх ломает гарантию:
   * запас провианта 49 при полном обходе 50 округлился в 50, и локацию стало
   * можно зачистить — выбор «куда идти» исчезал (§22.4 `fullTourImpossible`).
   * Правило поймало это в первый же прогон, поэтому Кухня округляется вниз.
   */
  dir: 'nearest' | 'down' = 'nearest',
): number[] {
  const out: number[] = [];
  for (const v of values) {
    let r = dir === 'down' ? Math.max(step, Math.floor(v / step) * step) : roundTo(v, step);
    const prev = out[out.length - 1];
    if (prev !== undefined && r <= prev) r = prev + step;
    out.push(r);
  }
  return out;
}

