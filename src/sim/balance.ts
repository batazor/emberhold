/**
 * Цена присутствия врага в настоящей вылазке. Меряется `npm run encounter`:
 * предельная цена — прогон с одним врагом, ещё не тронутый насыщением.
 *
 * **Перемерено дважды: под пошаговый бой (§11.3) и под шкалу hp того же
 * раздела.** Ниже — второй замер, он же действующий; единица теперь очко
 * шкалы, а не рана, и сравнивать числа с прежними напрямую нельзя.
 *
 * - **Маг дороже всех.** К нему идти шесть гексов под выстрелами при ходе
 *   героя в три. Это не «сильный противник», это дистанция, которую нечем
 *   закрыть.
 * - **Воин вдвое дороже рядового**, а не вровень с ним. Ровно они стояли
 *   на прежней шкале, где целая рана была и минимумом, и потолком удара.
 * - **Скелет снова стоит.** Прежняя редакция записывала ему 0,00 и выводила
 *   отсюда, что скелетов нельзя набирать бюджетом. Вывод был верен на своей
 *   шкале: рана целая, скелет её не снимал, и «бесплатен» было буквальной
 *   правдой. На шкале hp его удар стоит трёх очков из двадцати, прибор даёт
 *   2,98, и бюджет снова его ограничивает.
 *
 * Что из прежней редакции остаётся в силе целиком: **потолок §15 всё равно
 * нужен**. Бюджет ограничивает цену, а не число тел на карте, и локация,
 * набранная дешёвыми противниками до упора, становится коридором из скелетов
 * независимо от того, сколько они стоят.
 *
 * **Цена своя у каждого яруса, и это не удобство таблицы, а замер.** Одним
 * числом она была до тех пор, пока прибор мерил её только на ярусе 2. Прогон
 * по всем четырём даёт разброс вдвое — скелет стоит 3,73 на Подступах и 1,85
 * на Дне, — и причина не в скелете: на карте 20×20 его встречают вдвое реже,
 * чем на 12×12. Цена присутствия зависит от геометрии яруса по определению,
 * и одно число для всех ярусов означало, что модель берёт с Дна плату
 * по расценкам яруса 2 за противников, которые там вдвое дешевле.
 *
 * Именно это и ломало лестницу: ярус 2 выходил тяжелее Дна, потому что
 * бюджет пускал туда столько же врагов, сколько на вдвое большую карту.
 */
/**
 * **Перемерено в третий раз — под уровни обеих сторон (§22.6).** Тела встают
 * уровнем яруса (`TIER_ENEMY_LEVEL`), ходит модельный герой яруса
 * (`TIER_HERO_LEVEL`): мерить Дно новичком значило бы снимать цену встречи,
 * которой в игре не бывает. Глубокие ярусы подешевели не по ошибке: рост
 * героя обгоняет рост тел, и то же привидение стоит герою Дна почти ничего —
 * поэтому бюджет там покупает больше тел, и лестницу держит число, а не
 * каждый удар.
 */
