/** Событий нет: нейтральный набор, с которым считаются все замеры. */
export const NO_EVENT: Omit<EventDef, 'id' | 'name' | 'line'> = {
  risk: 0,
  loot: 1,
  enemies: 1,
  vision: 0,
  step: 1,
};

/**
 * Сколько окон события помещается в сутки. Окно — часы, а не минуты
 * (`world.html`, кадр 06): «ни таймера обратного отсчёта под давлением,
 * ни „успей за 10 минут“». Событие обязано пережить сессию, чтобы решение
 * «пойду туда» не превращалось в гонку, и обязано смениться внутри суток,
 * чтобы карта не была расписанием.
 *
 * Число измерено, а не назначено — см. `events.rules.ts`.
 */
export const EVENT_WINDOW_SHIFTS = 9;

/**
 * Доля точек региона, на которых сегодня что-то происходит.
 *
 * Меньше — событие не встречается и правилом не становится; больше —
 * событием перестаёт быть, потому что событие это отклонение от обычного дня.
 * Верхнюю границу держит замер: `world.rules.ts` требует, чтобы в любой момент
 * оставалось не меньше трёх локаций с богатством ≥ 2, и событие, отпугивающее
 * игрока с точки, работает как её занятость.
 */
export const EVENT_SHARE = 0.25;

/**
 * Что выпало на этом сиде. `null` — обычный день на обычной точке, и таких
 * большинство.
 *
 * Первый бросок решает, есть ли событие вообще, второй — какое. Два броска,
 * а не один диапазон: доля событий и их состав меняются независимо, и одним
 * числом их пришлось бы двигать вместе.
 */
export function eventFor(seed: number): EventId | null {
  const a = ((seed >>> 0) % 1000) / 1000;
  if (a >= EVENT_SHARE) return null;
  const b = (seed >>> 10) % EVENT_ORDER.length;
  return EVENT_ORDER[b] ?? null;
}

/** Набор модификаторов события; для `null` — нейтральный. */
export const effectOf = (id: EventId | null): Omit<EventDef, 'id' | 'name' | 'line'> =>
  id === null ? NO_EVENT : EVENTS[id];

/**
 * Годится ли событие первой вылазке. Такое ровно одно — «Тихая ночь»:
 * §11.6 заводит её не ради баланса, а как «честный способ зайти без риска —
 * и как мягкий вход для новичка».
 *
 * Отдельная функция, а не проверка `=== 'quiet'` по месту: кадр `move`
 * спрашивает «куда можно первым», а не «где тихая ночь», и если мягких
 * событий станет два, спрашивать он будет то же самое.
 */
export const isGentle = (id: EventId | null): boolean => id === 'quiet';

