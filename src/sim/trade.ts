/**
 * Обмен у торговца (§13.5). Единственное место в игре, где один ресурс
 * превращается в другой.
 *
 * **Зачем.** Кадр `craft` открывает витрину ковки сразу после того, как игрок
 * поставил Мастерскую, — а первый предмет стоит 4 железа (§14), железо роняют
 * только ярусы 1–3 (§13), и ярус 1 в этот момент заперт Кухней (§22). Пока
 * гейт не был включён, это было невезением; теперь это расписание, и упор
 * гарантирован каждому.
 *
 * Вторая дыра — с другой стороны: §13.2 сам признаёт, что «камень сознательно
 * имеет слабые стоки». Камня 4,5 за вылазку нулевого яруса, и к концу дня он
 * лежит мёртвым грузом. Лавка забирает избыток и отдаёт дефицит.
 *
 * **Главный риск, из которого выведено всё остальное.** §13 про кристалл
 * говорит: «его нельзя получить иначе, кроме как рискнув; если он однажды
 * начнёт капать на мелких ярусах, игра лишится смысла спускаться». Железо
 * устроено так же уровнем ниже — оно и есть причина открывать ярус 1. Щедрая
 * лавка эту причину отменяет.
 *
 * Поэтому курс здесь **намеренно плохой**, и это не осторожность, а условие
 * существования системы: обмен обязан проигрывать вылазке. Ровно та же форма,
 * что у §13.3, где «рубка обязана проигрывать подбору на каждом сиде».
 *
 * **Запрета при этом нет.** Проект последовательно предпочитает плохую сделку
 * запрету: выработанная локация даёт ×0,4, а не закрывается (§4); обвал стоит
 * шагов, а не отменяет вход (§11.6). Лавка работает так же — менять можно
 * всегда, просто невыгодно, и решение остаётся у игрока.
 *
 * **Запас у лавки один — пища, и он не её.** Железо у торговца не кончается:
 * его в мире никто не добывает для него, и всякий счёт на нём был бы числом
 * назначенным. Пища же на прилавке — ровно та, что местные сняли с кустов
 * этого места (§13.8, `localsTook`): ягода, которую игрок не успел сорвать
 * рукой, лежит здесь и продаётся за камень.
 *
 * Завести этот счёт заставил замер, а не вкус. Файл сам требует от пищевой
 * строки «проигрывать своему добытчику», и на темпе жильца она проигрывает
 * (`npm run upkeep`, 1,5 рта против трёх) — а на темпе игрока обгоняет его
 * **в триста раз**: заход нулевого яруса длиной в двенадцать секунд несёт
 * 4,1 камня, то есть две пищи, и суточное содержание лагеря из шести ртов
 * окупается тридцатью пятью секундами вылазок. Требование было записано
 * и не держалось; прилавок — то, чем оно держится.
 *
 * **Счёт при этом не хранится.** Он считается формулой от сида и часов, как
 * весь мир §4: сколько местные унесли за сутки, столько на прилавке и лежит.
 * Хранится только выкупленное игроком — самоистекающим списком на день
 * (`BoughtLog`), тем же приёмом, что `camp.picks` у кустов.
 *
 * **Цена решения названа: лавка может оказаться пустой.** Каждый пятый день
 * местные не приносят ничего, и пищи в тот день не купить. Отказом после
 * дороги это не становится ровно потому, что счёт стоит **только на пище**:
 * железо — то, за чем в замок и ходят (§13.2, у камня слабые стоки), — есть
 * всегда, и §13.1 не задет ни разу.
 *
 * Модуль чистый, как `consumables.ts`: ни DOM, ни состояния. Часы он знает
 * одни — длину суток, и та берётся у мира, а не назначается здесь.
 * Имена — рабочие подписи (§0.1).
 */
import { canAfford, spend } from './resources';
import type { ResourceKind, Resources } from './resources';
import type { CampState } from './camp';
import { storeCapacity, storeUsed } from './camp';
import { DAY_SEC } from './world';

export type OfferId = 'iron-stone' | 'iron-wood' | 'food-stone';

export const OFFER_ORDER: readonly OfferId[] = ['iron-stone', 'iron-wood', 'food-stone'];

export interface Offer {
  readonly id: OfferId;
  /** Что игрок отдаёт. */
  readonly give: Partial<Resources>;
  /** Что получает. */
  readonly take: Partial<Resources>;
}

/**
 * Курс. Числа измерены (`scripts/trade.ts`), а не назначены, и держатся
 * на трёх критериях разом:
 *
 * 1. **Обмен проигрывает вылазке на ярус 1** по железу за минуту. Замер:
 *    вылазка даёт 4,93 железа в минуту, восьмикамённый обмен — 2,58, вдвое
 *    меньше. Иначе ярус 1 не нужен, и §13 рушится.
 * 2. **Один обмен стоит не дороже двух с половиной заходов.** Дороже — лавкой
 *    не пользуется никто, и всё равно что её нет.
 * 3. **Обмен не отодвигает Кухню ур. 2 больше чем на два захода.** Кухня
 *    открывает ярус 1, то есть настоящее железо; лавка, тормозящая её,
 *    работает против себя.
 *
 * Прежде здесь стоял четвёртый критерий — «первая ковка достижима, пока ярус 1
 * закрыт», — и инструмент его снял. Окно, в котором ярус 1 заперт, длиной
 * в два захода (Кухня ур. 2 копится за две вылазки и четыре минуты), и курс,
 * успевающий в него, обязан давать железо быстрее вылазки, то есть ломать
 * §13. Критерии оказались несовместимы по построению. Кадр `craft` чинится
 * таймингом кадра, а не курсом.
 *
 * **Дерево покупает лучше камня**, и это не поблажка, а §13: дерево — «ранний
 * ограничитель темпа», его два за заход, и оно всё уходит в постройки; камня
 * четыре, и §13.2 сам признаёт, что стоки у него слабые. Дороже то, чего
 * меньше. Дровяная строка при этом единственная, что прошла критерии, —
 * на четырёх деревьях за железо Кухня отодвигается ровно на свою цену.
 *
 * **Оговорка замера, которую надо помнить.** Бот валунов не бьёт (§13.4),
 * а живой игрок бьёт: у него камня больше, чем в этих числах, и лавка для него
 * мягче измеренной. Перемерить курс — работа для телеметрии, а не для догадки:
 * событие `trade` пишется ровно затем, чтобы стало видно, ходят ли к торговцу
 * чаще, чем на ярус 1.
 *
 * Восемь камня выбраны из четырёх прошедших (5, 6, 7, 8) как самый дорогой:
 * лавка обязана читаться плохой сделкой. Заодно это тот же порядок, что
 * у расходников (8, 9, 10 камня, §21.6), где цена «примерно полторы вылазки»
 * уже отмерена — обе системы тратят один и тот же избыточный камень.
 */
/**
 * Паритет — курс, к которому приходят отношения. Числа прежние, измеренные
 * (`scripts/trade.ts`, три критерия): 8 камня или 3 дерева за железо. Это
 * лучшая цена лавки, и она по-прежнему проигрывает вылазке — условие
 * существования системы (§13) не сдвинулось ни на число.
 */
export const PARITY: Record<OfferId, Offer> = {
  'iron-stone': { id: 'iron-stone', give: { stone: 8 }, take: { iron: 1 } },
  'iron-wood': { id: 'iron-wood', give: { wood: 3 }, take: { iron: 1 } },
  /**
   * §13.7 — пища за камень. Третий обмен появился вместе с содержанием
   * и решает ровно одну задачу: **у камня наконец есть постоянный сток.**
   * §13.2 прямо называет его слабым местом — камень копится и обесценивается;
   * теперь его можно проесть.
   *
   * Курс выведен по той же линейке, что и два первых: единица пищи стоит
   * как две единицы камня (`VALUE`). Дороже делать нельзя — обмен обязан
   * проигрывать своему добытчику, иначе жилец с приказом «Добывать пищу»
   * теряет смысл, а вместе с ним и выбор между людьми.
   */
  // Пайком, а не поштучно: единица пищи стоит двух камней по линейке
  // `VALUE`, но обмен обязан стоить заходов, а не мелочи (`trade.rules.ts`),
  // иначе лавка раздаёт подарки. Тройка — суточный паёк трёх жильцов.
  'food-stone': { id: 'food-stone', give: { stone: 6 }, take: { food: 3 } },
};

/**
 * Наценка продавца. Незнакомому — четверть сверху, каждая сделка снимает
 * по пять сотых: после пятой лавка выходит на паритет. Отношения — это
 * сделки, а не разговоры: торговец верит рукам.
 *
 * Наценка в пользу продавца всегда: отрицательной она не бывает, и обмен
 * не может стать щедрее паритета — иначе критерии §13 рушатся втихую.
 */
export const feeOf = (deals: number): number =>
  Math.max(0, 0.25 - 0.05 * Math.max(0, Math.floor(deals)));

/** Сколько сделок осталось до паритета — интерфейсу, чтобы называть прогресс. */
export const dealsToParity = (deals: number): number =>
  Math.max(0, Math.ceil(0.25 / 0.05) - Math.max(0, Math.floor(deals)));

/** Курс с наценкой: цена округляется вверх — в пользу продавца. */
export function offerOf(id: OfferId, deals: number): Offer {
  const base = PARITY[id];
  const fee = feeOf(deals);
  const give: Partial<Resources> = {};
  for (const [kind, amount] of Object.entries(base.give) as [ResourceKind, number][]) {
    give[kind] = Math.ceil(amount * (1 + fee));
  }
  return { id, give, take: base.take };
}

/**
 * Ценность единицы — общая линейка сделки. Выведена из паритета, а не
 * назначена: 8 камня = 3 дерева = 1 железо, наименьшие целые — 3, 8, 24.
 * Кристалл линейки не имеет намеренно: он не продаётся и не принимается
 * (§13 — «нельзя получить иначе, кроме как рискнув»).
 */
export const VALUE: Partial<Record<ResourceKind, number>> = {
  stone: 3, wood: 8, iron: 24, food: 6, meat: 8, pelt: 24,
};

/** Что игрок может класть на прилавок. Железа здесь нет: обратного курса нет. */
export const GIVABLE: readonly ResourceKind[] = ['stone', 'wood', 'meat', 'pelt'];

/** Чем торгует торговец. */
export const SELLABLE: readonly ResourceKind[] = ['iron', 'food'];

/** Ценность кучки — по линейке; чего нет в линейке, то не считается. */
export const worthOf = (part: Partial<Resources>): number =>
  (Object.entries(part) as [ResourceKind, number][])
    .reduce((sum, [kind, n]) => sum + (VALUE[kind] ?? 0) * n, 0);

/** Во что торговец оценивает свою сторону: ценность плюс наценка, вверх. */
export const askOf = (take: Partial<Resources>, deals: number): number =>
  Math.ceil(worthOf(take) * (1 + feeOf(deals)));

/* ---------- прилавок: счёт, которого нет в сохранении ---------- */

/**
 * Что лежит на прилавке. Вид, которого в счёте нет, **не кончается** —
 * это не «ноль», а «без счёта»: железо у торговца бесконечно, и отличать
 * его от распроданной пищи обязан тип, а не соглашение о нуле.
 */
export type Stock = Partial<Resources>;

/** Виды, у которых счёт есть. Один — пища; почему только он, см. шапку. */
export const STOCKED: readonly ResourceKind[] = ['food'];

/**
 * Что игрок уже выкупил с прилавка. Ключ — место и сутки, значение — сколько
 * пищи унесено. Список **самоистекающий**, как `camp.picks` у кустов (§13.8):
 * записи прошлых суток вычищаются первым же обращением, поэтому в покое он
 * пуст, а при активной игре в нём столько чисел, сколько замков обошли
 * за день, — то есть не больше трёх (§4, `NODE_KINDS`).
 */
export type BoughtLog = Record<string, number>;

/** Сутки торговли: тот же день, что у подарка за вход (§29). */
export const tradeDay = (now: number): number => Math.floor(now / DAY_SEC);

/** Ключ прилавка: место и сутки. Место — сид площадки, торговцев столько же. */
export const marketKey = (seed: number, now: number): string => `${seed}:${tradeDay(now)}`;

/** Выбросить вчерашнее. Возвращает новый список — как `prunePicks`. */
export function pruneBought(log: BoughtLog, now: number): BoughtLog {
  const day = tradeDay(now);
  const kept: BoughtLog = {};
  for (const [key, n] of Object.entries(log)) {
    if (key.endsWith(`:${day}`)) kept[key] = n;
  }
  return kept;
}

/**
 * Что осталось на прилавке: принесённое местными минус выкупленное. Ноль
 * значит «сегодня всё разобрали», а не «лавка закрылась»: завтра местные
 * принесут снова, и того же считать не надо — считает формула.
 */
export function stockOf(supply: number, log: BoughtLog, seed: number, now: number): Stock {
  const gone = log[marketKey(seed, now)] ?? 0;
  return { food: Math.max(0, Math.floor(supply) - gone) };
}

/** Сколько этого вида на прилавке. `Infinity` — счёта нет. */
export const onCounter = (stock: Stock | null, kind: ResourceKind): number =>
  stock === null || stock[kind] === undefined ? Infinity : stock[kind];

/**
 * Почему сделка не состоится. 'cheap' — предложено меньше, чем просит
 * торговец: сделка всегда ровно или в его пользу, недоплаты не бывает.
 * 'full' — взятому нет места в кладовой (§13.6): обмен не режется потолком,
 * а отказывает целиком — терять купленное хуже, чем не купить.
 * 'stock' — на прилавке столько не лежит (§13.5): пищу приносят местные,
 * и больше принесённого не продаётся.
 */
export type DealBlock = 'ok' | 'empty' | 'resources' | 'cheap' | 'full' | 'stock';

/**
 * Отказы прилавка словами. Одна причина — одни слова — один файл (§23.3):
 * прежде единственная озвученная причина жила строкой в `main.ts`, и второй
 * её половины не было вовсе.
 */
export const DEAL_REASON: Record<Exclude<DealBlock, 'ok'>, string> = {
  empty: 'С прилавка ничего не взято',
  resources: 'В кладовой столько не наберётся',
  cheap: 'Торговцу этого мало',
  full: 'Кладовая полна — обмену нет места',
  stock: 'Столько пищи местные не принесли',
};

/** Кучка одним числом — для сверки с местом кладовой. */
const countOf = (part: Partial<Resources>): number =>
  Object.values(part).reduce((sum, n) => sum + (n ?? 0), 0);

export function dealBlock(
  camp: CampState,
  give: Partial<Resources>,
  take: Partial<Resources>,
  /** Прилавок. `null` — счёта нет вовсе: обмен между жителями, не лавка. */
  stock: Stock | null = null,
): DealBlock {
  if (worthOf(take) <= 0) return 'empty';
  // Прилавок читается раньше кошелька: пустая лавка — это про мир,
  // а не про игрока, и узнать о ней он должен до того, как считать камни.
  for (const [kind, amount] of Object.entries(take) as [ResourceKind, number][]) {
    if (amount > onCounter(stock, kind)) return 'stock';
  }
  if (!canAfford(camp.resources, give)) return 'resources';
  if (worthOf(give) < askOf(take, camp.trades ?? 0)) return 'cheap';
  // Отданное освобождает место в тот же миг: сверяется итог сделки.
  if (storeUsed(camp) - countOf(give) + countOf(take) > storeCapacity(camp)) return 'full';
  return 'ok';
}

/**
 * Сделка кучками — вход перетаскивания. Та же операция, что `trade`,
 * только стороны собирает игрок; переплата остаётся торговцу — прилавок
 * сдачи не даёт, и это в его пользу, как и наценка.
 */
export function makeDeal(
  camp: CampState,
  give: Partial<Resources>,
  take: Partial<Resources>,
  stock: Stock | null = null,
): boolean {
  if (dealBlock(camp, give, take, stock) !== 'ok') return false;
  spend(camp.resources, give);
  for (const [kind, amount] of Object.entries(take) as [ResourceKind, number][]) {
    camp.resources[kind] += amount;
  }
  camp.trades = (camp.trades ?? 0) + 1;
  return true;
}

/** Почему обменять нельзя. Причина, а не булево, — как везде (§20.3). */
export type TradeBlock = 'ok' | 'resources' | 'full' | 'stock';

export function tradeBlock(camp: CampState, id: OfferId, stock: Stock | null = null): TradeBlock {
  const offer = offerOf(id, camp.trades ?? 0);
  // Готовая пара считается тем же прилавком, что и свободная сделка:
  // два входа в одну систему обязаны отказывать одинаково.
  for (const [kind, amount] of Object.entries(offer.take) as [ResourceKind, number][]) {
    if (amount > onCounter(stock, kind)) return 'stock';
  }
  if (!canAfford(camp.resources, offer.give)) return 'resources';
  // То же правило, что у свободной сделки: взятому нужно место (§13.6).
  if (storeUsed(camp) - countOf(offer.give) + countOf(offer.take) > storeCapacity(camp)) {
    return 'full';
  }
  return 'ok';
}

/**
 * Обмен. Ровно один вход в систему, как у покупки расходника: обратной
 * операции нет и не будет.
 *
 * Продать железо обратно нельзя намеренно. Обратный курс превратил бы лавку
 * в качели, на которых можно ездить туда-сюда, а торговля в этом проекте
 * описана только как то, чего надо избегать: §21.3 боится, что экран возврата
 * станет «торговым автоматом, где нечего решать».
 *
 * Сделка двигает отношения: следующая цена ниже. Считаются только
 * состоявшиеся обмены — отказ по кошельку знакомством не является.
 */
export function trade(camp: CampState, id: OfferId, stock: Stock | null = null): boolean {
  if (tradeBlock(camp, id, stock) !== 'ok') return false;
  const offer = offerOf(id, camp.trades ?? 0);
  spend(camp.resources, offer.give);
  for (const [kind, amount] of Object.entries(offer.take) as [ResourceKind, number][]) {
    camp.resources[kind] += amount;
  }
  camp.trades = (camp.trades ?? 0) + 1;
  return true;
}

/** Строка курса для интерфейса: «Камень 10 → Железо 1» — по текущей наценке. */
export const offerLine = (
  id: OfferId,
  name: (kind: ResourceKind) => string,
  deals = 0,
): { give: string; take: string } => {
  const offer = offerOf(id, deals);
  const side = (part: Partial<Resources>): string =>
    (Object.entries(part) as [ResourceKind, number][])
      .map(([kind, amount]) => `${name(kind)} ${amount}`)
      .join(' · ');
  return { give: side(offer.give), take: side(offer.take) };
};
