/**
 * Правила разведения тел (`crowd.ts`). Проверяется не «красиво ли расходятся»,
 * а четыре обещания, на которые опираются все, кто этим пользуется:
 * разводит до ширины тела, неподвижного не двигает, в стену не толкает
 * и от вызова к вызову даёт одно и то же.
 *
 * Последнее — не педантизм: обход гарнизона и круг жильца объявлены чистыми
 * функциями времени, и разведение с памятью выбило бы из-под них опору.
 *
 * Запуск: npm run check
 */
import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { BODY, keepApart } from './crowd';

const dist = (a: { x: number; z: number }, b: { x: number; z: number }): number =>
  Math.hypot(a.x - b.x, a.z - b.z);

describe('Толпа: тела не проходят сквозь тела', () => {
  test('сошедшихся разводит на ширину тела', () => {
    const men = [
      { x: 5, z: 5 },
      { x: 5.1, z: 5 },
    ];
    keepApart(men);
    assert.ok(
      dist(men[0]!, men[1]!) >= BODY - 1e-9,
      `развело только на ${dist(men[0]!, men[1]!).toFixed(3)} при ${BODY}`,
    );
  });

  test('совпавших точка в точку тоже разводит', () => {
    // Направление тут вырождено, и без своего ответа на этот случай двое
    // остались бы стоять один в другом навсегда.
    const men = [
      { x: 3, z: 3 },
      { x: 3, z: 3 },
    ];
    keepApart(men);
    assert.ok(dist(men[0]!, men[1]!) >= BODY - 1e-9, 'совпавшие не разошлись');
  });

  test('троих в куче разводит всех, а не двоих', () => {
    const men = [
      { x: 10, z: 10 },
      { x: 10.05, z: 10.02 },
      { x: 9.98, z: 10.04 },
    ];
    keepApart(men);
    for (let i = 0; i < men.length; i++) {
      for (let j = i + 1; j < men.length; j++) {
        assert.ok(
          dist(men[i]!, men[j]!) >= BODY - 1e-9,
          `${i} и ${j} остались в ${dist(men[i]!, men[j]!).toFixed(3)}`,
        );
      }
    }
  });

  test('неподвижного не двигают, и всё расстояние отходит второму', () => {
    const men = [
      { x: 7, z: 7 },
      { x: 7.2, z: 7 },
    ];
    keepApart(men, { fixed: (i) => i === 0 });
    assert.deepEqual(men[0], { x: 7, z: 7 }, 'неподвижный сдвинулся');
    assert.ok(dist(men[0]!, men[1]!) >= BODY - 1e-9, 'подвижный не отошёл на своё');
  });

  test('в занятую точку не толкает: лучше перекрытие, чем человек в камне', () => {
    const men = [
      { x: 2, z: 2 },
      { x: 2.1, z: 2 },
    ];
    // Свободно только слева: значит, второй сдвинуться не может вовсе.
    keepApart(men, { free: (x) => x < 2.05 });
    assert.ok(men[1]!.x <= 2.1 + 1e-9, 'толкнуло в занятую точку');
  });

  test('сдвиг не больше половины клетки: из своих клеток никого не выносит', () => {
    // Худший случай: совпали точка в точку, и второй неподвижен — весь сдвиг
    // достаётся одному. Дальше половины клетки он всё равно не уедет.
    const men = [
      { x: 4, z: 4 },
      { x: 4, z: 4 },
    ];
    keepApart(men, { fixed: (i) => i === 0 });
    assert.ok(dist(men[0]!, men[1]!) < 0.5, `сдвинуло на ${dist(men[0]!, men[1]!).toFixed(3)}`);
  });

  test('далёких не трогает вовсе', () => {
    const men = [
      { x: 0, z: 0 },
      { x: 3, z: 4 },
    ];
    keepApart(men);
    assert.deepEqual(men, [
      { x: 0, z: 0 },
      { x: 3, z: 4 },
    ]);
  });

  test('от вызова к вызову — то же самое', () => {
    const make = (): { x: number; z: number }[] => [
      { x: 1, z: 1 },
      { x: 1, z: 1 },
      { x: 1.1, z: 0.95 },
    ];
    const a = make();
    const b = make();
    keepApart(a);
    keepApart(b);
    assert.deepEqual(a, b, 'кадр перестал быть функцией от входа');
  });
});
