/**
 * Время таймеров (DESIGN §6): по серверному при наличии сети, иначе локальное
 * с фиксацией дельты. Защита от перевода часов — монотонный счётчик: время
 * никогда не идёт назад, сколько бы игрок ни крутил системные часы.
 *
 * **Серверная половина подключена.** По таймерам идут стройка, лечение,
 * тренировка, отправка §26, восстановление локаций и колесо призов —
 * то есть системные часы клиента были ценой, которую он назначал себе сам.
 * Монотонный счётчик закрывал только перевод назад: перевод вперёд отдавал
 * готовую стройку и новую прокрутку колеса и выглядел при этом законно.
 *
 * Отметка сервера привязывается не к `Date.now()`, а к `performance.now()` —
 * счётчику, который идёт от загрузки страницы и системными часами
 * не управляется вовсе. Поэтому перевод часов **посреди сессии** не даёт
 * ничего: игра смотрит не на них. Спрошенное один раз время держится всю
 * сессию, а `resync` подтверждает его после сна вкладки, где монотонный
 * счётчик браузера ведёт себя по-разному.
 *
 * Без сети всё остаётся как было: локальные часы и та же защита от перевода
 * назад. Облако — источник правды, а не условие работы (§6).
 */
export class Clock {
  private lastSeen: number;
  /** Сдвиг, накопленный переводом часов назад. Только растёт. */
  private offset = 0;
  /**
   * Отметка сервера и показание монотонного счётчика в тот же миг.
   * null — сервера не спрашивали или он не ответил.
   */
  private anchor: { server: number; mono: number } | null = null;

  constructor(lastSeen = 0) {
    this.lastSeen = lastSeen;
  }

  /**
   * Принять отметку сервера (секунды эпохи). Зовётся на входе и после сна
   * вкладки; отказ сети сюда не доходит — там просто не зовут.
   */
  sync(server: number): void {
    if (!Number.isFinite(server) || server <= 0) return;
    this.anchor = { server, mono: performance.now() / 1000 };
  }

  /** Идёт ли время по серверному. Нужно показу и замерам, а не логике. */
  get synced(): boolean {
    return this.anchor !== null;
  }

  /** Секунды эпохи, монотонно неубывающие. */
  now(): number {
    const raw =
      this.anchor === null
        ? Date.now() / 1000 + this.offset
        : this.anchor.server + (performance.now() / 1000 - this.anchor.mono);
    if (raw < this.lastSeen) {
      // Часы уехали назад — компенсируем, а не доверяем им. При серверной
      // привязке сюда попадает только сейв из будущего (сохранён на другом
      // устройстве, чьи часы спешили): отматывать его назад нельзя — таймеры
      // лагеря считаны по нему, и стройка бы «раззавершилась».
      if (this.anchor === null) this.offset += this.lastSeen - raw;
      return this.lastSeen;
    }
    this.lastSeen = raw;
    return raw;
  }

  get watermark(): number {
    return this.lastSeen;
  }
}

export const formatDuration = (seconds: number): string => {
  const s = Math.max(0, Math.ceil(seconds));
  if (s >= 3600) {
    const h = Math.floor(s / 3600);
    const m = Math.round((s % 3600) / 60);
    return m > 0 ? `${h} ч ${m} мин` : `${h} ч`;
  }
  if (s >= 60) {
    const m = Math.floor(s / 60);
    const rest = s % 60;
    return rest > 0 ? `${m} мин ${rest} с` : `${m} мин`;
  }
  return `${s} с`;
};
