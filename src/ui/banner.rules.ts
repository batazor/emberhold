/**
 * Правила ленты сообщений лагеря.
 *
 * Проверять это глазами в браузере нечем: строка живёт четыре секунды,
 * и «показалась ли вторая после первой» — вопрос про время, а не про кадр.
 * Поэтому правило поведения вынесено из панели в чистый `banner.ts`
 * и проверяется здесь.
 *
 * Запуск: npm run check
 */
import assert from 'node:assert/strict';
import { describe, test } from 'node:test';
import { BANNER_SECONDS, Banner } from './banner';

/** Досидеть до конца строки: столько же, сколько её показывают. */
const waitOut = (b: Banner): void => b.tick(BANNER_SECONDS);

describe('Лента сообщений лагеря', () => {
  test('пачка из одного тика показывается целиком, а не последним', () => {
    // Ровно тот случай, ради которого лента и появилась: возврат из вылазки
    // объявляет рост героя и его рану одним тиком, ранен он почти всегда,
    // и присваивание в одно поле оставляло от пачки только рану.
    const b = new Banner();
    b.push('Рыцарь: уровень 4');
    b.push('Рыцарь ранен — в строю через 12 мин');
    assert.equal(b.text, 'Рыцарь: уровень 4', 'вторая строка стёрла первую');
    assert.equal(b.waiting, 1);

    waitOut(b);
    assert.equal(b.text, 'Рыцарь ранен — в строю через 12 мин', 'вторая строка не дождалась своей очереди');
    assert.equal(b.waiting, 0);
  });

  test('очередь опустела — возвращается текст покоя', () => {
    const b = new Banner();
    b.setSticky('Коснитесь земли, чтобы идти');
    assert.equal(b.text, 'Коснитесь земли, чтобы идти');

    b.push('Жильё: стройка началась');
    assert.equal(b.text, 'Жильё: стройка началась');
    waitOut(b);
    assert.equal(b.text, 'Коснитесь земли, чтобы идти', 'подсказка кадра не вернулась');
  });

  test('подсказка кадра ждёт под сообщением, а не поверх него', () => {
    // Подсказка ставится каждый тик, и без этого правила она затирала бы
    // любое сообщение на первом же кадре после его появления.
    const b = new Banner();
    b.push('Стены: выберите карточку');
    b.setSticky('Коснитесь земли, чтобы идти');
    assert.equal(b.text, 'Стены: выберите карточку');
    waitOut(b);
    assert.equal(b.text, 'Коснитесь земли, чтобы идти');
  });

  test('повтор продлевает строку, а не копит показы', () => {
    // Третий удар по валуну обязан держать «+3 · Камень» на экране. Копить
    // три показа подряд — двенадцать секунд одной строки — было бы хуже
    // и прежнего поведения.
    const b = new Banner();
    b.push('+3 · Камень');
    b.tick(BANNER_SECONDS * 0.75);
    b.push('+3 · Камень');
    assert.equal(b.waiting, 0, 'повтор встал в очередь');

    b.tick(BANNER_SECONDS * 0.75);
    assert.equal(b.text, '+3 · Камень', 'повтор не продлил строку');
    waitOut(b);
    assert.equal(b.text, '', 'строка не ушла после продления');
  });

  test('дубль в хвосте очереди — одно событие, а не два', () => {
    const b = new Banner();
    b.push('Жильё: стройка началась');
    b.push('Все герои заняты');
    b.push('Все герои заняты');
    assert.equal(b.waiting, 1);
  });

  test('порядок сохраняется на любой длине пачки', () => {
    const b = new Banner();
    const pack = ['Лучник принят в отряд', 'Бандит принят в отряд', 'Жильё готов'];
    for (const text of pack) b.push(text);
    for (const text of pack) {
      assert.equal(b.text, text, `порядок нарушен на «${text}»`);
      waitOut(b);
    }
    assert.equal(b.text, '');
  });
});
