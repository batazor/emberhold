/**
 * Лента сообщений лагеря — одна строка, через которую игра говорит игроку
 * всё, что случилось: стройка началась, герой вырос, действие не вышло.
 *
 * Вынесена из `campHud` отдельным файлом и без единого обращения к DOM,
 * потому что это правило поведения, а не разметка: какое сообщение видно
 * сейчас и что будет видно дальше. Панель остаётся тем, чем должна быть, —
 * местом, где текст кладут в элемент.
 *
 * **Почему очередь, а не поле.** События приходят пачкой в один тик. Возврат
 * из вылазки объявляет и то, что герой вырос, и то, что он ранен; лагерь
 * с достроенным Жильём объявляет и постройку, и принятого в отряд героя.
 * Присваивание в одно поле оставляло от пачки последнее, а ранен герой
 * почти всегда — так что уровень героя не показывался практически никогда,
 * при том что другой обратной связи по его росту в игре нет.
 *
 * **Текст покоя** — подсказка кадра онбординга. Она не спорит с сообщениями,
 * а ждёт под ними: сообщение живёт секунды, кадр живёт до следующего кадра.
 * Тот же приём, которым `Hud.setHint` держит подсказку в вылазке.
 */

/** Сколько секунд держится одна строка. */
export const BANNER_SECONDS = 4;

export class Banner {
  private readonly queue: string[] = [];
  /** Сколько секунд ещё держать нынешнюю строку. 0 — держим текст покоя. */
  private left = 0;
  private sticky = '';
  private shown = '';

  /** Что показывать сейчас. */
  get text(): string {
    return this.shown;
  }

  /** Ждёт ли что-то своей очереди. Наружу — ради проверок. */
  get waiting(): number {
    return this.queue.length;
  }

  /**
   * Текст покоя: подсказка кадра. Ставится каждый тик и потому не имеет
   * права перебивать сообщение — только занять экран, когда сообщений нет.
   */
  setSticky(text: string): void {
    this.sticky = text;
    if (this.left <= 0 && this.queue.length === 0) this.shown = text;
  }

  /** Сказать строку. */
  push(text: string): void {
    // То же самое, что висит сейчас, — продлевается, а не встаёт в очередь.
    // Так ведёт себя повторяющееся событие: третий удар по валуну обязан
    // держать «+3 · Камень» на экране, а не копить три показа подряд.
    if (this.left > 0 && this.shown === text) {
      this.left = BANNER_SECONDS;
      return;
    }
    // Дубль в хвосте очереди — это одно событие, записанное дважды.
    if (this.queue.at(-1) === text) return;
    this.queue.push(text);
    if (this.left <= 0) this.next();
  }

  /** Прошло `dt` секунд. */
  tick(dt: number): void {
    if (this.left <= 0) return;
    this.left -= dt;
    if (this.left <= 0) this.next();
  }

  /** Показать следующее из очереди; пусто — вернуться к тексту покоя. */
  private next(): void {
    const text = this.queue.shift();
    this.shown = text ?? this.sticky;
    this.left = text === undefined ? 0 : BANNER_SECONDS;
  }
}
