/**
 * Ветер от курсора. Трава расходится там, где ведут мышью: курсор считается
 * не телом, а источником воздуха — стоящий не приминает ничего, ведомый
 * гонит перед собой порыв.
 *
 * Почему источник, а не седьмой толчок в ряд к герою и врагам: толчок в
 * grass.ts — это присутствие, он держится, пока тело на месте. Курсор,
 * работающий так же, оставлял бы под собой постоянную вмятину — на экране
 * это читается как дырка в поле, а не как ветер. Порыв же берётся от
 * скорости и спадает сам, поэтому за курсором остаётся след, а брошенная
 * мышь поле не портит.
 *
 * Считается по кадрам, а не по событиям ввода: pointermove приходит пачкой
 * по несколько штук на кадр, и скорость, посчитанная между соседними
 * событиями, скачет от частоты опроса мыши, а не от руки. За кадр берётся
 * последняя точка — и скорость выходит та, которую видит глаз.
 *
 * Отдаётся наружу три величины, и делят они работу так: огибающая (сила)
 * и возраст живут здесь, а сама волна считается в шейдере. Причина в
 * масштабе: у травинки вылазки и у кустика заставки разный размер мира,
 * значит и длина волны у них разная, а вот рука у игрока одна.
 *
 * Три и DOM тут не нужны — значит, проверяется в Node (cursorWind.rules.ts).
 */

export interface Gust {
  /** Где порыв. Отстаёт от курсора: у воздуха есть инерция. */
  readonly x: number;
  readonly z: number;
  /** Куда дует: единичный вектор вдоль хода курсора. */
  readonly dirX: number;
  readonly dirZ: number;
  /** Огибающая, 0..1: сколько силы осталось. Знак отыгрыша — за волной. */
  readonly strength: number;
  /** Секунд с последнего подкрепления. По нему шейдер и гонит волну. */
  readonly age: number;
}

/** Скорость курсора по земле (клеток в секунду), на которой порыв полон. */
const FULL_SPEED = 10;

/** За столько секунд брошенный порыв слабеет в e раз. */
const RELEASE = 0.42;

/** Скачок курсора за кадр, который движением уже не считается. */
const JUMP = 6;

/** Ниже этого порыва нет: в шейдере он всё равно пойдёт нулём. */
const SILENT = 0.01;

/**
 * Насколько быстро точка ветра догоняет курсор (1/с). Это и есть инерция
 * воздуха: рука уже ушла, а порыв ещё тянется следом. Отставание держится
 * меньше полклетки — дальше это не инерция, а оторвавшийся от мыши ветер
 * (правило «точка ветра отстаёт от курсора»).
 */
const FOLLOW = 26;

/**
 * Класс сам себе Gust: поле обновляется каждый кадр, и заводить под это
 * объект — мусор на ровном месте (так же, как переиспользуемые слоты
 * толчка в raidView).
 */
export class CursorWind implements Gust {
  x = 0;
  z = 0;
  dirX = 0;
  dirZ = 0;
  strength = 0;
  age = 0;

  private aimX = 0;
  private aimZ = 0;
  private lastX = 0;
  private lastZ = 0;
  private aimed = false;
  /** Первая точка после появления курсора — ещё не движение, а место. */
  private seeded = false;

  /** Курсор на земле. Зовётся из ввода, сколько угодно раз за кадр. */
  point(x: number, z: number): void {
    this.aimX = x;
    this.aimZ = z;
    this.aimed = true;
  }

  /** Курсор ушёл с земли или из окна: порыв дожинается, но не растёт. */
  away(): void {
    this.aimed = false;
    this.seeded = false;
  }

  /** Раз в кадр. dt — секунды. */
  step(dt: number): void {
    if (dt <= 0) return;

    // Огибающая гаснет всегда; подкрепление ниже может её поднять и тогда
    // же обнулить возраст — волна пойдёт от свежего толчка.
    const faded = this.strength * Math.exp(-dt / RELEASE);
    let fresh = 0;

    if (this.aimed) {
      const dx = this.aimX - this.lastX;
      const dz = this.aimZ - this.lastZ;
      this.lastX = this.aimX;
      this.lastZ = this.aimZ;
      const dist = Math.hypot(dx, dz);

      // Курсор, перепрыгнувший пол-локации (возврат во вкладку, второй
      // экран), — не рука, а телепорт: считать это ураганом неоткуда.
      if (!this.seeded || dist > JUMP) {
        this.seeded = true;
        this.x = this.aimX;
        this.z = this.aimZ;
      } else {
        // Точка ветра догоняет курсор, а не прыгает в него: воздух тянется
        // следом за рукой, и след получается сплошным, а не пунктиром.
        const follow = Math.min(1, dt * FOLLOW);
        this.x += (this.aimX - this.x) * follow;
        this.z += (this.aimZ - this.z) * follow;

        if (dist > 1e-4) {
          // Направление сглаживается: рука дрожит на пиксель, а порыв от
          // этого не обязан вертеться.
          const k = Math.min(1, dt * 12);
          this.dirX += (dx / dist - this.dirX) * k;
          this.dirZ += (dz / dist - this.dirZ) * k;
          const len = Math.hypot(this.dirX, this.dirZ);
          if (len > 1e-4) {
            this.dirX /= len;
            this.dirZ /= len;
          }
        }
        fresh = Math.min(1, dist / dt / FULL_SPEED);
      }
    }

    // Резкая атака, мягкий отпуск. Возраст обнуляется только настоящим
    // толчком: иначе волна топталась бы на месте, пока мышь ползёт.
    if (fresh > faded) {
      this.strength = fresh;
      this.age = 0;
    } else {
      this.strength = faded;
      this.age += dt;
    }
  }

  /** Порыв или null, если ветра нет. */
  get gust(): Gust | null {
    return this.strength < SILENT ? null : this;
  }
}
