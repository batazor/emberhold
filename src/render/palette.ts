/**
 * Палитра набора — не второй список цветов, а порядок, в котором набор берёт
 * цвета из первого. Слот приходит из `.data.ts`, цвет ему назначается здесь,
 * и оба набора смотрят в одни и те же 28 цветов.
 */
function paletteOf(slots: readonly string[]): readonly number[] {
  return slots.map((name) => {
    const color = (MATERIAL as Record<string, number | undefined>)[name];
    if (color === undefined) throw new Error(`слота «${name}» нет среди 28 цветов артбука`);
    return color;
  });
}

/** Набор KayKit Forest (§6.1.1): растительность, земля и камень. */
export const FOREST_PALETTE = paletteOf(FOREST_SLOT_ORDER);

/** Набор KayKit Skeletons (§6.1.3): кость, сталь, сукно и свечение глаз. */
export const SKELETON_PALETTE = paletteOf(SKELETON_SLOT_ORDER);
