import { C, rgb } from './colors';

/**
 * DESIGN §6.1: единая палитра обязательна, но применяется к материалам,
 * а не ремапом картинок на сборке. Один список на игру.
 */
export const PALETTE = {
  night: 0x080b12,
  day: 0xa8bcc4,
  moon: 0x9fb6d8,
  sun: 0xffe7bd,
  torch: 0xffb166,
  groundHue: 0.12,
  grassBase: 0x2c3a1c,
  grassTip: 0x8fb45f,
  rock: 0x6a6355,
  heroBody: 0xdcd2b0,
  heroCloak: 0x8a3f2e,
  scavenger: 0x6b5340,
  spearman: 0x4b3852,
  golem: 0x55504a,
  telegraph: 0xd4543a,
  loot: 0xdba845,
  evac: 0x8fd6c0,
  backdrop: 0x141410,
} as const;

/**
 * Слоты готовых моделей (§6.1). Наборы KayKit раскрашены своими атласами;
 * `scripts/models.ts` при запекании меняет картинку на индекс, а цвет индексу
 * назначается здесь. Поэтому чужой набор перекрашивается правкой одной строки,
 * а палитра остаётся одним списком — им же красятся примитивы.
 *
 * Цвета берутся из `colors.ts` по имени, а не переписываются числами: список,
 * переписанный дважды, расходится молча — и однажды уже разошёлся.
 *
 * Порядок обязан совпадать с FOREST_SLOTS из forest.data.ts; проверяет forest.ts.
 * Имена — из палитры артбука (artbook.html), группы «Растительность»,
 * «Земля и дерево», «Камень и соль».
 */
export const FOREST_PALETTE: readonly number[] = [
  C.hvoT, C.hvo, C.moh, C.trav, // хвоя-тень, хвоя, мох, трава
  C.zem, C.derT, C.der, C.derS, // земля, дерево-тень, дерево, дерево-свет
  C.kam, C.kamS, C.skol, C.solT, // камень, камень-свет, скол, соль-тень
].map(rgb);

/**
 * Слоты набора персонажей (§6.1.3). Первые двенадцать — те же, что у леса,
 * и они здесь ссылкой, а не копией.
 *
 * Дальше идёт добавленное наборами. Золото и кожа взяты из игровой палитры:
 * цвет для них уже был (`loot` — добыча вылазки, `heroBody` — тело
 * героя-примитива), не было слотов. Сталь у артбука тоже была — ею покрашены
 * ноги примитивов, — но моделям она была недоступна: в двенадцать слотов леса
 * попало только тёплое. Сукно и кость артбук завёл ради этого набора.
 *
 * Порядок обязан совпадать с ADVENTURERS_SLOTS; проверяет adventurers.ts.
 */
export const ADVENTURERS_PALETTE: readonly number[] = [
  ...FOREST_PALETTE,
  PALETTE.loot, // золото
  PALETTE.heroBody, // кожа
  ...[C.metT, C.met, C.stal].map(rgb), // сталь-тень, сталь, сталь-свет
  ...[C.sukT, C.suk, C.sukS].map(rgb), // сукно-тень, сукно, сукно-свет
  rgb(C.kost), // кость
];
