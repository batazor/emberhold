/**
 * Палитра набора — не второй список цветов, а порядок, в котором набор берёт
 * цвета из первого. Слот приходит из `.data.ts`, цвет ему назначается здесь,
 * и все наборы смотрят в один и тот же список.
 */
function paletteOf(slots: readonly string[]): readonly number[] {
  return slots.map((name) => {
    const color = (MATERIAL as Record<string, number | undefined>)[name];
    if (color === undefined) throw new Error(`слота «${name}» нет среди 34 цветов артбука`);
    return color;
  });
}

