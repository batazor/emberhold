/**
 * LTV как интеграл удержания. Прибор написан под чужой метод — «Риск, ARPDAU
 * и LTV» (gdcuffs), — и отвечает на единственный вопрос: **что этот метод
 * скажет нам, когда игроки появятся, и чего он не скажет никогда.**
 *
 * Метод статьи в три строки: удержание приближается степенной кривой
 * `S(t) = a·t^b`, подогнанной по логарифмам; среднее время жизни — площадь
 * под ней, `LT = ∫S(t)dt`; `LTV = ARPDAU × LT`. Риск потерять дожившего
 * до дня `t` — `h(t) = −b/t`.
 *
 * Арифметика у нас уже была (§22.10): `powerFit`, `tailArea`, `powerArea`
 * в `src/core/survival.ts`. Поэтому прибор не пересчитывает статью — он
 * проверяет **три места, где метод ломается о собственные предположения**,
 * и все три видны без единого нашего игрока:
 *
 * 1. **Горизонт.** При `b = −0,34` интеграл до бесконечности расходится:
 *    подогнанная кривая обещает бессмертие. Число статьи конечно ровно
 *    потому, что она молча обрезала срок годом. Наш `tailArea` на этих
 *    параметрах возвращает `null` — то есть отказывается делать шаг,
 *    который статья делает не объявляя.
 *
 * 2. **Риск.** `h(t) = −b/t` падает как `1/t`, и это не деталь: между первым
 *    днём и полугодием риск отличается в сотни раз. Значит «удержание» без
 *    названного дня — не число, а два разных числа под одним словом.
 *
 * 3. **Шум подгонки.** Две недели наблюдений превращаются в год прогноза.
 *    Блок гоняет когорты разного размера, портит удержание биномиальным
 *    шумом наблюдения и смотрит, во сколько раз разъезжается `LT(год)`.
 *    Это и есть ответ на «сколько игроков нужно, чтобы метод что-то значил».
 *
 * Чего прибор не делает: не считает наш LTV. `ARPDAU` у нас не определён —
 * покупок за деньги в игре нет вовсе, — а `LT` требует заходов, которых
 * на момент написания три. Прибор меряет **метод**, а не игру; когда
 * заходы появятся, считать будет чем и менять здесь ничего не придётся.
 *
 * Запуск: npm run ltv
 */
import { mulberry32 } from '../src/core/rng';
import { powerArea, powerFit, tailArea } from '../src/core/survival';
import type { PowerFit } from '../src/core/survival';

/**
 * Кривая из статьи. Автор получил её по своим двум неделям и на ней же
 * напечатал LT: 27,62 дня за полугодие и 44,60 за год. Числа опубликованы,
 * поэтому годятся как чужой свидетель нашей арифметике — `survival.rules.ts`
 * проверяет совпадение, а здесь кривая работает эталоном, от которого
 * считается всё остальное.
 */
const ARTICLE: PowerFit = { a: 0.612, b: -0.34, r2: 1 };
/** Сколько дней автор наблюдал, прежде чем продлить кривую на год. */
const OBSERVED_DAYS = 14;

const pct = (x: number): string => `${(x * 100).toFixed(1)}%`;
const day = (x: number): string => x.toFixed(2);

/* ---------- 1. Горизонт ---------- */

/**
 * Срок — не деталь округления, а главный свободный параметр метода.
 * Блок печатает LT на разных сроках рядом, чтобы «LT = 44,6» никогда
 * не читалось как свойство игры: это свойство игры **и года**.
 */
function horizon(): void {
  console.log('1. Горизонт: LT за срок\n');
  console.log('  срок          LT, дней   к полугодию');
  const half = powerArea(ARTICLE, 1, 180)!;
  for (const [name, to] of [
    ['месяц', 30],
    ['квартал', 90],
    ['полгода', 180],
    ['год', 365],
    ['два года', 730],
    ['пять лет', 1825],
  ] as const) {
    const lt = powerArea(ARTICLE, 1, to)!;
    console.log(`  ${name.padEnd(12)}  ${day(lt).padStart(8)}   ×${(lt / half).toFixed(2)}`);
  }
  const forever = tailArea(ARTICLE, 1);
  console.log(`\n  бесконечность ${forever === null ? '  расходится' : day(forever)}`);
  console.log(
    `  b = ${ARTICLE.b} ≥ −1, поэтому ∫ до бесконечности не существует.\n` +
      '  Любое конечное LT здесь — следствие обрезки, а не свойство кривой.',
  );
}

/* ---------- 2. Риск ---------- */

/**
 * `h(t) = −b/t` — вероятность потерять того, кто дожил до дня `t`.
 * Проверяется не формула, а её следствие: во сколько раз риск первого дня
 * отличается от риска полугодия. Если разрыв велик, то одно слово
 * «удержание» покрывает несравнимые величины.
 */
function risk(): void {
  console.log('\n\n2. Риск потерять дожившего: h(t) = −b/t\n');
  console.log('  день    риск в день   S(t)');
  const h = (t: number): number => -ARTICLE.b / t;
  for (const t of [1, 3, 7, 14, 30, 90, 180, 365]) {
    const s = ARTICLE.a * t ** ARTICLE.b;
    const mark = t <= OBSERVED_DAYS ? '' : '   ← за краем данных';
    console.log(`  ${String(t).padStart(4)}   ${pct(h(t)).padStart(10)}   ${pct(s).padStart(6)}${mark}`);
  }
  console.log(
    `\n  Разрыв первого дня и полугодия: ×${(h(1) / h(180)).toFixed(0)}.\n` +
      '  «Удержание N%» без названного дня — не число: тот же b даёт\n' +
      '  и жестокий отсев на входе, и почти бессмертный хвост.',
  );
}

/* ---------- 3. Шум подгонки ---------- */

/** Нормальная величина из равномерной — Бокс—Мюллер, чтобы сид правил всем. */
function gauss(rnd: () => number): number {
  const u = Math.max(rnd(), 1e-12);
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * rnd());
}

/**
 * Одна наблюдённая когорта: `days` точек удержания, каждая испорчена шумом
 * измерения. Доля вернувшихся на день `t` — биномиальная величина с числом
 * испытаний `n`, и её разброс `√(p(1−p)/n)` при больших `n` нормален.
 * Приближение названо вслух намеренно: при `n` в десятки оно грубовато,
 * но ошибается в сторону оптимизма, то есть настоящий разброс не меньше
 * напечатанного.
 */
function observe(n: number, days: number, rnd: () => number): { x: number; y: number }[] {
  const points: { x: number; y: number }[] = [];
  for (let t = 1; t <= days; t += 1) {
    const p = ARTICLE.a * t ** ARTICLE.b;
    const sd = Math.sqrt((p * (1 - p)) / n);
    const y = Math.min(1, Math.max(1 / n, p + gauss(rnd) * sd));
    points.push({ x: t, y });
  }
  return points;
}

const quantile = (sorted: readonly number[], q: number): number =>
  sorted[Math.min(sorted.length - 1, Math.max(0, Math.round(q * (sorted.length - 1))))]!;

/**
 * Сколько игроков нужно, чтобы двухнедельная подгонка что-то значила
 * про год. Прогон повторяется по сидам: одна когорта — один сид,
 * воспроизводимо.
 */
function noise(): void {
  console.log('\n\n3. Шум: две недели наблюдения → год прогноза\n');
  const truth = powerArea(ARTICLE, 1, 365)!;
  console.log(`  Истинное LT(год) = ${day(truth)} дня. Подгонка по ${OBSERVED_DAYS} дням.\n`);
  console.log('  когорта   медиана   5–95%              вилка');
  const RUNS = 500;
  for (const n of [30, 100, 300, 1000, 3000, 10000]) {
    const got: number[] = [];
    for (let r = 0; r < RUNS; r += 1) {
      const fit = powerFit(observe(n, OBSERVED_DAYS, mulberry32(n * 7919 + r)));
      if (fit === null) continue;
      const lt = powerArea(fit, 1, 365);
      if (lt !== null && Number.isFinite(lt)) got.push(lt);
    }
    got.sort((a, b) => a - b);
    const [lo, mid, hi] = [quantile(got, 0.05), quantile(got, 0.5), quantile(got, 0.95)];
    const spread = (hi - lo) / mid;
    console.log(
      `  ${String(n).padStart(7)}   ${day(mid).padStart(7)}   ${day(lo).padStart(6)}–${day(hi).padEnd(7)}   ±${pct(spread / 2)}`,
    );
  }
  const half = powerArea(ARTICLE, 1, 180)!;
  console.log(
    `\n  Для сравнения: смена срока с полугодия на год двигает ответ\n` +
      `  на ${pct(truth / half - 1)} — больше, чем шум подгонки на когорте от сотни.\n` +
      '  Значит спорить о точности данных, не назвав срок, — спорить не о том.',
  );
}

