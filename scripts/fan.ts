/**
 * Замер веера (`features/fan`): какой радиус нужен дуге, чтобы столько-то
 * лиц встали вокруг большого пальца и не налезли друг на друга.
 *
 * Вопрос пришёл из разговора об управлении людьми: список аватаров, который
 * листают одной рукой. Отряд — это трое (§11.8), и трое влезают в любую дугу;
 * веер обсуждался как один контрол на **всех** людей лагеря, а жильцов
 * (`sim/residents.ts`) бывает десятки. Половину ответа считать не нужно —
 * она геометрическая, и вот она.
 *
 * Вторую половину — докуда вообще дотягивается палец — этот скрипт не знает
 * и не выдумывает: досягаемость зависит от экрана, ладони и хвата, и меряется
 * обводом в сцене `?веер`. Здесь считается только вместимость дуги.
 *
 * Запуск: npm run fan
 */
import { FITS, QUADRANT, TAP, minRadius, step } from '../src/features/fan';

const SIZES = [36, TAP, 52, 64, 72];
const FITTED = [3, 4, 5, 6, 8, 12];
const shape = (fits: number, size: number) => ({
  radius: 0,
  size,
  gap: 8,
  span: QUADRANT,
  hand: 'правая' as const,
  fits,
});

const deg = (rad: number): string => `${((rad * 180) / Math.PI).toFixed(1)}°`;

console.log('Потребный радиус дуги: чтобы столько слотов не налезли друг на друга\n');
console.log(`  мест   шаг${SIZES.map((s) => `слот ${s}`.padStart(9)).join('')}`);
for (const fits of FITTED) {
  const line = SIZES.map((size) =>
    `${Math.ceil(minRadius(shape(fits, size)))} px`.padStart(9),
  ).join('');
  console.log(`  ${String(fits).padStart(4)}  ${deg(step(shape(fits, TAP))).padStart(5)}${line}`);
}

const base = shape(FITS, TAP);
console.log(
  `\nПринято: ${FITS} места, шаг ${deg(step(base))}, слот ${TAP} px — ` +
    `дуге хватает радиуса ${Math.ceil(minRadius(base))} px.`,
);

console.log(
  '\nПочему число назначено, а не выведено. Раньше ёмкость считалась от радиуса:\n' +
    '  сколько влезет, столько и мест. Величина эта без дна — на радиусе 300\n' +
    '  их десять, только палец до десятого не достаёт, и упирается всё\n' +
    '  не в геометрию, а в руку. Поэтому мест четыре, радиус берётся из этой\n' +
    '  таблицы, а пятый человек приходит прокруткой.\n' +
    '  Докуда достаёт палец — меряется обводом в сцене ?веер, тут не считается.',
);
